def test_atomic_write_process_exit_before_replace_leaves_old_file(tmp_path):
    root = fake_root(tmp_path)
    target = root / "etc" / "atomic.env"
    target.write_bytes(b"old state\n")
    script = textwrap.dedent(
        """\
        import os, sys
        from pathlib import Path
        from cli_extended import hostendpoints as module
        root = Path(sys.argv[1])
        module.os.replace = lambda *args: os._exit(79)
        module._atomic_write(root, root / 'etc' / 'atomic.env', b'new state\\n', 0o644)
        """
    )
    env = dict(os.environ)
    env["PYTHONPATH"] = str(SOURCE)
