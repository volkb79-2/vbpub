def fake_root(tmp_path: Path, environment: bytes = b"") -> Path:
    root = tmp_path / "root"
    etc = root / "etc"
    (etc / "profile.d").mkdir(parents=True, exist_ok=True)
    (etc / "environment").write_bytes(environment)
    return root


def publish(root: Path, owner: str = "svc", entries=None, writer: str = "svc install 1.2.3"):
    if entries is None:
        entries = {"SVC_SOCKET": "/run/svc/sock"}
    endpoints.publish(owner, entries, writer=writer, root=root)


def test_publish_renders_fragment_aggregate_environment_and_profile_with_modes(tmp_path):
    root = fake_root(tmp_path, b"# keep this\nSITE_MODE=prod\n")

    publish(root)

    etc = root / "etc"
    fragment_dir = etc / "host-endpoints.d"
    fragment = fragment_dir / "svc.env"
    aggregate = etc / "host-endpoints.env"
    profile = etc / "profile.d" / "host-endpoints.sh"
    assert fragment.read_text() == (
        "# host-endpoints v1\n"
        "# owner=svc\n"
        "# writer=svc install 1.2.3\n"
        "SVC_SOCKET=/run/svc/sock\n"
    )
    assert aggregate.read_text() == (
        "# host-endpoints v1\n"
        "# owner=svc\n"
        "# writer=svc install 1.2.3\n"
        "SVC_SOCKET=/run/svc/sock\n"
    )
    environment = (etc / "environment").read_bytes()
    assert environment.startswith(b"# keep this\nSITE_MODE=prod\n")
    assert environment.endswith(
        b"# BEGIN host-endpoints (generated by cli_extended.hostendpoints; do not edit)\n"
        + aggregate.read_bytes()
        + b"# END host-endpoints\n"
    )
    assert profile.read_bytes() == endpoints._PROFILE
    assert stat.S_IMODE(fragment_dir.stat().st_mode) == 0o755
    assert stat.S_IMODE((fragment_dir / ".lock").stat().st_mode) == 0o600
    for path in (fragment, aggregate, etc / "environment", profile):
        assert stat.S_IMODE(path.stat().st_mode) == 0o644
    assert endpoints.check(root=root) == []


def test_publish_is_idempotent_and_replaces_only_its_owner(tmp_path):
    root = fake_root(tmp_path)
    publish(root)
    watched = [
        root / "etc" / "host-endpoints.d" / "svc.env",
        root / "etc" / "host-endpoints.env",
        root / "etc" / "environment",
        root / "etc" / "profile.d" / "host-endpoints.sh",
    ]
    before = [(path.read_bytes(), path.stat().st_mtime_ns) for path in watched]

    publish(root)
    after = [(path.read_bytes(), path.stat().st_mtime_ns) for path in watched]
    assert after == before

    publish(root, entries={"SVC_SOCKET": "/run/new.sock", "SVC_GID": "1234"})
    assert "SVC_SOCKET=/run/new.sock" in (root / "etc" / "host-endpoints.env").read_text()
    assert endpoints.check(root=root) == []


def test_withdraw_renders_remaining_fragments_and_removes_last_managed_block(tmp_path):
    root = fake_root(tmp_path, b"# administrator line\n")
    publish(root, owner="alpha", entries={"ALPHA_SOCKET": "/run/a.sock"})
    publish(root, owner="beta", entries={"BETA_SOCKET": "/run/b.sock"})

    endpoints.withdraw("alpha", root=root)

    aggregate = (root / "etc" / "host-endpoints.env").read_text()
    environment = (root / "etc" / "environment").read_text()
    assert "ALPHA_SOCKET" not in aggregate
    assert "BETA_SOCKET=/run/b.sock" in aggregate
    assert "# administrator line\n" in environment
    assert "ALPHA_SOCKET" not in environment
    assert endpoints.check(root=root) == []

    endpoints.withdraw("beta", root=root)
    assert (root / "etc" / "host-endpoints.env").read_text() == "# host-endpoints v1\n"
    assert (root / "etc" / "environment").read_text() == "# administrator line\n"
    assert endpoints.check(root=root) == []


