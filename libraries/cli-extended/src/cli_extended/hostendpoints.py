"""Publish host-owned endpoint facts as fragments and a shared environment file.

The record format is intentionally shell, pam_env, systemd EnvironmentFile,
and Docker env-file compatible. Runtime endpoint defaults belong to the
service that owns an endpoint; this module only publishes the facts it is
given.
"""

from __future__ import annotations

import errno
import fcntl
import os
import re
import stat
import sys
import tempfile
from collections.abc import Iterable, Iterator, Mapping, Sequence
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from .identity import CliIdentity, VersionLookupError
from .parser import CliFailure, CliRegistry, CliRuntime, OptionSpec, VerbSpec

_OWNER_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,63}")
_KEY_RE = re.compile(r"[A-Z][A-Z0-9_]{0,63}")
_VALUE_RE = re.compile(r"[A-Za-z0-9_./:@+-]{1,4096}")
_WRITER_TOKEN_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.:/+-]*")
_BEGIN = b"# BEGIN host-endpoints (generated by cli_extended.hostendpoints; do not edit)"
_END = b"# END host-endpoints"
_BEGIN_PREFIX = b"# BEGIN host-endpoints"
_END_PREFIX = b"# END host-endpoints"
_VERSION = b"# host-endpoints v1"
_PROFILE = (
    b"[ -r /etc/host-endpoints.env ] && { set -a; "
    b". /etc/host-endpoints.env; set +a; }\n"
)
_TEMP_PREFIX = ".host-endpoints-tmp-"
_DIR_MODE = 0o755
_FILE_MODE = 0o644
_LOCK_MODE = 0o600


@dataclass(frozen=True)
class _Fragment:
    owner: str
    writer: str
    entries: dict[str, str]


def _root_path(root: str | os.PathLike[str]) -> Path:
    """Return a lexical absolute fake-root path without following symlinks."""

    raw = os.fspath(root)
    if not isinstance(raw, str) or not raw:
        raise CliFailure("root must be a non-empty filesystem path", exit_code=2)
    path = Path(os.path.abspath(raw))
    try:
        mode = path.lstat().st_mode
    except FileNotFoundError as exc:
        raise CliFailure(f"root directory does not exist: {path}", exit_code=2) from exc
    if stat.S_ISLNK(mode):
        raise CliFailure(f"refusing symlinked root directory: {path}", exit_code=2)
    if not stat.S_ISDIR(mode):
        raise CliFailure(f"root is not a directory: {path}", exit_code=2)
    return path


def _path(root: Path, absolute: str) -> Path:
    return root / absolute.lstrip("/")


def _display(path: Path, root: Path) -> str:
    try:
        relative = path.relative_to(root)
    except ValueError:
        return str(path)
    return "/" + relative.as_posix()


def _safe_components(root: Path, path: Path) -> None:
    """Refuse symlinks in every managed path component below ``root``."""

    try:
        relative = path.relative_to(root)
    except ValueError as exc:
        raise CliFailure(f"managed path is outside root: {path}", exit_code=2) from exc
    cursor = root
    for index, part in enumerate(relative.parts):
        cursor = cursor / part
        try:
            mode = cursor.lstat().st_mode
        except FileNotFoundError:
            continue
        except NotADirectoryError as exc:
            raise CliFailure(
                f"managed directory is not a directory: {_display(cursor.parent, root)}",
                exit_code=2,
            ) from exc
        if stat.S_ISLNK(mode):
            raise CliFailure(
                f"refusing symlinked target: {_display(cursor, root)}", exit_code=2
            )
        if index < len(relative.parts) - 1 and not stat.S_ISDIR(mode):
            raise CliFailure(
                f"managed directory is not a directory: {_display(cursor, root)}",
                exit_code=2,
            )


def _regular_or_missing(root: Path, path: Path) -> os.stat_result | None:
    _safe_components(root, path)
    try:
        info = path.lstat()
    except FileNotFoundError:
        return None
    if not stat.S_ISREG(info.st_mode):
        raise CliFailure(
            f"managed target is not a regular file: {_display(path, root)}",
            exit_code=2,
        )
    return info


def _ensure_directory(root: Path, path: Path, *, mode: int | None = None) -> None:
    _safe_components(root, path)
    missing: list[Path] = []
    cursor = path
    while cursor != root:
        try:
            info = cursor.lstat()
        except FileNotFoundError:
            missing.append(cursor)
            cursor = cursor.parent
            continue
        if stat.S_ISLNK(info.st_mode):
            raise CliFailure(
                f"refusing symlinked target: {_display(cursor, root)}", exit_code=2
            )
        if not stat.S_ISDIR(info.st_mode):
            raise CliFailure(
                f"managed directory is not a directory: {_display(cursor, root)}",
                exit_code=2,
            )
        break
    for directory in reversed(missing):
        try:
            directory.mkdir(mode=mode or _DIR_MODE)
        except FileExistsError:
            pass
    _safe_components(root, path)
    if not stat.S_ISDIR(path.lstat().st_mode):
        raise CliFailure(
            f"managed directory is not a directory: {_display(path, root)}",
            exit_code=2,
        )
    if mode is not None:
        os.chmod(path, mode)


def _owner_problem(owner: object) -> str | None:
    if not isinstance(owner, str) or _OWNER_RE.fullmatch(owner) is None:
        return "owner must match [A-Za-z0-9][A-Za-z0-9_.-]{0,63}"
    return None


def _writer_problem(writer: object) -> str | None:
    if not isinstance(writer, str) or len(writer) > 256:
        return "writer must contain a verb and version on one line"
    words = writer.split(" ")
    if len(words) < 2 or any(_WRITER_TOKEN_RE.fullmatch(word) is None for word in words):
        return "writer must contain a verb and version on one line"
    return None


def _entries_map(entries: object) -> tuple[dict[str, str], list[str]]:
    problems: list[str] = []
    if isinstance(entries, Mapping):
        items: Iterable[object] = entries.items()
    elif isinstance(entries, Iterable) and not isinstance(entries, (str, bytes)):
        items = entries
    else:
        return {}, ["entries must be a mapping or an iterable of key/value pairs"]

    result: dict[str, str] = {}
    for index, item in enumerate(items, start=1):
        if isinstance(item, (str, bytes)):
            problems.append(f"entry {index} must be a key/value pair")
            continue
        try:
            pair = tuple(item)  # type: ignore[arg-type]
        except TypeError:
            problems.append(f"entry {index} must be a key/value pair")
            continue
        if len(pair) != 2:
            problems.append(f"entry {index} must contain exactly one key and value")
            continue
        key, value = pair
        if not isinstance(key, str) or _KEY_RE.fullmatch(key) is None:
            problems.append(f"entry {index} has an invalid key {key!r}")
            continue
        if not isinstance(value, str) or _VALUE_RE.fullmatch(value) is None:
            problems.append(f"entry {index} has an invalid value for {key}")
            continue
        if key in result:
            problems.append(f"entry {index} duplicates key {key}")
            continue
        result[key] = value
    if not result and not problems:
        problems.append("at least one endpoint entry is required")
    return result, problems


def _fragment_path(root: Path, owner: str) -> Path:
    return _path(root, f"/etc/host-endpoints.d/{owner}.env")


def _fragment_bytes(fragment: _Fragment) -> bytes:
    lines = [
        _VERSION.decode("ascii"),
        f"# owner={fragment.owner}",
        f"# writer={fragment.writer}",
    ]
    lines.extend(f"{key}={fragment.entries[key]}" for key in sorted(fragment.entries))
    return ("\n".join(lines) + "\n").encode("ascii")


def _aggregate_bytes(fragments: Mapping[str, _Fragment]) -> bytes:
    lines = [_VERSION.decode("ascii")]
    for owner in sorted(fragments):
        fragment = fragments[owner]
        lines.extend((f"# owner={owner}", f"# writer={fragment.writer}"))
        lines.extend(
            f"{key}={fragment.entries[key]}" for key in sorted(fragment.entries)
        )
    return ("\n".join(lines) + "\n").encode("ascii")


def _line_body(line: bytes) -> bytes:
    if line.endswith(b"\n"):
        line = line[:-1]
    if line.endswith(b"\r"):
        line = line[:-1]
    return line


def _environment_parts(data: bytes) -> tuple[bytes, bytes | None, list[str]]:
    """Return unmanaged bytes, generated payload, and marker defects."""

    lines = data.splitlines(keepends=True)
    begins: list[int] = []
    ends: list[int] = []
    problems: list[str] = []
    for index, line in enumerate(lines):
        body = _line_body(line)
        if body.startswith(_BEGIN_PREFIX):
            if body == _BEGIN:
                begins.append(index)
            else:
                problems.append("malformed BEGIN marker")
        if body.startswith(_END_PREFIX):
            if body == _END:
                ends.append(index)
            else:
                problems.append("malformed END marker")
    if len(begins) > 1:
        problems.append("more than one BEGIN marker")
    if len(ends) > 1:
        problems.append("more than one END marker")
    if ends and (not begins or ends[0] < begins[0]):
        problems.append("END marker before its BEGIN")
    if begins and not ends:
        problems.append("BEGIN marker without END")
    if ends and not begins:
        problems.append("END marker without BEGIN")
    if problems:
        return data, None, problems
    if not begins:
        return data, None, []
    begin = begins[0]
    end = ends[0]
    unmanaged = b"".join(lines[:begin] + lines[end + 1 :])
    payload = b"".join(lines[begin + 1 : end])
    return unmanaged, payload, []


def _outside_keys(unmanaged: bytes) -> set[str]:
    found: set[str] = set()
    for line in unmanaged.splitlines():
        match = re.match(rb"^([A-Z][A-Z0-9_]{0,63})=", line)
        if match is not None:
            found.add(match.group(1).decode("ascii"))
    return found


def _read_file(root: Path, path: Path) -> bytes | None:
    info = _regular_or_missing(root, path)
    if info is None:
        return None
    return path.read_bytes()


def _parse_fragment(root: Path, owner: str, path: Path) -> tuple[_Fragment | None, list[str]]:
    problems: list[str] = []
    try:
        data = _read_file(root, path)
    except (CliFailure, OSError) as exc:
        return None, [str(exc)]
    if data is None:
        return None, [f"missing fragment for owner {owner!r}: {_display(path, root)}"]
    try:
        lines = data.decode("ascii").splitlines()
    except UnicodeDecodeError:
        return None, [f"fragment for owner {owner!r} is not ASCII"]
    if len(lines) < 3 or lines[0].encode("ascii") != _VERSION:
        return None, [f"fragment for owner {owner!r} has an invalid header"]
    expected_owner = f"# owner={owner}"
    if lines[1] != expected_owner:
        problems.append(
            f"fragment {_display(path, root)} declares owner {lines[1]!r}, expected {owner!r}"
        )
    if not lines[2].startswith("# writer="):
        return None, problems + [f"fragment for owner {owner!r} has no writer header"]
    writer = lines[2][len("# writer=") :]
    writer_problem = _writer_problem(writer)
    if writer_problem is not None:
        problems.append(f"fragment for owner {owner!r}: {writer_problem}")
    entries: dict[str, str] = {}
    for number, line in enumerate(lines[3:], start=4):
        key, separator, value = line.partition("=")
        if not separator or _KEY_RE.fullmatch(key) is None:
            problems.append(
                f"fragment for owner {owner!r} has an invalid entry on line {number}"
            )
            continue
        if _VALUE_RE.fullmatch(value) is None:
            problems.append(
                f"fragment for owner {owner!r} has an invalid value for {key}"
            )
            continue
        if key in entries:
            problems.append(f"fragment for owner {owner!r} duplicates key {key}")
            continue
        entries[key] = value
    if not entries:
        problems.append(f"fragment for owner {owner!r} has no endpoint entries")
    fragment = _Fragment(owner=owner, writer=writer, entries=entries)
    if not problems and data != _fragment_bytes(fragment):
        problems.append(f"fragment for owner {owner!r} is not in canonical format")
    return (fragment if not problems else None), problems


def _load_fragments(root: Path, *, skip_owner: str | None = None) -> tuple[dict[str, _Fragment], list[str]]:
    directory = _path(root, "/etc/host-endpoints.d")
    try:
        _safe_components(root, directory)
        info = directory.lstat()
    except FileNotFoundError:
        return {}, []
    except CliFailure as exc:
        return {}, [str(exc)]
    if not stat.S_ISDIR(info.st_mode):
        return {}, [f"managed directory is not a directory: {_display(directory, root)}"]

    fragments: dict[str, _Fragment] = {}
    problems: list[str] = []
    try:
        children = sorted(directory.iterdir(), key=lambda child: child.name)
    except OSError as exc:
        return {}, [f"cannot read {_display(directory, root)}: {exc}"]
    for path in children:
        name = path.name
        if name == ".lock" or name.startswith(_TEMP_PREFIX):
            continue
        if not name.endswith(".env"):
            problems.append(f"unexpected entry in {_display(directory, root)}: {name}")
            continue
        owner = name[:-4]
        owner_problem = _owner_problem(owner)
        if owner_problem is not None:
            problems.append(f"invalid fragment filename {name!r}: {owner_problem}")
            continue
        if owner == skip_owner:
            try:
                _regular_or_missing(root, path)
            except CliFailure as exc:
                problems.append(str(exc))
            continue
        fragment, fragment_problems = _parse_fragment(root, owner, path)
        problems.extend(fragment_problems)
        if fragment is not None:
            fragments[owner] = fragment

    owners_by_key: dict[str, str] = {}
    for owner, fragment in fragments.items():
        for key in fragment.entries:
            previous = owners_by_key.setdefault(key, owner)
            if previous != owner:
                problems.append(_collision_problem(key, previous, owner, root))
    return fragments, problems


def _collision_problem(key: str, first: str, second: str, root: Path) -> str:
    first_path = _display(_fragment_path(root, first), root)
    second_path = _display(_fragment_path(root, second), root)
    return (
        f"key {key} is declared by both owner {first!r} ({first_path}) and "
        f"owner {second!r} ({second_path})"
    )


def _environment_state(root: Path) -> tuple[bytes, bytes | None, list[str]]:
    path = _path(root, "/etc/environment")
    try:
        data = _read_file(root, path)
    except (CliFailure, OSError) as exc:
        return b"", None, [str(exc)]
    if data is None:
        data = b""
    unmanaged, payload, problems = _environment_parts(data)
    return unmanaged, payload, problems


def _preflight_unlocked(
    root: Path,
    owner: str,
    entries: Mapping[str, str],
    *,
    allow_empty: bool = False,
) -> list[str]:
    problems: list[str] = []
    fragments, fragment_problems = _load_fragments(root, skip_owner=owner)
    problems.extend(fragment_problems)
    if not allow_empty and not entries:
        problems.append("at least one endpoint entry is required")
    prospective = dict(fragments)
    if entries:
        prospective[owner] = _Fragment(owner, "preflight 0", dict(entries))

    owners_by_key: dict[str, str] = {}
    for current_owner in sorted(prospective):
        for key in prospective[current_owner].entries:
            previous = owners_by_key.setdefault(key, current_owner)
            if previous != current_owner:
                collision = _collision_problem(key, previous, current_owner, root)
                if collision not in problems:
                    problems.append(collision)

    unmanaged, _payload, environment_problems = _environment_state(root)
    problems.extend(environment_problems)
    if not environment_problems:
        duplicates = sorted(_outside_keys(unmanaged) & set(owners_by_key))
        for key in duplicates:
            problems.append(
                f"{key} is already set outside the host-endpoints block in "
                f"{_display(_path(root, '/etc/environment'), root)}; remove the "
                "unmanaged assignment before publishing"
            )

    for target in (
        _path(root, "/etc/host-endpoints.env"),
        _path(root, "/etc/profile.d/host-endpoints.sh"),
    ):
        try:
            _regular_or_missing(root, target)
        except CliFailure as exc:
            problems.append(str(exc))
    return problems


def _format_problems(action: str, problems: Iterable[str]) -> str:
    lines = [f"{action} refused:"]
    lines.extend(f"- {problem}" for problem in problems)
    return "\n".join(lines)


def _fsync_directory(path: Path) -> None:
    flags = os.O_RDONLY | getattr(os, "O_DIRECTORY", 0)
    descriptor = os.open(path, flags)
    try:
        os.fsync(descriptor)
    finally:
        os.close(descriptor)


def _atomic_write(root: Path, path: Path, data: bytes, mode: int) -> bool:
    """Atomically replace a regular file and return whether bytes/mode changed."""

    info = _regular_or_missing(root, path)
    if info is not None and path.read_bytes() == data and stat.S_IMODE(info.st_mode) == mode:
        return False
    parent = path.parent
    _ensure_directory(root, parent)
    descriptor, temporary_name = tempfile.mkstemp(prefix=_TEMP_PREFIX, dir=parent)
    temporary = Path(temporary_name)
    try:
        os.fchmod(descriptor, mode)
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        _regular_or_missing(root, path)
        os.replace(temporary, path)
        _fsync_directory(parent)
    except BaseException:
        try:
            os.close(descriptor)
        except OSError:
            pass
        try:
            temporary.unlink()
        except FileNotFoundError:
            pass
        raise
    return True


@contextmanager
def _exclusive_lock(root: Path) -> Iterator[None]:
    directory = _path(root, "/etc/host-endpoints.d")
    lock_path = directory / ".lock"
    _regular_or_missing(root, lock_path)
    flags = os.O_RDWR | os.O_CREAT | getattr(os, "O_NOFOLLOW", 0)
    try:
        descriptor = os.open(lock_path, flags, _LOCK_MODE)
    except OSError as exc:
        if exc.errno == errno.ELOOP:
            raise CliFailure(
                f"refusing symlinked target: {_display(lock_path, root)}", exit_code=2
            ) from exc
        raise
    try:
        info = os.fstat(descriptor)
        if not stat.S_ISREG(info.st_mode):
            raise CliFailure(
                f"managed target is not a regular file: {_display(lock_path, root)}",
                exit_code=2,
            )
        os.fchmod(descriptor, _LOCK_MODE)
        fcntl.flock(descriptor, fcntl.LOCK_EX)
        yield
    finally:
        try:
            fcntl.flock(descriptor, fcntl.LOCK_UN)
        finally:
            os.close(descriptor)


def _ensure_publish_directories(root: Path) -> None:
    etc = _path(root, "/etc")
    endpoints = _path(root, "/etc/host-endpoints.d")
    profile = _path(root, "/etc/profile.d")
    _ensure_directory(root, etc)
    _ensure_directory(root, endpoints, mode=_DIR_MODE)
    _ensure_directory(root, profile)


def _render_environment(root: Path, aggregate: bytes, keys: set[str]) -> bytes:
    path = _path(root, "/etc/environment")
    current = _read_file(root, path)
    if current is None:
        current = b""
    unmanaged, _old_payload, problems = _environment_parts(current)
    if problems:
        raise CliFailure(_format_problems("environment block preflight", problems), exit_code=2)
    duplicates = sorted(_outside_keys(unmanaged) & keys)
    if duplicates:
        raise CliFailure(
            _format_problems(
                "environment block preflight",
                [
                    f"{key} is already set outside the host-endpoints block in "
                    f"{_display(path, root)}; remove the unmanaged assignment before publishing"
                    for key in duplicates
                ],
            ),
            exit_code=2,
        )
    if not keys:
        return unmanaged
    if unmanaged and not unmanaged.endswith(b"\n"):
        unmanaged += b"\n"
    return unmanaged + _BEGIN + b"\n" + aggregate + _END + b"\n"


def _target_symlink_problems(root: Path) -> list[str]:
    problems: list[str] = []
    for target in (
        _path(root, "/etc/host-endpoints.d"),
        _path(root, "/etc/host-endpoints.d/.lock"),
        _path(root, "/etc/host-endpoints.env"),
        _path(root, "/etc/environment"),
        _path(root, "/etc/profile.d"),
        _path(root, "/etc/profile.d/host-endpoints.sh"),
    ):
        try:
            _safe_components(root, target)
        except CliFailure as exc:
            if str(exc) not in problems:
                problems.append(str(exc))
    return problems


def plan(owner: str, entries: object, *, root: str | os.PathLike[str] = "/") -> list[str]:
    """Preflight entries, ownership collisions, environment markers and targets."""

    problems: list[str] = []
    owner_problem = _owner_problem(owner)
    if owner_problem is not None:
        problems.append(owner_problem)
    normalized, entry_problems = _entries_map(entries)
    problems.extend(entry_problems)
    try:
        root_path = _root_path(root)
    except CliFailure as exc:
        return problems + [str(exc)]
    problems.extend(_target_symlink_problems(root_path))
    if owner_problem is None:
        problems.extend(_preflight_unlocked(root_path, owner, normalized))
    return list(dict.fromkeys(problems))


def _publish_unlocked(root: Path, owner: str, writer: str, entries: dict[str, str]) -> None:
    problems = _preflight_unlocked(root, owner, entries)
    if problems:
        raise CliFailure(_format_problems("publish", problems), exit_code=2)

    fragments, fragment_problems = _load_fragments(root, skip_owner=owner)
    if fragment_problems:
        raise CliFailure(_format_problems("publish", fragment_problems), exit_code=2)
    fragments[owner] = _Fragment(owner=owner, writer=writer, entries=entries)
    aggregate = _aggregate_bytes(fragments)
    keys = {key for fragment in fragments.values() for key in fragment.entries}
    environment = _render_environment(root, aggregate, keys)

    _atomic_write(root, _fragment_path(root, owner), _fragment_bytes(fragments[owner]), _FILE_MODE)
    _atomic_write(root, _path(root, "/etc/host-endpoints.env"), aggregate, _FILE_MODE)
    _atomic_write(root, _path(root, "/etc/environment"), environment, _FILE_MODE)
    _atomic_write(root, _path(root, "/etc/profile.d/host-endpoints.sh"), _PROFILE, _FILE_MODE)


def publish(
    owner: str,
    entries: object,
    *,
    writer: str,
    root: str | os.PathLike[str] = "/",
) -> None:
    """Publish or replace one owner's fragment and atomically render host files."""

    owner_problem = _owner_problem(owner)
    writer_problem = _writer_problem(writer)
    normalized, entry_problems = _entries_map(entries)
    problems = [problem for problem in (owner_problem, writer_problem) if problem]
    problems.extend(entry_problems)
    if problems:
        raise CliFailure(_format_problems("publish", problems), exit_code=2)
    try:
        root_path = _root_path(root)
        _ensure_publish_directories(root_path)
        targets = _target_symlink_problems(root_path)
        if targets:
            raise CliFailure(_format_problems("publish", targets), exit_code=2)
        with _exclusive_lock(root_path):
            _publish_unlocked(root_path, owner, writer, normalized)
    except CliFailure:
        raise
    except OSError as exc:
        raise CliFailure(f"cannot publish host endpoint records: {exc}", exit_code=2) from exc


def _withdraw_unlocked(root: Path, owner: str) -> None:
    preflight = _preflight_unlocked(root, owner, {}, allow_empty=True)
    if preflight:
        raise CliFailure(_format_problems("withdraw", preflight), exit_code=2)
    fragments, problems = _load_fragments(root, skip_owner=owner)
    if problems:
        raise CliFailure(_format_problems("withdraw", problems), exit_code=2)
    fragment_path = _fragment_path(root, owner)
    try:
        info = _regular_or_missing(root, fragment_path)
    except CliFailure as exc:
        raise CliFailure(_format_problems("withdraw", [str(exc)]), exit_code=2) from exc
    keys = {key for fragment in fragments.values() for key in fragment.entries}
    aggregate = _aggregate_bytes(fragments)
    environment = _render_environment(root, aggregate, keys)
    if info is not None:
        fragment_path.unlink()
        _fsync_directory(fragment_path.parent)
    _atomic_write(root, _path(root, "/etc/host-endpoints.env"), aggregate, _FILE_MODE)
    _atomic_write(root, _path(root, "/etc/environment"), environment, _FILE_MODE)
    _atomic_write(root, _path(root, "/etc/profile.d/host-endpoints.sh"), _PROFILE, _FILE_MODE)


def withdraw(owner: str, *, root: str | os.PathLike[str] = "/") -> None:
    """Remove one owner's fragment and re-render the shared host files."""

    owner_problem = _owner_problem(owner)
    if owner_problem is not None:
        raise CliFailure(_format_problems("withdraw", [owner_problem]), exit_code=2)
    try:
        root_path = _root_path(root)
        _ensure_publish_directories(root_path)
        targets = _target_symlink_problems(root_path)
        if targets:
            raise CliFailure(_format_problems("withdraw", targets), exit_code=2)
        with _exclusive_lock(root_path):
            _withdraw_unlocked(root_path, owner)
    except CliFailure:
        raise
    except OSError as exc:
        raise CliFailure(f"cannot withdraw host endpoint records: {exc}", exit_code=2) from exc


def verify(
    owner: str,
    expected: object,
    *,
    root: str | os.PathLike[str] = "/",
) -> list[str]:
    """Compare one owner's published fragment with its live expected entries."""

    problems: list[str] = []
    owner_problem = _owner_problem(owner)
    if owner_problem is not None:
        problems.append(owner_problem)
    normalized, entry_problems = _entries_map(expected)
    problems.extend(entry_problems)
    try:
        root_path = _root_path(root)
    except CliFailure as exc:
        return problems + [str(exc)]
    if owner_problem is not None:
        return problems
    fragment, fragment_problems = _parse_fragment(
        root_path, owner, _fragment_path(root_path, owner)
    )
    problems.extend(fragment_problems)
    if fragment is not None and fragment.entries != normalized:
        problems.append(f"fragment for owner {owner!r} does not match expected entries")
    return list(dict.fromkeys(problems))


def _mode_problem(root: Path, path: Path, expected: int, info: os.stat_result | None) -> str | None:
    if info is None:
        return f"missing managed path: {_display(path, root)}"
    actual = stat.S_IMODE(info.st_mode)
    if actual != expected:
        return (
            f"wrong mode on {_display(path, root)}: {actual:04o}, expected {expected:04o}"
        )
    return None


def _check_unlocked(root: Path) -> list[str]:
    problems: list[str] = []
    endpoints = _path(root, "/etc/host-endpoints.d")
    directory_info: os.stat_result | None = None
    try:
        _safe_components(root, endpoints)
        directory_info = endpoints.lstat()
        if not stat.S_ISDIR(directory_info.st_mode):
            problems.append(f"managed directory is not a directory: {_display(endpoints, root)}")
            directory_info = None
    except FileNotFoundError:
        problems.append(f"missing managed directory: {_display(endpoints, root)}")
    except CliFailure as exc:
        problems.append(str(exc))
    if directory_info is not None:
        issue = _mode_problem(root, endpoints, _DIR_MODE, directory_info)
        if issue:
            problems.append(issue)

    fragments: dict[str, _Fragment] = {}
    fragment_problems: list[str] = []
    if directory_info is not None:
        fragments, fragment_problems = _load_fragments(root)
        problems.extend(fragment_problems)
        lock_path = endpoints / ".lock"
        try:
            lock_info = _regular_or_missing(root, lock_path)
        except CliFailure as exc:
            lock_info = None
            problems.append(str(exc))
        issue = _mode_problem(root, lock_path, _LOCK_MODE, lock_info)
        if issue:
            problems.append(issue)
        try:
            children = sorted(endpoints.iterdir(), key=lambda child: child.name)
        except OSError as exc:
            children = []
            problems.append(f"cannot read {_display(endpoints, root)}: {exc}")
        for child in children:
            if child.name in {".lock"} or child.name.startswith(_TEMP_PREFIX):
                continue
            if child.name.endswith(".env") and _owner_problem(child.name[:-4]) is None:
                try:
                    info = _regular_or_missing(root, child)
                except CliFailure as exc:
                    info = None
                    problems.append(str(exc))
                issue = _mode_problem(root, child, _FILE_MODE, info)
                if issue:
                    problems.append(issue)

    aggregate_path = _path(root, "/etc/host-endpoints.env")
    try:
        aggregate_info = _regular_or_missing(root, aggregate_path)
    except CliFailure as exc:
        aggregate_info = None
        problems.append(str(exc))
    issue = _mode_problem(root, aggregate_path, _FILE_MODE, aggregate_info)
    if issue:
        problems.append(issue)
    try:
        actual_aggregate = _read_file(root, aggregate_path)
    except (CliFailure, OSError):
        actual_aggregate = None
    expected_aggregate = _aggregate_bytes(fragments)
    if actual_aggregate is not None and actual_aggregate != expected_aggregate:
        problems.append("/etc/host-endpoints.env differs from endpoint fragments")

    environment_path = _path(root, "/etc/environment")
    try:
        environment_info = _regular_or_missing(root, environment_path)
        environment = _read_file(root, environment_path)
    except (CliFailure, OSError) as exc:
        environment_info = None
        environment = None
        problems.append(str(exc))
    issue = _mode_problem(root, environment_path, _FILE_MODE, environment_info)
    if issue:
        problems.append(issue)
    if environment is not None:
        unmanaged, block_payload, marker_problems = _environment_parts(environment)
        problems.extend(f"/etc/environment: {problem}" for problem in marker_problems)
        managed_keys = {key for fragment in fragments.values() for key in fragment.entries}
        for key in sorted(_outside_keys(unmanaged) & managed_keys):
            problems.append(f"{key} is duplicated outside the host-endpoints block")
        if managed_keys:
            if block_payload is None:
                problems.append("/etc/environment is missing the host-endpoints block")
            elif actual_aggregate is not None and block_payload != actual_aggregate:
                problems.append("/etc/environment host-endpoints block differs from aggregate")
        elif block_payload is not None:
            problems.append("/etc/environment has a host-endpoints block but no fragments remain")

    profile_dir = _path(root, "/etc/profile.d")
    profile_path = profile_dir / "host-endpoints.sh"
    try:
        _safe_components(root, profile_dir)
        profile_dir_info = profile_dir.lstat()
        if not stat.S_ISDIR(profile_dir_info.st_mode):
            problems.append(f"managed directory is not a directory: {_display(profile_dir, root)}")
            profile_info = None
            profile_content = None
        else:
            profile_info = _regular_or_missing(root, profile_path)
            profile_content = _read_file(root, profile_path)
    except FileNotFoundError:
        problems.append(f"missing managed directory: {_display(profile_dir, root)}")
        profile_info = None
        profile_content = None
    except (CliFailure, OSError) as exc:
        problems.append(str(exc))
        profile_info = None
        profile_content = None
    issue = _mode_problem(root, profile_path, _FILE_MODE, profile_info)
    if issue:
        problems.append(issue)
    if profile_content is not None and profile_content != _PROFILE:
        problems.append("/etc/profile.d/host-endpoints.sh differs from generated content")
    return list(dict.fromkeys(problems))


def check(*, root: str | os.PathLike[str] = "/") -> list[str]:
    """Check all fragments, rendered files, markers, symlinks and modes."""

    try:
        root_path = _root_path(root)
    except CliFailure as exc:
        return [str(exc)]
    try:
        return _check_unlocked(root_path)
    except OSError as exc:
        return [f"cannot check host endpoint records: {exc}"]


def require_env(
    name: str,
    *,
    remedy: str,
    environ: Mapping[str, str] = os.environ,
) -> str:
    """Return a non-empty endpoint variable or fail with its named remedy."""

    if not isinstance(name, str) or _KEY_RE.fullmatch(name) is None:
        raise ValueError("name must be a valid uppercase environment variable")
    if not isinstance(remedy, str) or not remedy.strip() or "\n" in remedy or "\r" in remedy:
        raise ValueError("remedy must be a non-empty single line")
    value = environ.get(name)
    if value is None or value == "":
        raise CliFailure(f"{name} is unset: {remedy}")
    return value


def _read_aggregate(root: Path) -> bytes:
    path = _path(root, "/etc/host-endpoints.env")
    try:
        data = _read_file(root, path)
    except (CliFailure, OSError) as exc:
        raise CliFailure(str(exc), exit_code=2) from exc
    if data is None:
        raise CliFailure("/etc/host-endpoints.env is missing", exit_code=2)
    return data


def _cli_publish(args: Any, runtime: CliRuntime) -> None:
    entries: list[tuple[str, str]] = []
    for raw in args.entry:
        key, separator, value = raw.partition("=")
        if not separator:
            raise CliFailure(f"invalid --entry {raw!r}; expected KEY=VALUE", exit_code=2)
        entries.append((key, value))
    publish(args.owner, entries, writer=args.writer)
    runtime.output.primary(f"Published host endpoints for {args.owner}.")


def _cli_withdraw(args: Any, runtime: CliRuntime) -> None:
    withdraw(args.owner)
    runtime.output.primary(f"Withdrew host endpoints for {args.owner}.")


def _cli_check(_args: Any, runtime: CliRuntime) -> int:
    problems = check()
    if runtime.json_mode:
        runtime.output.primary({"problems": problems})
    elif problems:
        for problem in problems:
            runtime.output.error(problem)
    else:
        runtime.output.primary("hostendpoints check passed.")
    return 1 if problems else 0


def _cli_show(_args: Any, runtime: CliRuntime) -> None:
    try:
        rendered = _read_aggregate(_root_path("/")).decode("ascii")
    except UnicodeDecodeError as exc:
        raise CliFailure("/etc/host-endpoints.env is not ASCII", exit_code=2) from exc
    runtime.output.primary(rendered.removesuffix("\n"))


def build_cli(identity: CliIdentity | None = None) -> Any:
    """Build the registered ``hostendpoints`` CLI used by ``python -m``."""

    if identity is None:
        identity = CliIdentity.from_distribution(
            name="HOST ENDPOINTS",
            distribution="cli-extended",
            long_name="Host endpoint record manager",
            command="hostendpoints",
        )
    registry = CliRegistry(
        identity,
        prog="hostendpoints",
        description="Publish and inspect host-owned endpoint environment facts.",
        getting_started=("hostendpoints check",),
    )
    owner_option = OptionSpec(
        ("--owner",),
        "fragment owner used as the record filename",
        group="RECORD",
        metavar="OWNER",
        parser_kwargs={"required": True},
    )
    registry.register(
        VerbSpec(
            "publish",
            description="Publish one owner's endpoint entries and render the shared files.",
            group="MODIFICATION",
            options=(
                owner_option,
                OptionSpec(
                    ("--writer",),
                    "owning install verb and version, for example 'cgpd install 2.3.0'",
                    group="RECORD",
                    metavar="WRITER",
                    parser_kwargs={"required": True},
                ),
                OptionSpec(
                    ("--entry",),
                    "endpoint entry in KEY=VALUE form; repeat for each key",
                    group="RECORD",
                    metavar="KEY=VALUE",
                    parser_kwargs={"action": "append", "required": True},
                ),
            ),
            handler=_cli_publish,
            mutating=True,
            confirmation_required=False,
            include_json=False,
            include_progress=False,
        )
    )
    registry.register(
        VerbSpec(
            "withdraw",
            description="Withdraw one owner's fragment and update the shared files.",
            group="MODIFICATION",
            options=(owner_option,),
            handler=_cli_withdraw,
            mutating=True,
            confirmation_required=False,
            include_json=False,
            include_progress=False,
        )
    )
    registry.register(
        VerbSpec(
            "check",
            description="Check fragments, rendered files, marker structure, modes and symlinks.",
            group="EXPLORATION",
            handler=_cli_check,
            include_json=True,
            include_progress=False,
        )
    )
    registry.register(
        VerbSpec(
            "show",
            description="Print the generated aggregate environment file.",
            group="EXPLORATION",
            handler=_cli_show,
            include_json=False,
            include_progress=False,
        )
    )
    return registry.build()


def main(argv: Sequence[str] | None = None) -> int:
    """Run the registered endpoint-record CLI."""

    try:
        app = build_cli()
    except VersionLookupError as exc:
        print(f"[ERROR] hostendpoints: {exc}", file=sys.stderr)
        return 2
    return app.run(argv=argv)


if __name__ == "__main__":
    raise SystemExit(main())
