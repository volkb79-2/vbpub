def _docker_available() -> bool:
    if not shutil.which("docker"):
        return False
    result = subprocess.run(
        ["docker", "info"],
        capture_output=True,
        text=True,
        check=False,
    )
    return result.returncode == 0


def _ensure_network_exists(network_name: str) -> None:
    if not network_name:
        raise WorkspaceEnvError("DOCKER_NETWORK_INTERNAL is missing or empty.")

    if not _docker_available():
        raise WorkspaceEnvError("Docker not available; cannot create network.")

    inspect = subprocess.run(
        ["docker", "network", "inspect", network_name],
        capture_output=True,
        text=True,
        check=False,
    )
    if inspect.returncode == 0:
        return

    _log_info(f"Creating docker network: {network_name}")
    create = subprocess.run(
        ["docker", "network", "create", network_name],
        capture_output=True,
        text=True,
        check=False,
    )
    if create.returncode != 0:
        raise WorkspaceEnvError(
            f"Failed to create docker network {network_name}: {create.stderr.strip()}"
        )


def _connect_devcontainer_to_network(network_name: str) -> None:
    """Attach the devcontainer to the named network.

    S1.9: MUST no-op cleanly when ENV_TYPE != devcontainer.
    """
    env_type = os.environ.get("ENV_TYPE", "").lower()
    if env_type != "devcontainer":
        return

    container_name = os.environ.get("DEVCONTAINER_NAME") or os.environ.get("HOSTNAME", "")
    if not container_name:
        _log_warn("Devcontainer name not detected; skipping network attach.")
        return

    if not _docker_available():
        _log_warn("Docker not available; skipping devcontainer network attach.")
        return

    inspect = subprocess.run(
        ["docker", "network", "inspect", network_name, "--format", "{{range .Containers}}{{.Name}} {{end}}"],
        capture_output=True,
        text=True,
        check=False,
    )
    if inspect.returncode == 0 and container_name in inspect.stdout.split():
        return

    _log_info(f"Connecting devcontainer {container_name} to {network_name}")
    connect = subprocess.run(
        ["docker", "network", "connect", network_name, container_name],
        capture_output=True,
        text=True,
        check=False,
    )
    if connect.returncode != 0:
        _log_warn(
            f"Failed to connect devcontainer to {network_name}: {connect.stderr.strip()}"
        )


def _check_tls_access() -> None:
    """TLS accessibility probe.

    S1.9 / S2.8: only runs when PUBLIC_TLS_* are set; degrades to warn on
    non-devcontainer or when docker is unavailable.
    """
    cert_path = os.environ.get("PUBLIC_TLS_CRT_PEM", "")
    key_path = os.environ.get("PUBLIC_TLS_KEY_PEM", "")
    if not cert_path or not key_path:
        return

    if not _docker_available():
        _log_warn("Docker not available; skipping TLS accessibility checks.")
        return

    user_uid = os.environ.get("USER_UID", str(os.getuid()))
    docker_gid = os.environ.get("DOCKER_GID") or os.environ.get("CONTAINER_GID", "")
    if not docker_gid:
        _log_warn("DOCKER_GID not set; skipping TLS accessibility checks.")
        return

    for label, path in (("certificate", cert_path), ("private key", key_path)):
        test = subprocess.run(
            [
                "docker",
                "run",
                "--rm",
                "-v",
                "/etc/letsencrypt:/etc/letsencrypt:ro",
                "--user",
                f"{user_uid}:{docker_gid}",
                "alpine:latest",
                "sh",
                "-c",
                f"test -r {shlex.quote(path)}",
            ],
            capture_output=True,
            text=True,
            check=False,
        )
        if test.returncode != 0:
            _log_warn(f"TLS {label} not accessible to Docker: {path}")


def validate_required_certs(env: Optional[Dict[str, str]] = None) -> None:
    """Validate TLS cert/key files as given in env (S2.4).

    Reads PUBLIC_TLS_CRT_PEM and PUBLIC_TLS_KEY_PEM from *env* (defaults to
    os.environ).  For each path that is set, checks:
      - the file exists and is readable by the calling process, AND
      - is readable by DOCKER_GID: group-readable when st_gid == DOCKER_GID,
        or other-readable (st_mode & 0o004).

    Raises WorkspaceEnvError naming the exact failing path.
    ABSOLUTELY NO path re-derivation — the path is validated exactly as given
    (kills the v1 live/live bug A10 by design).

    S2.5: DOCKER_GID '0' is a valid GID; falsy-safe int parse.
    """
    source = env if env is not None else dict(os.environ)

    cert_path = source.get("PUBLIC_TLS_CRT_PEM", "")
    key_path = source.get("PUBLIC_TLS_KEY_PEM", "")

    if not cert_path and not key_path:
        return

    # S2.5: parse DOCKER_GID with falsy-safe check: '' or absent means unknown
    raw_gid = source.get("DOCKER_GID", "")
    docker_gid: Optional[int]
    if raw_gid is None or raw_gid == "":
        docker_gid = None
    else:
        try:
            docker_gid = int(raw_gid)
        except ValueError:
            docker_gid = None

    for path_str in (cert_path, key_path):
        if not path_str:
            continue
        p = Path(path_str)
        if not p.exists():
            raise WorkspaceEnvError(
                f"TLS file does not exist: {path_str}"
            )
        try:
            st = p.stat()
        except OSError as exc:
            raise WorkspaceEnvError(
                f"TLS file not readable: {path_str}: {exc}"
            ) from exc

        mode = st.st_mode
        # other-readable — accessible regardless of GID
        other_readable = bool(mode & stat.S_IROTH)
        # group-readable by DOCKER_GID
        group_readable_by_docker = (
            docker_gid is not None
            and st.st_gid == docker_gid
            and bool(mode & stat.S_IRGRP)
        )
        if not other_readable and not group_readable_by_docker:
            raise WorkspaceEnvError(
                f"TLS file not readable by DOCKER_GID ({docker_gid}): {path_str}"
            )


def ensure_workspace_network(
    network_name: Optional[str] = None,
    auto_connect: bool = True,
) -> None:
    """Ensure the shared Docker network exists and attach devcontainer if enabled."""
    resolved = network_name or os.environ.get("DOCKER_NETWORK_INTERNAL", "")
    _ensure_network_exists(resolved)
    if auto_connect:
        _connect_devcontainer_to_network(resolved)


def render_generated_facts_block(facts: Mapping[str, str]) -> list[str]:
    """Render the `[ciu.instance.generated]` block as a list of TOML lines.

    Values are emitted with ``json.dumps`` exactly as
    ``worktree._worktree_overlay_text`` already does for its own tables — TOML
    basic strings and JSON strings share an escape grammar for the characters
    a filesystem path or a hostname can contain.

    Key ORDER is :data:`GENERATED_FACTS_KEYS`, never ``facts``' iteration
    order, so the rendered block is byte-identical across runs regardless of
    how the caller built the mapping.
    """
    missing = [key for key in GENERATED_FACTS_KEYS if key not in facts]
    if missing:
        raise WorkspaceEnvError(
            f"[S3.1b] generated identity facts incomplete: missing {missing}"
        )
    lines = [GENERATED_FACTS_HEADER, *_GENERATED_FACTS_BANNER]
    lines.extend(f"{key} = {json.dumps(facts[key])}" for key in GENERATED_FACTS_KEYS)
    return lines


def upsert_generated_facts(repo_root: Path, facts: Mapping[str, str]) -> Path:
    """S3.1b (CIU-60) — write *facts* into ``ciu.global.worktree.toml.j2``.

    This is a TEXT-LEVEL surgical block replace, deliberately NOT a
    ``tomllib`` parse + ``tomli_w`` dump round-trip. The overlay is documented
    operator-editable (S3.1b): a full-file round-trip would round-trip every
    VALUE correctly while silently discarding every comment and reformatting
    every table an operator hand-authored.

    **The bytes CIU owns**, stated exactly, because the boundary is narrower
    than "up to the next table" and the narrowness is the safety property:
    from the ``[ciu.instance.generated]`` header line, up to and including the
    last line this writer itself emits — its own banner comments and its own
    ``key = value`` lines. The scan finds the next line beginning a table at
    column 0 and then walks BACK over that region's trailing run of blank and
    comment lines, which is never ours (the last line rendered is always a
    ``key = value``) and which in TOML's ordinary reading introduces the
    FOLLOWING table. That run is carried across untouched. So a comment
    written immediately below the generated block survives, exactly like one
    written above it. Nothing outside those owned lines is read, rewritten, or
    reordered.

    Behaviour:

    * file absent → created, carrying the same header comment
      ``worktree._worktree_overlay_text`` writes, then the block;
    * table absent → block appended at EOF, one blank line after whatever was
      already there;
    * table present → its owned lines replaced in place, with the trailing
      blank/comment run preserved verbatim (and a single blank separator
      manufactured only when the region carried none at all), so a second run
      over an unchanged workspace produces a byte-identical file.

    Unlike ``worktree._write_worktree_overlay`` — which correctly REFUSES an
    existing file, because its only call site is worktree creation on day zero
    — this runs on every ``ciu env generate``, possibly the tenth one over a
    file the operator has since added their own tables and comments to. Hence
    upsert, not refuse-if-exists and not blind append. That refusal is left
    exactly as it is; its other callers still need it.

    Known and accepted limit of text scanning: a line reading exactly
    ``[ciu.instance.generated]`` *inside a multi-line TOML string elsewhere in
    the file* would be mistaken for the table header. That construct cannot
    occur in a sparse override of the shape S3.1b describes, and the
    alternative (a full-file round-trip) fails the far more likely case of an
    operator comment.

    Returns the overlay path.
    """
    path = Path(repo_root) / GLOBAL_CONFIG_WORKTREE_OVERRIDES
    block = render_generated_facts_block(facts)

    try:
        existing = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        existing = ""
    except OSError as exc:
        raise WorkspaceEnvError(f"[S3.1b] could not read {path}: {exc}") from exc

    if existing:
        lines = existing.splitlines()
    else:
        lines = list(_OVERLAY_FRESH_HEADER)

    start = next(
        (i for i, line in enumerate(lines) if line.strip() == GENERATED_FACTS_HEADER),
        None,
    )
    if start is None:
        if lines and lines[-1].strip():
            lines.append("")
        lines.extend(block)
    else:
        end = next(
            (i for i in range(start + 1, len(lines)) if lines[i].startswith("[")),
            len(lines),
        )
        # The region's TRAILING run of blank/comment lines is never ours — the
        # last line this writer emits is always a `key = value` — so it is
        # either the blank separator before the next table or, in TOML's
        # ordinary reading, a hand-authored comment that belongs to that next
        # table. Carrying it across keeps O2's promise for a comment written
        # immediately BELOW the generated block, and is idempotent: the same
        # run is re-detected and re-emitted unchanged on every later run.
        keep = end
        while keep > start + 1 and (
            not lines[keep - 1].strip() or lines[keep - 1].lstrip().startswith("#")
        ):
            keep -= 1
        tail = lines[keep:end]
        # Only manufacture a separator when the region carried none at all.
        if not tail and end < len(lines):
            tail = [""]
        lines[start:end] = [*block, *tail]

    _atomic_write_text(path, "\n".join(lines) + "\n")
    return path


def _atomic_write_text(path: Path, payload: str) -> None:
    """Temp-file + fsync + ``os.replace`` (S16 durability), as
    ``worktree._write_worktree_overlay`` does.

    Uses ``"w"`` rather than that function's ``"x"``: this writer runs on every
    `env generate`, so a temp file left behind by a crash under the same PID
    must not wedge every future generate.
    """
    tmp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    try:
        with tmp.open("w", encoding="utf-8") as fh:
            fh.write(payload)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    except OSError as exc:
        try:
            tmp.unlink()
        except OSError:
            pass
        raise WorkspaceEnvError(f"[S3.1b] could not write {path}: {exc}") from exc


def has_generated_facts(ciu_root: Path) -> bool:
    """S3.1c (CIU-75) — does *ciu_root*'s overlay CARRY the CIU-owned table?

    PRESENCE, never readability: the header line exists or it does not. A
    present-but-corrupt table answers ``True`` here on purpose, so the caller's
    own read (:func:`read_generated_facts`) refuses loudly instead of this
    predicate silently downgrading indeterminacy to "not a CIU instance"
    (AGENTS.md's absence-for-emptiness anti-pattern).

    This is the post-cutover replacement for the ``ciu.env`` ``.is_file()``
    readiness signal: what makes a checkout able to act as a CIU instance is
    now the generated table, because that is what every internal fact read
    consults.
    """
    path = Path(ciu_root) / GLOBAL_CONFIG_WORKTREE_OVERRIDES
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        # Unreadable is not "absent" — but a boolean cannot say so. The one
        # honest answer a *presence* predicate can give for a file that exists
        # and cannot be read is "treat it as present": the caller's real read
        # then raises with the actual cause. `FileNotFoundError` (a genuine
        # absence) is the only OSError that must answer False.
        return path.exists()
    return any(line.strip() == GENERATED_FACTS_HEADER for line in text.splitlines())


def read_generated_facts(ciu_root: Path) -> dict[str, str]:
    """S3.1c (CIU-75) — the ``[ciu.instance.generated]`` facts for *ciu_root*.

    The READ side of S3.1b, and since CIU-75 the ONLY source CIU itself
    consults for instance identity: ``ciu.env`` is a write-only legacy export
    (contract item 2) and is never read back by any CIU internal.

    Deliberately a text-level scan of the CIU-owned block, exactly mirroring
    :func:`upsert_generated_facts`'s own ownership boundary — NOT a
    :func:`config_model.render_global_chain` of the whole checkout. Three
    reasons, each of which the chain render fails:

    * the overlay is a Jinja **template**; rendering it needs the merged
      config it is itself a layer of, and (CIU-74) an undefined name is now a
      hard error — but the CIU-owned block is plain TOML by construction
      (``json.dumps``'d strings), so it can be read without any context;
    * the sites this replaces (a reap survey, a shared-infra reference, a
      budget candidate) read a checkout that is NOT this process's own repo
      root and whose committed config chain may be absent or broken; the
      ``ciu.env`` read they used had no such dependency and neither may this;
    * the block is merged LAST in the chain and written by CIU alone, so its
      own bytes ARE the merged value — reading the chain could only agree.

    Returns ``{}`` when the overlay, or the table, is absent — the exact
    counterpart of the pre-cutover "no ``ciu.env`` here" case. Raises
    :class:`WorkspaceEnvError` when the file is present and cannot be read
    (``OSError``), is not UTF-8, is not parseable TOML, or carries a
    non-string value: all four are indeterminacy, never emptiness.
    """
    path = Path(ciu_root) / GLOBAL_CONFIG_WORKTREE_OVERRIDES
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return {}
    except (OSError, UnicodeDecodeError) as exc:
        raise WorkspaceEnvError(f"[S3.1c] could not read {path}: {exc}") from exc

    lines = text.splitlines()
    start = next(
        (i for i, line in enumerate(lines) if line.strip() == GENERATED_FACTS_HEADER),
        None,
    )
    if start is None:
        return {}
    end = next(
        (i for i in range(start + 1, len(lines)) if lines[i].startswith("[")),
        len(lines),
    )
    try:
        parsed = tomllib.loads("\n".join(lines[start:end]))
    except tomllib.TOMLDecodeError as exc:
        raise WorkspaceEnvError(
            f"[S3.1c] {path} has a malformed {GENERATED_FACTS_HEADER} table: {exc}"
        ) from exc

    # The slice STARTS at the table header and stops before the next line
    # beginning a table, so the parse can only ever be this one nested table —
    # no `.get(..., {})` defaulting is warranted, and inventing one would hide
    # a slicing bug behind an empty result.
    table: dict = parsed
    for part in GENERATED_FACTS_TABLE.split("."):
        table = table[part]
    facts: dict[str, str] = {}
    for key, value in table.items():
        if not isinstance(value, str):
            raise WorkspaceEnvError(
                f"[S3.1c] {path} {GENERATED_FACTS_HEADER}.{key} is "
                f"{type(value).__name__}, not a string"
            )
        facts[key] = value
    return facts


def identity_env_from_facts(facts: Mapping[str, str]) -> dict[str, str]:
    """Translate ``[ciu.instance.generated]`` facts to legacy env KEY names.

    The single place :data:`GENERATED_FACT_ENV_KEYS` is applied, so a child
    process's environment and a candidate render's ``environ`` can never
    disagree about which facts cross that boundary. A fact with no env name
    (an operator-added key) is dropped rather than exported under a guessed
    name; a fact CIU never derived (an empty ``public_fqdn``) is carried
    through as the empty string it is, exactly as ``ciu.env`` carried it.
    """
    return {
        GENERATED_FACT_ENV_KEYS[key]: value
        for key, value in facts.items()
        if key in GENERATED_FACT_ENV_KEYS
    }


def read_instance_identity_env(ciu_root: Path) -> dict[str, str]:
    """:func:`read_generated_facts` under the legacy ``ciu.env`` KEY names.

    The SCREAMING_CASE shell names a CHILD ciu process (or a rendered
    template's ``$VAR`` expansion) still speaks. Empty facts → empty dict.
    """
    return identity_env_from_facts(read_generated_facts(ciu_root))


def seed_identity_env(ciu_root: Path) -> dict[str, str]:
    """Put *ciu_root*'s overlay identity into ``os.environ``, OVERRIDING it.

    S3.1c clause 2a, and the fix for the gap the CIU-75 review found: moving
    the twelve per-checkout fact READS onto the overlay left the PROCESS
    ENVIRONMENT still seeded from `ciu.env`, and ~26 internal sites read
    `REPO_ROOT` / `PHYSICAL_REPO_ROOT` / `DOCKER_NETWORK_INTERNAL` /
    `PUBLIC_FQDN` straight out of `os.environ` (a rendered
    ``network_name = "$DOCKER_NETWORK_INTERNAL"`` among them). With the seed
    coming from a file that skipped keys already present, a shell that had
    sourced a SIBLING checkout's `ciu.env` won the render — the exact CIU-41
    hazard, arriving through the one door the cutover had not closed.

    **Override, never skip-if-present.** This is `adopt_file_identity`'s old
    CIU-41 rule with a better source: the overlay was written for THIS repo
    root and outranks inherited shell state by construction. Skip-if-present
    would re-open the hazard for every already-exported key, which is all of
    them in the case that actually bites.

    Returns what it applied (empty when this checkout has no generated table).
    """
    identity = read_instance_identity_env(ciu_root)
    for key, value in identity.items():
        os.environ[key] = value
    return identity


def _load_legacy_machine_env(env_path: Path, *, override: bool) -> dict[str, str]:
    """Seed ``os.environ`` with the NON-identity half of `ciu.env`.

    S3.1c clause 2: `ciu.env` remains the transport for MACHINE facts at
    process start — a cache of live derivation, regenerated when absent — and
    is never a source of instance identity. The identity keys it still carries
    are skipped here and seeded from the overlay by
    :func:`seed_identity_env`; that is belt and braces (the caller seeds
    identity afterwards regardless), and it is what makes "no identity fact is
    ever read from `ciu.env`" true of the code rather than of the ordering.

    Read failure is a WARN and an empty dict, not a traceback. Pre-CIU-75 this
    was a bare `read_text` at the first statement of every verb, so a non-UTF-8
    byte in a file CIU calls write-only crashed `ciu up` with a raw
    `UnicodeDecodeError` — CIU-62's three unrelated failure types
    (`OSError`, `UnicodeDecodeError`, `WorkspaceEnvError`) reaching one more
    reader that had never been given them. Missing machine facts still refuse
    loudly, one step later and with a remedy, in :func:`ensure_workspace_env`.
    """
    try:
        values = parse_workspace_env(env_path)
    except (OSError, UnicodeDecodeError, WorkspaceEnvError) as exc:
        _log_warn(
            f"[S3.1c] could not read {env_path}: {exc}. Machine facts "
            "(CONTAINER_UID, DOCKER_GID, ENV_TYPE, PUBLIC_TLS_*, …) fall back "
            "to this process's own environment; instance identity is "
            f"unaffected — since 7.7.0 it comes from "
            f"{GLOBAL_CONFIG_WORKTREE_OVERRIDES}, not from this file. "
            "Repair with: ciu env generate",
            stream=sys.stderr,
        )
        return {}
    applied: dict[str, str] = {}
    for key, value in values.items():
        if key in LEGACY_IDENTITY_ENV_KEYS:
            continue
        if override or key not in os.environ:
            os.environ[key] = value
            applied[key] = value
    return applied


def _seed_identity_or_repair(ciu_root: Path, *, generated: bool) -> dict[str, str]:
    """:func:`seed_identity_env`, repairing a checkout that has no table yet.

    A 7.6.x checkout upgrading in place has a `ciu.env` and — since CIU-60
    (7.5.0) — usually an overlay table too, but not necessarily: the overlay is
    gitignored, so a fresh clone, a lost worktree-local file or a
    pre-CIU-60 record leaves nothing to read. The record CIU reads is the
    record CIU repairs, which is the same self-healing `ciu.env` has always had
    when absent — and it keeps the upgrade from being "your next `ciu up`
    refuses until you run a command it did not tell you about".

    Repairing is skipped when this run already generated (the generate wrote
    the table itself; a second one would only be slower). A PRESENT but
    unreadable table is not repaired either — :func:`read_generated_facts`
    raises, and S3.1c clause 4 wants that loud rather than overwritten.
    """
    identity = seed_identity_env(ciu_root)
    if identity or generated:
        return identity
    _log_warn(
        f"[S3.1c] {ciu_root / GLOBAL_CONFIG_WORKTREE_OVERRIDES} carries no "
        f"{GENERATED_FACTS_HEADER} table — regenerating this workspace's "
        "identity record (since 7.7.0 it is the only one CIU reads)",
        stream=sys.stderr,
    )
    generate_ciu_env(ciu_root, notice_stream=sys.stderr)
    return seed_identity_env(ciu_root)


def generate_ciu_env(
    repo_root: Path,
    output_path: Optional[Path] = None,
    *,
    notice_stream=None,
) -> Path:
    """Generate ciu.env with autodetected values.

    ``notice_stream`` routes the one-release deprecation notice (S3.1c clause
    3). It defaults to stdout, which is right for the verb an operator typed;
    the STEP-1 bootstrap passes ``sys.stderr``, because that same notice on
    stdout lands ahead of `ciu check --json`'s document and breaks the parse of
    every machine consumer that followed the migration advice.

    Side-effects: writes the ciu.env file, and upserts the identity facts it
    just derived into this checkout's `ciu.global.worktree.toml.j2` under
    `[ciu.instance.generated]` (S3.1b / CIU-60) so TEMPLATES can read them from
    the merged config chain instead of ambient `os.environ`. Both writes come
    from the SAME in-memory values — the facts are never re-derived, and
    `ciu.env` is never re-read to produce them. Network/TLS steps still belong
    in bootstrap_env_init so tests stay simple (S2.8).

    The overlay write is NOT gated on an S16 worktree instance record: the
    primary/main checkout reads the same file through the same unconditional
    `render_global_chain` step, and gating would leave exactly that checkout
    on the old ambient-env path.

    Returns the path to the generated ciu.env file.
    """
    repo_root = repo_root.resolve()
    output_path = output_path or repo_root / ENV_FILE_NAME

    env_flags = _detect_env_type()
    docker_gid = _detect_docker_gid()
    physical_root = _detect_physical_repo_root(repo_root)
    host_mdt_tmp = _detect_host_mdt_tmp()
    network_values = _compute_network_name(physical_root)
    public_values = _detect_public_fqdn(repo_root, require_fqdn=False)

    user_name = os.environ.get("USER_NAME", os.environ.get("USER", ""))
    user_uid = os.environ.get("USER_UID", str(os.getuid()))
    user_gid = os.environ.get("USER_GID", str(os.getgid()))
    docker_uid = os.environ.get("DOCKER_UID", user_uid)

    container_uid = os.environ.get("CONTAINER_UID", user_uid)
    container_gid = os.environ.get("CONTAINER_GID", docker_gid)

    python_exec = os.environ.get("PYTHON_EXECUTABLE", sys.executable)
    pip_exec = os.environ.get("PIP_EXECUTABLE") or shutil.which("pip") or ""

    gov_read_iops, gov_read_iops_note = _detect_governance_read_iops()

    def _emit_section(title: str, entries: list[tuple[str, str, str]]) -> list[str]:
        block: list[str] = [f"# {title}"]
        for key, value, comment in entries:
            block.append(f"# {comment}")
            block.append(f"export {key}=\"{value}\"")
        return block

    lines = [
        "# CIU Workspace Environment (Auto-generated)",
        "# Do not edit manually - regenerated by ciu --generate-env",
        "",
    ]

    lines.extend(_emit_section(
        "Environment type flags",
        [
            ("ENV_TYPE", env_flags["ENV_TYPE"], "Runtime environment: devcontainer | native | github-actions"),
            ("IS_DEVCONTAINER", env_flags["IS_DEVCONTAINER"], "1 when running inside a devcontainer"),
            ("IS_GITHUB_ACTIONS", env_flags["IS_GITHUB_ACTIONS"], "1 when running in GitHub Actions"),
            ("IS_NATIVE", env_flags["IS_NATIVE"], "1 when running on a native host"),
        ],
    ))
    lines.append("")

    lines.extend(_emit_section(
        "User identity",
        [
            ("USER_NAME", user_name, "Current user name"),
            ("USER_UID", user_uid, "Current user ID"),
            ("USER_GID", user_gid, "Current user primary group ID"),
        ],
    ))
    lines.append("")

    lines.extend(_emit_section(
        "Container identity",
        [
            ("CONTAINER_UID", container_uid, "UID used for container user mapping"),
            ("CONTAINER_GID", container_gid, "GID used for container user mapping"),
            ("DOCKER_UID", docker_uid, "UID for Docker socket access (defaults to USER_UID)"),
            ("DOCKER_GID", docker_gid, "Docker group GID for host volume permissions"),
            ("DEVCONTAINER_NAME", os.environ.get("DEVCONTAINER_NAME", os.environ.get("HOSTNAME", "")), "Detected devcontainer name (if applicable)"),
        ],
    ))
    lines.append("")

    lines.extend(_emit_section(
        "Repository paths",
        [
            ("REPO_ROOT", str(repo_root), "Repo root path inside the current environment"),
            ("PHYSICAL_REPO_ROOT", str(physical_root), "Host-visible repo root for Docker bind mounts"),
            ("HOST_MDT_TMP", host_mdt_tmp, "Host path of the persisted /tmp bind mount, so sibling containers (e.g. the test-runner) can bind the same /tmp; empty on native host"),
        ],
    ))
    lines.append("")

    lines.extend(_emit_section(
        "Docker network identity",
        [
            ("REPO_NAME", network_values["REPO_NAME"], "Lowercase repository name for network naming"),
            ("INSTANCE_ID", network_values["INSTANCE_ID"], "Deterministic instance ID from repo path"),
            ("DOCKER_NETWORK_INTERNAL", network_values["DOCKER_NETWORK_INTERNAL"], "Internal Docker network name"),
        ],
    ))
    lines.append("")

    lines.extend(_emit_section(
        "Public endpoint detection",
        [
            ("PUBLIC_IP", public_values["PUBLIC_IP"], "Detected public IP address (may be empty)"),
            ("PUBLIC_FQDN", public_values["PUBLIC_FQDN"], "Detected or configured public FQDN"),
            ("PUBLIC_TLS_CRT_PEM", public_values["PUBLIC_TLS_CRT_PEM"], "TLS certificate PEM path (S2.3: required only when require_certs=true)"),
            ("PUBLIC_TLS_KEY_PEM", public_values["PUBLIC_TLS_KEY_PEM"], "TLS private key PEM path (S2.3: required only when require_certs=true)"),
        ],
    ))
    lines.append("")

    # Seam 4: CIU_SERVICES_PROFILE placeholder — ordered profile list for this host
    lines.append("# Service profiles (Seam 4 / S7.5)")
    lines.append('# export CIU_SERVICES_PROFILE="core,db,worker-io"  # ordered profile list for this host')
    lines.append("")

    # S15.6: stack-wide resource governance — the overlay generator re-derives
    # this independently from the baseline file (works without an env regen);
    # this copy is a convenience for shell/template consumption.
    lines.extend(_emit_section(
        "Resource governance (S15)",
        [
            (
                "CIU_GOV_READ_IOPS",
                gov_read_iops,
                f"Derived read-IOPS governance cap ({gov_read_iops_note})",
            ),
        ],
    ))
    lines.append("")

    lines.extend(_emit_section(
        "Python tooling",
        [
            ("PYTHON_EXECUTABLE", python_exec, "Python interpreter for CIU subprocesses"),
            ("PIP_EXECUTABLE", pip_exec, "pip executable resolved on PATH"),
        ],
    ))

    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    # S3.1c (CIU-75) — the one-release deprecation WARN, in the shape this
    # codebase already uses for a deprecated-but-still-working path
    # (provisioning.py's `stack:<x>:healthy` exit-0 fallback): always-on, names
    # the forward path, names what a future release does. It is a WARN and not
    # a refusal on purpose — the key set below is byte-identical to 7.6.x, so
    # every `source ciu.env` consumer keeps working THIS release.
    _log_warn(
        LEGACY_ENV_EXPORT_WARNING.format(path=output_path),
        stream=notice_stream,
    )

    # S3.1b (CIU-60). Same values, same invocation, second destination: the
    # merged-config chain, which is what a Jinja TEMPLATE can actually see.
    # Deriving them a second time (or reading them back out of ciu.env) would
    # admit a disagreement between the two records that nothing would catch.
    upsert_generated_facts(
        repo_root,
        {
            "repo_name": network_values["REPO_NAME"],
            "instance_id": network_values["INSTANCE_ID"],
            "network": network_values["DOCKER_NETWORK_INTERNAL"],
            "physical_repo_root": str(physical_root),
            "repo_root": str(repo_root),
            "public_fqdn": public_values["PUBLIC_FQDN"],
        },
    )
    return output_path


def bootstrap_env_init(repo_root: Path) -> Path:
    """Single bootstrap entry point for --generate-env (S2.8).

    Performs the full S2.8 duty order:
      1. generate_ciu_env  — detect + write ciu.env
      2. ensure_workspace_network — create DOCKER_NETWORK_INTERNAL
      3. devcontainer self-attach  — no-op when ENV_TYPE != devcontainer (S1.9)
      4. TLS probe (_check_tls_access) — only when PUBLIC_TLS_* set (S1.9)

    generate_ciu_env is kept side-effect-light (write file only) so tests
    remain simple; this function composes the duties.

    Returns the path to the generated ciu.env file.
    """
    env_path = generate_ciu_env(repo_root)

    # Seed os.environ so the steps below see this workspace's values. Two
    # sources, on purpose (S3.1c clause 2): the MACHINE facts come from the
    # file just written, and the IDENTITY comes from the overlay table the
    # same generate wrote — always overriding ambient, because the network
    # step below must act on THIS workspace's network and not on a stale
    # DOCKER_NETWORK_INTERNAL inherited from another checkout's sourced
    # ciu.env (CIU-41).
    _load_legacy_machine_env(env_path, override=False)
    _seed_identity_or_repair(repo_root, generated=True)

    # Step 2+3: network + devcontainer attach (devcontainer attach is a no-op
    # on native/CI per _connect_devcontainer_to_network's ENV_TYPE guard)
    network_name = os.environ.get("DOCKER_NETWORK_INTERNAL", "")
    if network_name:
        try:
            ensure_workspace_network(network_name)
        except WorkspaceEnvError as exc:
            _log_warn(f"Network setup skipped: {exc}")

    # Step 4: TLS probe (no-op when paths not set; degrades to warn on native)
    _check_tls_access()

    return env_path


def bootstrap_workspace_env(
    start_dir: Path,
    define_root: Optional[Path],
    defaults_filename: str,
    generate_env: bool,
    update_cert_permission: bool,
    required_keys: Iterable[str],
) -> Path:
    """Prepare this process's environment for a verb, and validate it.

    STEP 1 of `ciu up` / `check` / `render` / `graph`. Since 7.7.0 it seeds
    from TWO records, and which one owns what is the whole of S3.1c:

    * **identity** — `[ciu.instance.generated]` in this checkout's overlay,
      always, and always OVERRIDING whatever the ambient environment claims;
    * **machine facts** — `ciu.env`, a cache of live derivation, applied only
      where the ambient environment has nothing to say (unless `--define-root`
      pins the root, which has always overridden).

    Returns the resolved env root directory.
    """
    env_root = resolve_env_root(start_dir, define_root, defaults_filename)
    env_path = env_root / ENV_FILE_NAME

    generated = False
    if generate_env or not env_path.exists():
        # The notice goes to stderr here: this regeneration is a side effect of
        # a verb the operator ran for another reason, and `ciu check --json`
        # writes its document to stdout (S3.1c clause 3).
        generate_ciu_env(env_root, notice_stream=sys.stderr)
        generated = True

    # By EXACT path in both cases. `load_workspace_env` walks via
    # `find_workspace_env`, which honors an ambient REPO_ROOT and can therefore
    # hand back ANOTHER checkout's ciu.env — the same cross-workspace leak the
    # identity seed below exists to close, and there is no reason to leave it
    # open for machine facts either now that the root is already resolved.
    _load_legacy_machine_env(env_path, override=bool(define_root))
    # S3.1c clause 2a — identity last, from the overlay, unconditionally
    # overriding. Ordering is not what makes this safe (the loader above skips
    # identity keys outright); it is here so a reader sees the precedence.
    _seed_identity_or_repair(env_root, generated=generated)

    if generated:
        # Run post-generate bootstrap steps (network + TLS probe).
        # These degrade to warn/no-op on native host per S1.9.
        network_name = os.environ.get("DOCKER_NETWORK_INTERNAL", "")
        if network_name:
            try:
                ensure_workspace_network(network_name)
            except WorkspaceEnvError as exc:
                _log_warn(f"Network setup skipped: {exc}")
        _check_tls_access()

    if update_cert_permission:
        public_fqdn = os.environ.get("PUBLIC_FQDN")
        update_cert_permissions(env_root, public_fqdn)

    ensure_workspace_env(required_keys)
    return env_root


def update_cert_permissions(repo_root: Path, public_fqdn: Optional[str] = None) -> None:
    """Run setup-letsencrypt-permissions.sh (requires root)."""
    if os.geteuid() != 0:
        raise WorkspaceEnvError(
            "--update-cert-permission requires root. "
            "Run: sudo ciu --update-cert-permission"
        )

    script_path = repo_root / "scripts" / "setup-letsencrypt-permissions.sh"
    if not script_path.exists():
        raise WorkspaceEnvError(
            f"Certificate permission script not found: {script_path}"
        )

    args = ["bash", str(script_path)]
    if public_fqdn:
        args.append(public_fqdn)

    subprocess.run(args, check=True)
