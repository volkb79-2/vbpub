class WorkspaceEnvError(ValueError):
    """Raised when workspace environment file is missing or invalid."""


def _log_info(message: str) -> None:
    print(f"[INFO] {message}", flush=True)


def _log_warn(message: str, *, stream=None) -> None:
    """A `[WARN]` line, on stdout by default.

    ``stream`` exists for S3.1c clause 3 (CIU-75 review): a notice raised by a
    verb the operator typed may go to stdout, but the SAME notice raised from
    the STEP-1 bootstrap of `ciu check --json` must not — it would land ahead
    of the JSON document and break every machine consumer's parse. ``None``
    means "stdout at call time", which is what `print` already does, so no
    existing caller changes behavior.
    """
    print(f"[WARN] {message}", file=stream, flush=True)


def resolve_env_root(start_dir: Path, define_root: Optional[Path], defaults_filename: str) -> Path:
    """Resolve the workspace env root directory.

    Order:
    1. Explicit --define-root
    2. Walk up from start_dir until defaults_filename is found
    3. Fallback to start_dir
    """
    if define_root:
        root = define_root.resolve()
        if not root.exists():
            raise WorkspaceEnvError(f"Repository root does not exist: {root}")
        return root

    current = start_dir.resolve()
    while True:
        if (current / defaults_filename).exists():
            return current
        if current == current.parent:
            break
        current = current.parent

    return start_dir.resolve()


def find_workspace_env(start_dir: Path) -> Path:
    """Find ciu.env by walking up from start_dir.

    Priority:
    1. REPO_ROOT environment variable (if set)
    2. Walk up directory tree from start_dir
    """
    repo_root = os.environ.get("REPO_ROOT")
    if repo_root:
        candidate = Path(repo_root).resolve() / ENV_FILE_NAME
        if candidate.exists():
            return candidate

    current = start_dir.resolve()
    while True:
        candidate = current / ENV_FILE_NAME
        if candidate.exists():
            return candidate
        if current == current.parent:
            break
        current = current.parent

    raise WorkspaceEnvError(
        f"Workspace environment file {ENV_FILE_NAME} not found. "
        "Run: ciu env generate"
    )


def parse_workspace_env(path: Path) -> Dict[str, str]:
    """Parse ciu.env into a dict of key/value pairs."""
    values: Dict[str, str] = {}

    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export ") :].strip()

        lexer = shlex.shlex(line, posix=True)
        lexer.whitespace_split = True
        lexer.commenters = "#"
        try:
            tokens = list(lexer)
        except ValueError as exc:
            raise WorkspaceEnvError(
                f"Invalid {ENV_FILE_NAME} entry: {raw_line!r}"
            ) from exc
        if not tokens:
            continue
        if len(tokens) != 1 or "=" not in tokens[0]:
            raise WorkspaceEnvError(
                f"Invalid {ENV_FILE_NAME} entry: {raw_line!r}"
            )

        key, value = tokens[0].split("=", 1)
        key = key.strip()
        if not key:
            raise WorkspaceEnvError(
                f"Invalid {ENV_FILE_NAME} entry (empty key): {raw_line!r}"
            )
        values[key] = value

    return values


def load_workspace_env(start_dir: Path, override: bool = False) -> Dict[str, str]:
    """Load ciu.env and populate os.environ.

    **Not for identity, and not for CIU's own bootstrap (S3.1c).** Two reasons,
    both of which cost real bugs before CIU-75: it seeds the six identity keys
    from the LEGACY export, which since 7.7.0 is not where identity lives; and
    it locates the file through :func:`find_workspace_env`, which honors an
    ambient ``REPO_ROOT`` and can therefore load a DIFFERENT checkout's file
    entirely. `bootstrap_workspace_env` uses :func:`_load_legacy_machine_env`
    (exact path, machine facts only) plus :func:`seed_identity_env`. This
    function remains for consumers of the legacy export itself.

    Args:
        start_dir: Directory to begin searching for ciu.env
        override: If True, overwrite existing os.environ values

    Returns:
        Dict of loaded values (from file)
    """
    env_path = find_workspace_env(start_dir)
    values = parse_workspace_env(env_path)

    for key, value in values.items():
        if override or key not in os.environ:
            os.environ[key] = value

    return values


def ensure_workspace_env(required_keys: Iterable[str]) -> None:
    """Ensure required environment variables are present.

    Raises WorkspaceEnvError if any are missing or empty.
    S2.5: 0 is a valid value — check is None / == "" not truthiness.
    """
    missing = [key for key in required_keys if os.environ.get(key) is None or os.environ.get(key) == ""]
    if missing:
        missing_str = ", ".join(missing)
        raise WorkspaceEnvError(
            "Missing required workspace environment variables: "
            f"{missing_str}. "
            'Run: ciu env generate (then, for a shell: eval "$(ciu env print)")'
        )


def detect_standalone_root(start_dir: Path) -> Optional[Path]:
    """Detect a standalone CIU root based on ciu.global.defaults.toml.j2.

    Returns the nearest parent directory whose ciu.global.defaults.toml.j2
    contains 'standalone_root = true'.
    """
    current = start_dir.resolve()
    while True:
        candidate = current / GLOBAL_CONFIG_DEFAULTS
        if candidate.exists():
            try:
                content = candidate.read_text(encoding="utf-8")
            except OSError:
                content = ""
            if STANDALONE_ROOT_PATTERN.search(content):
                return current
        if current == current.parent:
            break
        current = current.parent
    return None


def enforce_standalone_root(start_dir: Path) -> None:
    """Enforce the S1.2 standalone-root guard from an INVOCATION directory.

    If ``start_dir`` sits inside a standalone CIU root (a directory whose
    ``ciu.global.defaults.toml.j2`` sets ``standalone_root = true``), then
    ``$REPO_ROOT`` MUST resolve to that same directory, else ``WorkspaceEnvError``.

    ``start_dir`` MUST be the directory the command was invoked from (cwd, or the
    ``--dir`` target), NOT an already-resolved ``repo_root``. The guard exists
    precisely to catch a contaminated / stale ``$REPO_ROOT`` — e.g. a sibling
    repo's ``ciu.env`` auto-sourced by the shell (``~/.bashrc`` sourcing
    ``${REPO_ROOT}/ciu.env``). Walking up from the *resolved* root would inspect
    the wrong repo's marker and silently pass — which is exactly the bug this
    helper fixes: ``ciu render`` used ``detect_standalone_root(repo_root)`` while
    ``ciu up`` used the invocation dir, so the two paths disagreed and ``render``
    would proceed against the wrong repo. Both call this with their invocation
    directory now, so they cannot diverge again.
    """
    standalone_root = detect_standalone_root(start_dir)
    if standalone_root is None:
        return
    env_repo_root_raw = os.environ.get("REPO_ROOT", "")
    if not env_repo_root_raw:
        # Nothing to compare against; resolve_repo_root / bootstrap raise their
        # own "REPO_ROOT not set" error for the unset case.
        return
    env_repo_root = Path(env_repo_root_raw).resolve()
    if env_repo_root != standalone_root:
        raise WorkspaceEnvError(
            "[S1.2] standalone_root is true but REPO_ROOT does not match. "
            f"Expected: {standalone_root}, got: {env_repo_root}. "
            "Regenerate ciu.env from the standalone root (or run from it)."
        )


def _detect_env_type() -> Dict[str, str]:
    """Detect ENV_TYPE: devcontainer | native | github-actions (S2.7).

    v1's 'bare-metal' is renamed 'native' per S2.7 / Appendix C.
    IS_NATIVE replaces IS_BARE_METAL; IS_DEVCONTAINER and IS_GITHUB_ACTIONS
    are retained.
    """
    env_type = os.environ.get("ENV_TYPE")
    if not env_type:
        if os.environ.get("GITHUB_ACTIONS"):
            env_type = "github-actions"
        elif os.environ.get("REMOTE_CONTAINERS") or os.environ.get("WORKSPACE_DIR") or Path("/.dockerenv").exists():
            env_type = "devcontainer"
        else:
            env_type = "native"

    return {
        "ENV_TYPE": env_type,
        "IS_DEVCONTAINER": "1" if env_type == "devcontainer" else "0",
        "IS_GITHUB_ACTIONS": "1" if env_type == "github-actions" else "0",
        "IS_NATIVE": "1" if env_type == "native" else "0",
    }


def _detect_public_fqdn(repo_root: Path, require_fqdn: bool) -> Dict[str, str]:
    """Detect PUBLIC_FQDN/PUBLIC_IP with S2.7 refined precedence (CIU-47).

    ``env generate`` is the identity-computation verb: PUBLIC_FQDN is derived
    from THIS workspace's own inputs — the rendered global config's
    ``infrastructure.public_fqdn`` first, else reverse DNS of the detected
    public IP — and an ambient ``PUBLIC_FQDN`` (a shell that sourced another
    checkout's ``ciu.env`` carries that checkout's value) is adopted only
    when CONSISTENT with what this workspace derives. On a real mismatch the
    derived value wins and a stderr warning names the ignored ambient value
    — the same refined precedence S2.7 applies to ``PHYSICAL_REPO_ROOT`` and
    the identity tuple (CIU-41).

    One deliberate exception, mirroring the mountinfo precedent: when the
    detection path yields NO independently sourced value (no config entry,
    and reverse DNS produced nothing — e.g. an offline host), there is no
    basis to override an explicit pre-set value, so the ambient FQDN is kept
    silently. It remains the legitimate manual-override mechanism there.
    The bare ``os.environ.get("PUBLIC_FQDN", ...)`` fallback this replaces
    adopted the ambient value unconditionally, with no consistency check —
    a main checkout's sourced ``ciu.env`` leaked its FQDN into a fresh
    worktree's generated record (CIU-47).

    ``PUBLIC_IP`` and the TLS paths keep the plain S2.7 pre-set-wins reads;
    they are not part of the filed CIU-47 scope.
    """
    ambient_fqdn = os.environ.get("PUBLIC_FQDN") or ""
    public_ip = os.environ.get("PUBLIC_IP", "")

    # -- Derive from THIS workspace's own inputs first (CIU-47) ------------
    # `derived` is None until a value with a real source behind it exists.
    derived: Optional[str] = None

    ciu_global = repo_root / GLOBAL_CONFIG_RENDERED
    if ciu_global.exists():
        try:
            import tomllib

            with ciu_global.open("rb") as f:
                config = tomllib.load(f)
            configured = config.get("infrastructure", {}).get("public_fqdn", "")
            if isinstance(configured, str) and configured:
                derived = configured
        except (tomllib.TOMLDecodeError, OSError, KeyError, AttributeError, TypeError) as exc:
            _log_warn(f"Could not parse {ciu_global}: {exc}")

    if not public_ip:
        try:
            with urllib.request.urlopen("https://api.ipify.org", timeout=10) as resp:
                public_ip = resp.read().decode("utf-8").strip()
        except (urllib.error.URLError, TimeoutError):
            public_ip = ""

    if derived is None and public_ip:
        try:
            derived = socket.gethostbyaddr(public_ip)[0]
        except (socket.herror, socket.gaierror):
            derived = None

    # -- Reconcile with the ambient value (S2.7 refined precedence) --------
    if ambient_fqdn:
        if derived is not None and derived != ambient_fqdn:
            print(
                f"ciu: ignoring pre-set PUBLIC_FQDN={ambient_fqdn!r} during "
                f"env generate — inconsistent with the value derived for "
                f"this workspace ({derived!r}). The derived value is written "
                "to ciu.env (the pre-set env is likely stale/cross-workspace "
                "shell state, e.g. inherited from another checkout's sourced "
                "ciu.env).",
                file=sys.stderr,
            )
            public_fqdn = derived
        else:
            # Consistent, or no independently derived value to compare
            # against — the pre-set value stands (manual override).
            public_fqdn = ambient_fqdn
    else:
        public_fqdn = derived or ""

    if not public_fqdn:
        if require_fqdn:
            raise WorkspaceEnvError("Failed to detect PUBLIC_FQDN. Set PUBLIC_FQDN in the environment.")
        public_fqdn = public_ip or "localhost"

    return {
        "PUBLIC_IP": public_ip,
        "PUBLIC_FQDN": public_fqdn,
        "PUBLIC_TLS_CRT_PEM": os.environ.get("PUBLIC_TLS_CRT_PEM", ""),
        "PUBLIC_TLS_KEY_PEM": os.environ.get("PUBLIC_TLS_KEY_PEM", ""),
    }


def _detect_docker_gid() -> str:
    docker_gid = os.environ.get("DOCKER_GID", "")
    # S2.5: '0' is a valid value — do not reject on falsy check
    if docker_gid is not None and docker_gid != "":
        return docker_gid

    for socket_path in ("/var/run/docker-host.sock", "/var/run/docker.sock"):
        if Path(socket_path).exists():
            return str(Path(socket_path).stat().st_gid)

    try:
        import grp

        return str(grp.getgrnam("docker").gr_gid)
    except KeyError:
        raise WorkspaceEnvError("DOCKER_GID not found. Ensure docker group exists or set DOCKER_GID.")


def _detect_governance_read_iops() -> tuple[str, str]:
    """S15.6 — derive ``CIU_GOV_READ_IOPS`` for the ``ciu env generate`` phase.

    A pre-set environment value always wins (S2.7 — every ciu.env key is
    autodetected, but an already-set value is never overridden). Otherwise
    delegates to :func:`ciu.governance.derive_read_iops` with ``configured=0``
    (always "derive" here — ciu.env is the machine-identity layer, S2.7; the
    per-stack ``read_iops``/``baseline_path`` overrides are handled directly
    by the overlay generator, which re-derives independently so governance
    still works without an env regen). Derivation follows the S15.4 baseline
    search order: env ``CIU_GOV_BASELINE_PATH`` →
    ``/var/lib/ciu/io-baseline.env`` → mdt host-setup's
    ``/var/lib/mdt/io-baseline.env``; first existing file wins.

    Returns ``(value_str, source_note)`` — the note is folded into the emitted
    comment so ``ciu.env`` documents where the number came from.
    """
    preset = os.environ.get("CIU_GOV_READ_IOPS")
    if preset is not None and preset != "":
        return preset, "explicit (pre-set in environment)"
    value, note = governance_mod.derive_read_iops(0)
    return str(value), note


# Contract 1 (P-physical-root-mount-table): this process's own mount table.
# Overridable per-call for tests; referenced as a bare module global (not a
# function-default) inside _physical_root_from_mountinfo so monkeypatching
# `ciu.workspace_env._MOUNTINFO_PATH` takes effect without needing to thread
# the path through every caller.
_MOUNTINFO_PATH = Path("/proc/self/mountinfo")


def _unescape_mountinfo_path(value: str) -> str:
    """Decode the pathname escapes mandated by ``proc(5)`` mountinfo.

    The mount table separates fields on spaces, so its path fields encode a
    literal space, tab, newline, and backslash as octal escapes.  Treating the
    encoded spelling as a ``Path`` makes a bind mount below a directory with a
    space invisible to the longest-prefix lookup, and CIU then falls back to a
    potentially unrelated devcontainer label.  Decode exactly one mountinfo
    escape level; a literal ``\\040`` in a path must not be decoded twice.
    """
    escapes = {"040": " ", "011": "\t", "012": "\n", "134": "\\"}
    return re.sub(r"\\(040|011|012|134)", lambda match: escapes[match.group(1)], value)


def _parse_mountinfo(text: str) -> list[tuple[Path, Path]]:
    """Parse ``/proc/self/mountinfo`` into ``(mount_point, mount_root)`` pairs.

    Format (``man 5 proc``): each line's fixed fields before the literal
    ``" - "`` separator are ``mount_id parent_id major:minor root mount_point
    mount_opts``, followed by zero or more optional ``tag:value`` fields.
    ``root`` and ``mount_point`` sit at fixed indices (3, 4) regardless of how
    many optional fields trail them, so this is safe without locating the
    separator for those two fields.

    For a bind mount, ``root`` is the sub-path of the underlying filesystem
    exposed at ``mount_point`` — e.g. a devcontainer bind-mounting
    ``/home/vb/volkb79-2/vbpub`` (host) at ``/workspaces/vbpub`` (container)
    reports ``root=/home/vb/volkb79-2/vbpub mount_point=/workspaces/vbpub``.
    That ``root`` value is exactly the physical (host) path we want.

    The root mount itself (``mount_point == "/"``) is skipped: it carries no
    per-repo bind-mount signal (its ``root`` is meaningless overlay/rootfs
    plumbing, not a host path), so it must never win a longest-match contest.
    """
    entries: list[tuple[Path, Path]] = []
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        if " - " not in line:
            continue
        left = line.split(" - ", 1)[0]
        fields = left.split()
        if len(fields) < 5:
            continue
        mount_root = _unescape_mountinfo_path(fields[3])
        mount_point = _unescape_mountinfo_path(fields[4])
        if mount_point == "/":
            continue
        entries.append((Path(mount_point), Path(mount_root)))
    return entries


def _physical_root_from_mountinfo(repo_root: Path) -> Optional[Path]:
    """Contract 1 — longest mount-destination-prefix match via mountinfo.

    Ports the longest-match algorithm from tls-edge's ``physical_path()``
    (``tls-edge/scripts/render_standalone.py``): for *repo_root*, find the
    mount whose destination is the LONGEST prefix of ``repo_root.resolve()``
    and map through its source. The port reads THIS process's own mount table
    (``/proc/self/mountinfo``) instead of shelling out to ``docker inspect``
    for another container's Mounts — tls-edge inspects a named sibling
    container; here we only ever need our own view.

    Returns ``None`` when mountinfo is unreadable or yields no match, so the
    caller can fall through to the next candidate (Contract 2).
    """
    try:
        text = _MOUNTINFO_PATH.read_text(encoding="utf-8")
    except OSError:
        return None

    resolved = repo_root.resolve()
    best_dest: Optional[Path] = None
    best_root: Optional[Path] = None
    for dest, root in _parse_mountinfo(text):
        if (dest == resolved or dest in resolved.parents) and (
            best_dest is None or len(dest.parts) > len(best_dest.parts)
        ):
            best_dest, best_root = dest, root

    if best_dest is None or best_root is None:
        return None
    return best_root / resolved.relative_to(best_dest)


def _detect_physical_repo_root(repo_root: Path) -> Path:
    """Contract precedence (SPEC.md S2.7): pre-set env (when consistent) ->
    mountinfo -> docker-ps devcontainer-origin label -> identity.

    A pre-set ``PHYSICAL_REPO_ROOT`` is a legitimate manual-override
    mechanism (native host, mountinfo unreadable, deliberate remap) — but it
    is ALSO an inherited-shell-state contamination vector: a devcontainer's
    login shell may `source` one repo's ``ciu.env`` (e.g. via a
    ``REPO_ROOT``-triggered ``.bashrc`` hook for the devcontainer's primary
    workspace) and leave a stale ``PHYSICAL_REPO_ROOT`` in the environment
    when the same shell later operates on an unrelated, nested repo (2026-07
    live bug: dstdns's ``PHYSICAL_REPO_ROOT`` leaking into a
    ``ciu env generate`` run for ``vbpub/nyxloom``, corrupting its
    ``PHYSICAL_REPO_ROOT`` / ``REPO_NAME`` / network identity).

    Refined contract: the pre-set value wins ONLY when it is CONSISTENT with
    this process's own mountinfo-derived physical root for *repo_root* (or
    when mountinfo yields nothing to check against — mountinfo is our only
    independent signal, so absent it we have no basis to override the
    explicit env). When mountinfo yields a DIFFERENT physical root, that
    mountinfo value is trusted instead (it reflects an actual bind mount for
    THIS repo_root, not inherited shell state) and a warning is emitted.
    """
    physical_root = os.environ.get("PHYSICAL_REPO_ROOT")
    preset_path = Path(physical_root).resolve() if physical_root else None

    via_mountinfo = _physical_root_from_mountinfo(repo_root)

    if preset_path is not None:
        if via_mountinfo is None or via_mountinfo == preset_path:
            return preset_path
        print(
            f"ciu: ignoring pre-set PHYSICAL_REPO_ROOT={preset_path} for "
            f"repo_root={repo_root} — inconsistent with the mountinfo-derived "
            f"physical root {via_mountinfo}. Using the mountinfo-derived value "
            "(the pre-set env is likely stale/cross-repo shell state, e.g. "
            "inherited from a different repo's sourced ciu.env). Unset "
            "PHYSICAL_REPO_ROOT or update it if this override is intentional.",
            file=sys.stderr,
        )
        return via_mountinfo

    if via_mountinfo is not None:
        return via_mountinfo

    # Contract 2 fallback (mountinfo yielded nothing): existing
    # devcontainer-origin behavior. NOTE: this label reflects the CONTAINER's
    # own origin, not necessarily repo_root — it is a same-value-for-every-
    # repo_root fallback, kept only for parity with pre-existing behavior
    # when mountinfo is unavailable (e.g. not readable, non-Linux).
    try:
        result = subprocess.run(
            ["docker", "ps", "--format", "{{.Label \"devcontainer.local_folder\"}}"],
            capture_output=True,
            text=True,
            check=False,
        )
        # A failed ``docker ps`` cannot establish a physical-root identity.
        # Docker may still put diagnostics (or incomplete template output) on
        # stdout when its daemon/socket is unavailable; treating that as a
        # bind-mount source would make a transient daemon failure select an
        # unrelated repository path.
        if result.returncode == 0:
            for line in result.stdout.splitlines():
                candidate = line.strip()
                if candidate:
                    return Path(candidate).resolve()
    except FileNotFoundError:
        pass

    # Contract 2 final fallback / S1.9: on native host PHYSICAL_REPO_ROOT == REPO_ROOT
    return repo_root.resolve()


def _detect_host_mdt_tmp() -> str:
    """Host path of the persisted /tmp bind mount (mdt devcontainer convention).

    Sibling containers launched on the host Docker daemon (e.g. the test-runner) must bind the SAME
    host dir the devcontainer mounts at /tmp, so /tmp-based git worktrees are visible to them.
    Autodetected like PHYSICAL_REPO_ROOT: an explicit env override wins; otherwise inspect THIS
    container's own /tmp bind-mount source. Empty when /tmp is not a host bind mount (e.g. native host).
    """
    explicit = os.environ.get("HOST_MDT_TMP")
    if explicit:
        return explicit
    container = os.environ.get("DEVCONTAINER_NAME") or os.environ.get("HOSTNAME", "")
    if container:
        try:
            result = subprocess.run(
                ["docker", "inspect", container, "--format",
                 '{{ range .Mounts }}{{ if eq .Destination "/tmp" }}{{ .Source }}{{ end }}{{ end }}'],
                capture_output=True,
                text=True,
                check=False,
            )
            # An inspect failure has no trustworthy mount value, even if a
            # wrapper happened to emit text on stdout.
            if result.returncode == 0:
                src = result.stdout.strip()
                if src:
                    return src
        except FileNotFoundError:
            pass
    return ""


def _compute_network_name(physical_root: Path) -> Dict[str, str]:
    """Derive the identity tuple for THIS physical root (S2.7, CIU-41).

    Every value is derived from *physical_root* alone. Ambient environment
    values are NEVER adopted: ``env generate`` is the identity-computation
    verb, and its output (ciu.env) is the record every later ciu command
    trusts — an inherited ``DOCKER_NETWORK_INTERNAL`` from a shell that
    sourced a DIFFERENT checkout's ciu.env would silently point this
    workspace at that checkout's network (the masked-default defect behind
    dstdns P111 F2). The same refined precedence S2.7 applies to
    PHYSICAL_REPO_ROOT is mirrored here for the whole tuple: a pre-set value
    wins only when CONSISTENT with the derived one; on mismatch the derived
    value is used and a warning names the ignored ambient value.
    """
    repo_name = physical_root.name.lower()
    instance_id = hashlib.sha256(str(physical_root).encode("utf-8")).hexdigest()[:6]
    network_name = f"{repo_name}-{instance_id}-network"
    derived = {
        "REPO_NAME": repo_name,
        "INSTANCE_ID": instance_id,
        "DOCKER_NETWORK_INTERNAL": network_name,
    }
    _warn_inconsistent_ambient("REPO_NAME", repo_name)
    _warn_inconsistent_ambient("INSTANCE_ID", instance_id)
    _warn_inconsistent_ambient(
        "DOCKER_NETWORK_INTERNAL",
        network_name,
        remedy=(
            "To reuse another instance's running infra, use "
            "`ciu worktree add --shared-infra` (SPEC S16.1) instead of "
            "inheriting its network name."
        ),
    )
    return derived


def _warn_inconsistent_ambient(key: str, derived: str, *, remedy: str = "") -> None:
    """Warn when an ambient identity value disagrees with the derived one.

    A consistent pre-set value is silent (it changes nothing); a mismatched
    one is reported and IGNORED — never adopted (CIU-41 / S2.7 refined
    precedence extended to the derived identity tuple).
    """
    ambient = os.environ.get(key)
    if not ambient or ambient == derived:
        return
    message = (
        f"ciu: ignoring pre-set {key}={ambient!r} during env generate — "
        f"inconsistent with the value derived for this repo root ({derived!r}). "
        "The derived value is written to ciu.env (the pre-set env is likely "
        "stale/cross-workspace shell state, e.g. inherited from another "
        "checkout's sourced ciu.env)."
    )
    if remedy:
        message += f" {remedy}"
    print(message, file=sys.stderr)


