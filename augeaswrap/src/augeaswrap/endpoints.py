_KEY_RE = re.compile(r"[A-Z][A-Z0-9_]{0,63}")
_VALUE_RE = re.compile(r"[A-Za-z0-9_./:@+-]{1,4096}")
_WRITER_TOKEN_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.:/+-]*")
_MARKER_RE = re.compile(r"[a-z][a-z0-9-]{0,62}")
_OUTSIDE_KEY_RE = re.compile(rb"^[ \t]*(?:export[ \t]+)?([A-Z][A-Z0-9_]{0,63})[ \t]*=")
# Variables that change how every login shell, ssh, sudo, su or cron session
# behaves (pam_env applies /etc/environment to all of them) or that a POSIX
