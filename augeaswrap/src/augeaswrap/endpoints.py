"""Publish host-owned endpoint facts as fragments and a shared environment file.

The record format is intentionally shell, pam_env, systemd EnvironmentFile,
and Docker env-file compatible. Runtime endpoint defaults belong to the
service that owns an endpoint; this module only publishes the facts it is
given.

Layout (all root-owned, written atomically, serialised by one flock)::

    /etc/host-endpoints.d/<owner>.env   one fragment per owner (0644)
    /etc/host-endpoints.d/.lock         writer lock (0600)
    /etc/host-endpoints.env             aggregate of all fragments (0644)
    /etc/environment                    managed block holding the aggregate
    /etc/profile.d/host-endpoints.sh    exports the aggregate for login shells

The module is split so Augeaswrap's future transaction runner can reuse it: ``render``
and ``render_block`` are pure (bytes in, bytes out), ``publish``/``withdraw``
apply a rendered plan under the lock, and the filesystem primitives live in
``augeaswrap._fs`` with the lock path as a parameter.

``/etc/environment`` is shared with other managed blocks (host-setup's
``mdt-buildkit`` block). Every writer takes the lock of its own resource
and rewrites only the lines between its own ``# BEGIN <marker>`` and
``# END <marker>`` lines, so two blocks coexist; a writer of a different
block must hold this module's lock (``/etc/host-endpoints.d/.lock``) while it
rewrites ``/etc/environment`` to avoid a lost update.
"""

