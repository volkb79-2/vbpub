@dataclass(frozen=True)
class EndpointFragment:
    owner: str
    writer: str
    entries: dict[str, str]


class CheckResult(list):
    """Problems found by :func:`check`, plus a one-line status and message.

    It is a plain ``list`` of :class:`Problem` records (empty when the host
    is consistent). A host where nothing was ever published is clean with the
    message ``no endpoints published``.
    """

    def __init__(self, problems: Iterable[Problem] = (), *, message: str | None = None):
        super().__init__(problems)
        self.status = "problems" if self else "clean"
        if message is None:
            message = (
                f"{len(self)} problem(s) found"
                if self
                else "host endpoint records are consistent"
            )
        self.message = message


def _problem(
    code: str,
    message: str,
    *,
    path: str | None = None,
    owner: str | None = None,
    key: str | None = None,
) -> Problem:
    return Problem(code=code, message=message, path=path, owner=owner, key=key)


def _failure_problem(exc: CliFailure, *, owner: str | None = None) -> Problem:
    kind = getattr(exc, "kind", None)
    return _problem(
        f"endpoint.path.{kind}" if kind else "endpoint.path.refused",
        str(exc),
        path=getattr(exc, "path", None),
        owner=owner,
    )


def _io_problem(message: str, *, path: str | None = None) -> Problem:
    return _problem("endpoint.io.error", message, path=path)


def _root_path(root: str | os.PathLike[str]) -> Path:
    """Return a lexical absolute fake-root path without following symlinks."""

    raw = os.fspath(root)
    if not isinstance(raw, str) or not raw:
        raise CliFailure("root must be a non-empty filesystem path", exit_code=2)
    path = Path(os.path.abspath(raw))
    try:
        mode = path.lstat().st_mode
    except FileNotFoundError as exc:
        raise CliFailure(f"root directory does not exist: {path}", exit_code=2) from exc
    if stat.S_ISLNK(mode):
        raise CliFailure(f"refusing symlinked root directory: {path}", exit_code=2)
    if not stat.S_ISDIR(mode):
        raise CliFailure(f"root is not a directory: {path}", exit_code=2)
    return path


def _root_problem(exc: CliFailure) -> Problem:
    return _problem("endpoint.root.invalid", str(exc))


def _path(root: Path, absolute: str) -> Path:
    return root / absolute.lstrip("/")


def _exists(path: Path) -> bool:
    try:
        path.lstat()
    except FileNotFoundError:
        return False
    except OSError:
        return True
    return True


def _owner_problem(owner: object) -> Problem | None:
    try:
        validate_owner(owner)
    except ValueError as exc:
        return _problem(
            "endpoint.owner.invalid", str(exc), owner=owner if isinstance(owner, str) else None
        )
    return None


def _writer_message(writer: object) -> str | None:
    if not isinstance(writer, str) or len(writer) > 256:
        return "writer must contain a verb and version on one line"
    words = writer.split(" ")
    if len(words) < 2 or any(_WRITER_TOKEN_RE.fullmatch(word) is None for word in words):
        return "writer must contain a verb and version on one line"
    return None


def _writer_problem(writer: object) -> Problem | None:
    message = _writer_message(writer)
    return None if message is None else _problem("endpoint.writer.invalid", message)


def _entry_problem(message: str, *, key: str | None = None) -> Problem:
    return _problem("endpoint.entry.invalid", message, key=key)


def _entries_map(entries: object) -> tuple[dict[str, str], list[Problem]]:
    problems: list[Problem] = []
    if isinstance(entries, Mapping):
        items: Iterable[object] = entries.items()
    elif isinstance(entries, Iterable) and not isinstance(entries, (str, bytes)):
        items = entries
    else:
        return {}, [_entry_problem("entries must be a mapping or an iterable of key/value pairs")]

    result: dict[str, str] = {}
    for index, item in enumerate(items, start=1):
        if isinstance(item, (str, bytes)):
            problems.append(_entry_problem(f"entry {index} must be a key/value pair"))
            continue
        try:
            pair = tuple(item)  # type: ignore[arg-type]
        except TypeError:
            problems.append(_entry_problem(f"entry {index} must be a key/value pair"))
            continue
        if len(pair) != 2:
            problems.append(_entry_problem(f"entry {index} must contain exactly one key and value"))
            continue
        key, value = pair
        if not isinstance(key, str) or _KEY_RE.fullmatch(key) is None:
            problems.append(_entry_problem(f"entry {index} has an invalid key {key!r}"))
            continue
        if _is_reserved(key):
            problems.append(
                _problem(
                    "endpoint.key.reserved",
                    f"entry {index} uses reserved environment key {key}; "
                    "choose a service-specific key",
                    key=key,
                )
            )
            continue
        if not isinstance(value, str) or _VALUE_RE.fullmatch(value) is None:
            problems.append(_entry_problem(f"entry {index} has an invalid value for {key}", key=key))
            continue
        if key in result:
            problems.append(_entry_problem(f"entry {index} duplicates key {key}", key=key))
            continue
        result[key] = value
    if not result and not problems:
        problems.append(_entry_problem("at least one endpoint entry is required"))
    return result, problems


def _fragment_path(root: Path, owner: str) -> Path:
    return _path(root, f"/etc/host-endpoints.d/{owner}.env")


def _lock_path(root: Path) -> Path:
    return _path(root, "/etc/host-endpoints.d/.lock")


def _fragment_bytes(fragment: EndpointFragment) -> bytes:
    lines = [
        _VERSION.decode("ascii"),
        f"# owner={fragment.owner}",
        f"# writer={fragment.writer}",
    ]
    lines.extend(f"{key}={fragment.entries[key]}" for key in sorted(fragment.entries))
    return ("\n".join(lines) + "\n").encode("ascii")


def _aggregate_bytes(fragments: Mapping[str, EndpointFragment]) -> bytes:
    lines = [_VERSION.decode("ascii")]
    for owner in sorted(fragments):
        fragment = fragments[owner]
        lines.extend((f"# owner={owner}", f"# writer={fragment.writer}"))
        lines.extend(f"{key}={fragment.entries[key]}" for key in sorted(fragment.entries))
    return ("\n".join(lines) + "\n").encode("ascii")


def _line_body(line: bytes) -> bytes:
    if line.endswith(b"\n"):
        line = line[:-1]
    if line.endswith(b"\r"):
        line = line[:-1]
    return line


def _marker_lines(
    marker_name: str, begin_line: str | None = None
) -> tuple[bytes, bytes, bytes, bytes]:
    """Return BEGIN line, END line, BEGIN prefix and END prefix for one block."""

    if not isinstance(marker_name, str) or _MARKER_RE.fullmatch(marker_name) is None:
        raise ValueError("marker_name must match ^[a-z][a-z0-9-]{0,62}$")
    begin_prefix = f"# BEGIN {marker_name}"
    end = f"# END {marker_name}"
    begin = begin_line or (
        f"{begin_prefix} (generated by cli_extended.hostcfg.endpoints; do not edit)"
    )
    if not begin.startswith(begin_prefix) or "\n" in begin or "\r" in begin:
        raise ValueError("begin_line must be one marker line for marker_name")
    return (
        begin.encode("ascii"),
        end.encode("ascii"),
        begin_prefix.encode("ascii"),
        end.encode("ascii"),
    )


def _environment_parts(
    data: bytes,
    *,
    marker_name: str = _DEFAULT_MARKER,
    begin_line: str | None = None,
) -> tuple[bytes, bytes | None, list[str]]:
    """Return unmanaged bytes, generated payload, and selected-block defects.

    The block is always written last and every line of it, END included, ends
    with a newline, so a later ``echo X >> /etc/environment`` never glues onto
    a marker. When the file it was added to had no final newline, the END line
    reads ``# END <marker> (no final newline)``: removing a block that is still
    last then returns the original bytes exactly.
    """

    begin_marker, end_marker, begin_prefix, end_prefix = _marker_lines(marker_name, begin_line)
    end_no_newline = end_marker + _NO_FINAL_NEWLINE
    lines = data.splitlines(keepends=True)
    begins: list[int] = []
    ends: list[int] = []
    glued: list[int] = []
    problems: list[str] = []
    for index, line in enumerate(lines):
        body = _line_body(line)
        if body == begin_prefix or body.startswith(begin_prefix + b" "):
            if body == begin_marker:
                begins.append(index)
            else:
                problems.append("malformed BEGIN marker")
        if body in (end_marker, end_no_newline):
            ends.append(index)
        elif body.startswith(end_no_newline):
            glued.append(index + 1)
        elif body.startswith(end_prefix + b" "):
            problems.append("malformed END marker")
        elif body.startswith(end_prefix):
            glued.append(index + 1)
    if len(begins) > 1:
        problems.append("more than one BEGIN marker")
    if len(ends) > 1:
        problems.append("more than one END marker")
    if ends and (not begins or ends[0] < begins[0]):
        problems.append("END marker before its BEGIN")
    if begins and not ends:
        hint = (
            f" (line {glued[0]} starts with the END marker but has text glued after it; "
            "put the marker alone on its line)"
            if glued
            else ""
        )
        problems.append("BEGIN marker without END" + hint)
    if ends and not begins:
        problems.append("END marker without BEGIN")
    if problems:
        return data, None, problems
    if not begins:
        return data, None, []
    begin = begins[0]
    end = ends[0]
    before = b"".join(lines[:begin])
    after = b"".join(lines[end + 1 :])
    if not after and _line_body(lines[end]) == end_no_newline:
        # This byte separated the originally unterminated line from our block.
        # Keep it whenever a later block exists, or that block's BEGIN marker
        # would be joined to the unmanaged line during withdrawal.
        before = before[:-1]
    payload = b"".join(lines[begin + 1 : end])
    return before + after, payload, []


def _outside_keys(unmanaged: bytes) -> set[str]:
    found: set[str] = set()
    for line in unmanaged.splitlines():
        match = _OUTSIDE_KEY_RE.match(line)
        if match is not None:
            found.add(match.group(1).decode("ascii"))
    return found


def render_block(
    current: bytes,
    payload: bytes,
    keys: Iterable[str],
    *,
    marker_name: str = _DEFAULT_MARKER,
    begin_line: str | None = None,
) -> bytes:
    """Return ``current`` with one managed block set to ``payload`` (pure).

    The block is removed when ``keys`` is empty. Raises ``CliFailure`` when the
    block markers are damaged or a key is already assigned outside the block.
    """

    keys = set(keys)
    begin_marker, end_marker, _bp, _ep = _marker_lines(marker_name, begin_line)
    unmanaged, _old, problems = _environment_parts(
        current, marker_name=marker_name, begin_line=begin_line
    )
    if problems:
        raise CliFailure(_format_problems("environment block preflight", problems), exit_code=2)
    duplicates = sorted(_outside_keys(unmanaged) & keys)
    if duplicates:
        raise CliFailure(
            _format_problems(
                "environment block preflight",
                [_duplicate_message(key, marker_name, "/etc/environment") for key in duplicates],
            ),
            exit_code=2,
        )
    if not keys:
        return unmanaged
    if unmanaged and not unmanaged.endswith(b"\n"):
        return (
            unmanaged + b"\n" + begin_marker + b"\n" + payload
            + end_marker + _NO_FINAL_NEWLINE + b"\n"
        )
    return unmanaged + begin_marker + b"\n" + payload + end_marker + b"\n"


def _duplicate_message(key: str, marker_name: str, shown: str) -> str:
    return (
        f"{key} is already set outside the {marker_name} block in {shown}; "
        "remove the unmanaged assignment before publishing"
    )


def _read_file(root: Path, path: Path) -> bytes | None:
    info = _fs.regular_or_missing(root, path)
    if info is None:
        return None
    return path.read_bytes()


def _read_optional(root: Path, path: Path) -> bytes | None:
    try:
        return _read_file(root, path)
    except (CliFailure, OSError):
        return None


def _parse_fragment(
    root: Path, owner: str, path: Path
) -> tuple[EndpointFragment | None, list[Problem]]:
    shown = _fs.display(path, root)

    def bad(message: str, *, code: str = "endpoint.fragment.invalid", key: str | None = None):
        return _problem(code, message, path=shown, owner=owner, key=key)

    try:
        data = _read_file(root, path)
    except CliFailure as exc:
        return None, [_failure_problem(exc, owner=owner)]
    except OSError as exc:
        return None, [bad(str(exc), code="endpoint.io.error")]
    if data is None:
        return None, [
            bad(f"missing fragment for owner {owner!r}: {shown}", code="endpoint.fragment.missing")
        ]
    try:
        lines = data.decode("ascii").splitlines()
    except UnicodeDecodeError:
        return None, [bad(f"fragment for owner {owner!r} is not ASCII")]
    if len(lines) < 3 or lines[0].encode("ascii") != _VERSION:
        return None, [bad(f"fragment for owner {owner!r} has an invalid header")]
    problems: list[Problem] = []
    if lines[1] != f"# owner={owner}":
        problems.append(bad(f"fragment {shown} declares owner {lines[1]!r}, expected {owner!r}"))
    if not lines[2].startswith("# writer="):
        return None, problems + [bad(f"fragment for owner {owner!r} has no writer header")]
    writer = lines[2][len("# writer=") :]
    writer_message = _writer_message(writer)
    if writer_message is not None:
        problems.append(bad(f"fragment for owner {owner!r}: {writer_message}"))
    entries: dict[str, str] = {}
    for number, line in enumerate(lines[3:], start=4):
        key, separator, value = line.partition("=")
        if not separator or _KEY_RE.fullmatch(key) is None:
            problems.append(bad(f"fragment for owner {owner!r} has an invalid entry on line {number}"))
            continue
        if _is_reserved(key):
            problems.append(
                bad(f"fragment for owner {owner!r} uses reserved environment key {key}", key=key)
            )
            continue
        if _VALUE_RE.fullmatch(value) is None:
            problems.append(bad(f"fragment for owner {owner!r} has an invalid value for {key}", key=key))
            continue
        if key in entries:
            problems.append(bad(f"fragment for owner {owner!r} duplicates key {key}", key=key))
            continue
        entries[key] = value
    if not entries:
        problems.append(bad(f"fragment for owner {owner!r} has no endpoint entries"))
    fragment = EndpointFragment(owner=owner, writer=writer, entries=entries)
    if not problems and data != _fragment_bytes(fragment):
        problems.append(
            bad(
                f"fragment for owner {owner!r} is not in canonical format",
                code="endpoint.fragment.noncanonical",
            )
        )
    return (fragment if not problems else None), problems


def _collisions(fragments: Mapping[str, EndpointFragment], root: Path) -> list[Problem]:
    problems: list[Problem] = []
    owners_by_key: dict[str, str] = {}
    for owner in sorted(fragments):
        for key in sorted(fragments[owner].entries):
            previous = owners_by_key.setdefault(key, owner)
            if previous != owner:
                first = _fs.display(_fragment_path(root, previous), root)
                second = _fs.display(_fragment_path(root, owner), root)
                problems.append(
                    _problem(
                        "endpoint.key.collision",
                        f"key {key} is declared by both owner {previous!r} ({first}) and "
                        f"owner {owner!r} ({second})",
                        owner=owner,
                        key=key,
                    )
                )
    return problems


def _load_fragments(
    root: Path,
    *,
    skip_owner: str | None = None,
    tolerate_invalid: bool = False,
    skipped_fragments: list[Problem] | None = None,
) -> tuple[dict[str, EndpointFragment], list[Problem]]:
    """Load every fragment; with ``tolerate_invalid`` damaged ones are skipped.

    Damage in one owner's fragment (or a stray entry) must not block another
    owner's publish or withdraw; ``check`` still reports it.
    """

    directory = _path(root, "/etc/host-endpoints.d")
    try:
        _fs.safe_components(root, directory)
        info = directory.lstat()
    except FileNotFoundError:
        return {}, []
    except CliFailure as exc:
        return {}, [_failure_problem(exc)]
    shown = _fs.display(directory, root)
    if not stat.S_ISDIR(info.st_mode):
        return {}, [
            _problem(
                "endpoint.path.type", f"managed directory is not a directory: {shown}", path=shown
            )
        ]

    fragments: dict[str, EndpointFragment] = {}
    problems: list[Problem] = []
    try:
        children = sorted(directory.iterdir(), key=lambda child: child.name)
    except OSError as exc:
        return {}, [_io_problem(f"cannot read {shown}: {exc}", path=shown)]
    for path in children:
        name = path.name
        if name == ".lock" or name.startswith(_TEMP_PREFIX):
            continue
        if not name.endswith(".env"):
            if not tolerate_invalid:
                problems.append(
                    _problem(
                        "endpoint.entry.unexpected",
                        f"unexpected entry in {shown}: {name}",
                        path=f"{shown}/{name}",
                    )
                )
            continue
        owner = name[:-4]
        owner_problem = _owner_problem(owner)
        if owner_problem is not None:
            if not tolerate_invalid:
                problems.append(
                    _problem(
                        "endpoint.owner.invalid",
                        f"invalid fragment filename {name!r}: {owner_problem}",
                        path=f"{shown}/{name}",
                    )
                )
            continue
        if owner == skip_owner:
            continue
        fragment, fragment_problems = _parse_fragment(root, owner, path)
        if not tolerate_invalid:
            problems.extend(fragment_problems)
        elif fragment_problems and skipped_fragments is not None:
            skipped_fragments.extend(fragment_problems)
        if fragment is not None:
            fragments[owner] = fragment
    problems.extend(_collisions(fragments, root))
    return fragments, problems


def _owner_fragment_problems(root: Path, owner: str) -> list[Problem]:
    """Refuse an unsafe target for the owner's own fragment (symlink, not a file).

    The content is deliberately not parsed: publish replaces the whole
    fragment and withdraw deletes it, so a hand-edited or damaged fragment of
    the same owner is healed by re-running the install verb. ``check`` keeps
    reporting the damage until the replacement lands.
    """

    try:
        _fs.regular_or_missing(root, _fragment_path(root, owner))
    except CliFailure as exc:
        return [_failure_problem(exc, owner=owner)]
    return []


def _environment_bytes(root: Path) -> bytes:
    data = _read_file(root, _path(root, "/etc/environment"))
    return b"" if data is None else data


def _environment_state(root: Path) -> tuple[bytes, list[Problem]]:
    path = _path(root, "/etc/environment")
    shown = _fs.display(path, root)
    try:
        data = _environment_bytes(root)
    except CliFailure as exc:
        return b"", [_failure_problem(exc)]
    except OSError as exc:
        return b"", [_io_problem(str(exc), path=shown)]
    unmanaged, _payload, marker_problems = _environment_parts(data)
    return unmanaged, [
        _problem("endpoint.environment.block", message, path=shown) for message in marker_problems
    ]


def _preflight_unlocked(
    root: Path,
    owner: str,
    entries: Mapping[str, str],
    *,
    allow_empty: bool = False,
    skipped_fragments: list[Problem] | None = None,
) -> list[Problem]:
    problems: list[Problem] = []
    fragments, fragment_problems = _load_fragments(
        root,
        skip_owner=owner,
        tolerate_invalid=True,
        skipped_fragments=skipped_fragments,
    )
    problems.extend(fragment_problems)
    problems.extend(_owner_fragment_problems(root, owner))
    if not allow_empty and not entries:
        problems.append(_entry_problem("at least one endpoint entry is required"))
    prospective = dict(fragments)
    if entries:
        prospective[owner] = EndpointFragment(owner, "preflight 0", dict(entries))
    for collision in _collisions(prospective, root):
        if collision not in problems:
            problems.append(collision)

    unmanaged, environment_problems = _environment_state(root)
    problems.extend(environment_problems)
    if not environment_problems:
        managed = {key for fragment in prospective.values() for key in fragment.entries}
        shown = _fs.display(_path(root, "/etc/environment"), root)
        for key in sorted(_outside_keys(unmanaged) & managed):
            problems.append(
                _problem(
                    "endpoint.environment.duplicate",
                    _duplicate_message(key, _DEFAULT_MARKER, shown),
                    path=shown,
                    key=key,
                )
            )

    for target in (
        _path(root, "/etc/host-endpoints.env"),
        _path(root, "/etc/profile.d/host-endpoints.sh"),
    ):
        try:
            _fs.regular_or_missing(root, target)
        except CliFailure as exc:
            problems.append(_failure_problem(exc))
    return problems


def _format_problems(action: str, problems: Iterable[object]) -> str:
    lines = [f"{action} refused:"]
    lines.extend(f"- {problem}" for problem in problems)
    return "\n".join(lines)


@contextmanager
def _exclusive_lock(root: Path) -> Iterator[bool]:
    with _fs.lock(
        root, _lock_path(root), exclusive=True, create=True, mode=_LOCK_MODE
    ) as held:
        yield held


@contextmanager
def _shared_lock(root: Path) -> Iterator[bool]:
    with _fs.lock(root, _lock_path(root), exclusive=False, create=False) as held:
        yield held


def _ensure_publish_directories(root: Path) -> None:
    _fs.ensure_directory(root, _path(root, "/etc"))
    _fs.ensure_directory(root, _path(root, "/etc/host-endpoints.d"), mode=_DIR_MODE)
    _fs.ensure_directory(root, _path(root, "/etc/profile.d"))


def _render_environment(root: Path, aggregate: bytes, keys: set[str]) -> bytes:
    return render_block(_environment_bytes(root), aggregate, keys)


def _target_symlink_problems(root: Path) -> list[Problem]:
    problems: list[Problem] = []
    for target in (
        _path(root, "/etc/host-endpoints.d"),
        _lock_path(root),
        _path(root, "/etc/host-endpoints.env"),
        _path(root, "/etc/environment"),
        _path(root, "/etc/profile.d"),
        _path(root, "/etc/profile.d/host-endpoints.sh"),
    ):
        try:
            _fs.safe_components(root, target)
        except CliFailure as exc:
            problem = _failure_problem(exc)
            if problem not in problems:
                problems.append(problem)
    return problems


def plan(owner: str, entries: object, *, root: str | os.PathLike[str] = "/") -> list[Problem]:
    """Preflight entries, ownership collisions, environment markers and targets."""

    problems: list[Problem] = []
    owner_problem = _owner_problem(owner)
    if owner_problem is not None:
        problems.append(owner_problem)
    normalized, entry_problems = _entries_map(entries)
    problems.extend(entry_problems)
    try:
        root_path = _root_path(root)
    except CliFailure as exc:
        return problems + [_root_problem(exc)]
    problems.extend(_target_symlink_problems(root_path))
    if owner_problem is None:
        problems.extend(_preflight_unlocked(root_path, owner, normalized))
    return list(dict.fromkeys(problems))


def _managed_paths(root: Path) -> tuple[Path, Path, Path]:
    return (
        _path(root, "/etc/host-endpoints.env"),
        _path(root, "/etc/environment"),
        _path(root, "/etc/profile.d/host-endpoints.sh"),
    )


def _render_files(
    root: Path,
    fragments: Mapping[str, EndpointFragment],
    current_environment: bytes,
) -> dict[Path, tuple[bytes, int]]:
    aggregate_path, environment_path, profile_path = _managed_paths(root)
    aggregate = _aggregate_bytes(fragments)
    keys = {key for fragment in fragments.values() for key in fragment.entries}
    return {
        aggregate_path: (aggregate, _FILE_MODE),
        environment_path: (render_block(current_environment, aggregate, keys), _FILE_MODE),
        profile_path: (_PROFILE, _FILE_MODE),
    }


def render(
    owner: str,
    entries: object,
    *,
    writer: str,
    current_environment: bytes,
    existing_fragments: Mapping[str, EndpointFragment],
    root: str | os.PathLike[str] = "/",
) -> dict[Path, tuple[bytes, int]]:
    """Return ``{path: (content, mode)}`` for a publish without touching disk.

    ``existing_fragments`` are the other owners' valid fragments and
    ``current_environment`` the present ``/etc/environment`` bytes. Raises
    ``CliFailure`` on invalid input, a key collision or a damaged block.
    """

    root_path = Path(os.path.abspath(os.fspath(root)))
    normalized, problems = _entries_map(entries)
    for found in (_owner_problem(owner), _writer_problem(writer)):
        if found is not None:
            problems.insert(0, found)
    fragments = {name: fragment for name, fragment in existing_fragments.items() if name != owner}
    if not problems:
        fragments[owner] = EndpointFragment(owner=owner, writer=writer, entries=normalized)
        problems = _collisions(fragments, root_path)
    if problems:
        raise CliFailure(_format_problems("render", problems), exit_code=2)
    files = {_fragment_path(root_path, owner): (_fragment_bytes(fragments[owner]), _FILE_MODE)}
    files.update(_render_files(root_path, fragments, current_environment))
    return files


def render_withdraw(
    owner: str,
    *,
    current_environment: bytes,
    existing_fragments: Mapping[str, EndpointFragment],
    root: str | os.PathLike[str] = "/",
) -> dict[Path, tuple[bytes, int] | None]:
    """Return the plan for a withdraw; ``None`` marks the fragment to delete."""

    root_path = Path(os.path.abspath(os.fspath(root)))
    fragments = {name: fragment for name, fragment in existing_fragments.items() if name != owner}
    files: dict[Path, tuple[bytes, int] | None] = {_fragment_path(root_path, owner): None}
    files.update(_render_files(root_path, fragments, current_environment))
    return files


def _target_owner(root: Path) -> tuple[int, int] | None:
    """Files on the real ``/`` are created root:root (only root can ensure it)."""

    if root == Path("/") and os.geteuid() == 0:
        return (0, 0)
    return None


def _apply_plan(root: Path, files: Mapping[Path, tuple[bytes, int] | None]) -> None:
    """Apply a rendered plan in crash-window order: fragment, aggregate, environment, profile."""

    owner = _target_owner(root)
    for path, spec in files.items():
        if spec is None:
            _fs.unlink_and_sync(root, path)
        else:
            _fs.atomic_write(
                root, path, spec[0], spec[1], temp_prefix=_TEMP_PREFIX, owner=owner
            )


def _temporary_dirs(root: Path) -> tuple[Path, Path, Path]:
    return (
        _path(root, "/etc"),
        _path(root, "/etc/host-endpoints.d"),
        _path(root, "/etc/profile.d"),
    )


def _stale_temporaries(root: Path) -> list[Path]:
    found: list[Path] = []
    for directory in _temporary_dirs(root):
        found.extend(_fs.stale_temporaries(root, directory, _TEMP_PREFIX))
    return found


def _publish_unlocked(root: Path, owner: str, writer: str, entries: dict[str, str]) -> None:
    skipped_fragments: list[Problem] = []
    problems = _preflight_unlocked(
        root, owner, entries, skipped_fragments=skipped_fragments
    )
    if problems:
        raise CliFailure(_format_problems("publish", problems), exit_code=2)
    fragments, fragment_problems = _load_fragments(
        root,
        skip_owner=owner,
        tolerate_invalid=True,
        skipped_fragments=skipped_fragments,
    )
    if fragment_problems:
        raise CliFailure(_format_problems("publish", fragment_problems), exit_code=2)
    files = render(
        owner,
        entries,
        writer=writer,
        current_environment=_environment_bytes(root),
        existing_fragments=fragments,
        root=root,
    )
    _fs.remove_temporaries(_stale_temporaries(root))
    _apply_plan(root, files)
    skipped_owners = sorted({problem.owner for problem in skipped_fragments if problem.owner})
    for skipped_owner in skipped_owners:
        _LOGGER.warning(
            "publish skipped damaged host endpoint fragment for owner %s; its variables are omitted until that owner republishes",
            skipped_owner,
        )


def publish(
    owner: str,
    entries: object,
    *,
    writer: str,
    root: str | os.PathLike[str] = "/",
) -> None:
    """Publish or replace one owner's fragment and atomically render host files."""

    normalized, entry_problems = _entries_map(entries)
    problems = [
        found for found in (_owner_problem(owner), _writer_problem(writer)) if found is not None
    ]
    problems.extend(entry_problems)
    if problems:
        raise CliFailure(_format_problems("publish", problems), exit_code=2)
    try:
        root_path = _root_path(root)
        _ensure_publish_directories(root_path)
        targets = _target_symlink_problems(root_path)
        if targets:
            raise CliFailure(_format_problems("publish", targets), exit_code=2)
        with _exclusive_lock(root_path):
            _publish_unlocked(root_path, owner, writer, normalized)
    except CliFailure:
        raise
    except OSError as exc:
        raise CliFailure(f"cannot publish host endpoint records: {exc}", exit_code=2) from exc


def _withdraw_unlocked(root: Path, owner: str) -> bool:
    preflight = _preflight_unlocked(root, owner, {}, allow_empty=True)
    if preflight:
        raise CliFailure(_format_problems("withdraw", preflight), exit_code=2)
    fragments, problems = _load_fragments(root, skip_owner=owner, tolerate_invalid=True)
    if problems:
        raise CliFailure(_format_problems("withdraw", problems), exit_code=2)
    try:
        info = _fs.regular_or_missing(root, _fragment_path(root, owner))
    except CliFailure as exc:
        raise CliFailure(_format_problems("withdraw", [exc]), exit_code=2) from exc
    if info is None:
        return False
    files = render_withdraw(
        owner,
        current_environment=_environment_bytes(root),
        existing_fragments=fragments,
        root=root,
    )
    _fs.remove_temporaries(_stale_temporaries(root))
    _apply_plan(root, files)
    return True


def withdraw(owner: str, *, root: str | os.PathLike[str] = "/") -> bool:
    """Remove one owner's fragment and re-render the shared host files.

    Returns ``False`` without creating or changing anything when the owner has
    no fragment, ``True`` when a fragment was removed.
    """

    owner_problem = _owner_problem(owner)
    if owner_problem is not None:
        raise CliFailure(_format_problems("withdraw", [owner_problem]), exit_code=2)
    try:
        root_path = _root_path(root)
        targets = _target_symlink_problems(root_path)
        if targets:
            raise CliFailure(_format_problems("withdraw", targets), exit_code=2)
        if not _exists(_path(root_path, "/etc/host-endpoints.d")):
            return False
        with _exclusive_lock(root_path):
            return _withdraw_unlocked(root_path, owner)
    except CliFailure:
        raise
    except OSError as exc:
        raise CliFailure(f"cannot withdraw host endpoint records: {exc}", exit_code=2) from exc


def verify(
    owner: str,
    expected: object,
    *,
    root: str | os.PathLike[str] = "/",
) -> list[Problem]:
    """Compare one owner's published fragment with its live expected entries.

    A fragment is replaced atomically, so reading one file needs no lock.
    """

    problems: list[Problem] = []
    owner_problem = _owner_problem(owner)
    if owner_problem is not None:
        problems.append(owner_problem)
    normalized, entry_problems = _entries_map(expected)
    problems.extend(entry_problems)
    try:
        root_path = _root_path(root)
    except CliFailure as exc:
        return problems + [_root_problem(exc)]
    if owner_problem is not None:
        return problems
    fragment, fragment_problems = _parse_fragment(
        root_path, owner, _fragment_path(root_path, owner)
    )
    problems.extend(fragment_problems)
    if fragment is not None and fragment.entries != normalized:
        problems.append(
            _problem(
                "endpoint.fragment.mismatch",
                f"fragment for owner {owner!r} does not match expected entries",
                path=_fs.display(_fragment_path(root_path, owner), root_path),
                owner=owner,
            )
        )
    return list(dict.fromkeys(problems))


Ownership = Callable[[os.stat_result], bool]


def _default_ownership(root: Path) -> Ownership | None:
    """Require root:root on the real ``/``; fake roots skip the check."""

    if root != Path("/"):
        return None
    return lambda info: info.st_uid == 0 and info.st_gid == 0


def _mode_problems(
    root: Path,
    path: Path,
    expected: int,
    info: os.stat_result | None,
    ownership: Ownership | None,
) -> list[Problem]:
    shown = _fs.display(path, root)
    if info is None:
        return [_problem("endpoint.path.missing", f"missing managed path: {shown}", path=shown)]
    problems: list[Problem] = []
    actual = stat.S_IMODE(info.st_mode)
    if actual != expected:
        problems.append(
            _problem(
                "endpoint.mode.wrong",
                f"wrong mode on {shown}: {actual:04o}, expected {expected:04o}",
                path=shown,
            )
        )
    if ownership is not None and not ownership(info):
        problems.append(
            _problem(
                "endpoint.owner.wrong",
                f"wrong owner on {shown}: {info.st_uid}:{info.st_gid}, expected root:root",
                path=shown,
            )
        )
    return problems


def _managed_file(
    root: Path, path: Path, mode: int, ownership: Ownership | None
) -> tuple[os.stat_result | None, list[Problem]]:
    try:
        info = _fs.regular_or_missing(root, path)
    except CliFailure as exc:
        return None, [_failure_problem(exc)]
    return info, _mode_problems(root, path, mode, info, ownership)


def _missing_directory(root: Path, path: Path) -> Problem:
    shown = _fs.display(path, root)
    return _problem("endpoint.path.missing", f"missing managed directory: {shown}", path=shown)


def _not_a_directory(root: Path, path: Path) -> Problem:
    shown = _fs.display(path, root)
    return _problem("endpoint.path.type", f"managed directory is not a directory: {shown}", path=shown)


def _check_fragment_directory(
    root: Path, ownership: Ownership | None
) -> tuple[dict[str, EndpointFragment], list[Problem]]:
    problems: list[Problem] = []
    endpoints = _path(root, "/etc/host-endpoints.d")
    info: os.stat_result | None = None
    try:
        _fs.safe_components(root, endpoints)
        info = endpoints.lstat()
    except FileNotFoundError:
        problems.append(_missing_directory(root, endpoints))
    except CliFailure as exc:
        problems.append(_failure_problem(exc))
    if info is not None and not stat.S_ISDIR(info.st_mode):
        problems.append(_not_a_directory(root, endpoints))
        info = None
    if info is None:
        return {}, problems
    problems.extend(_mode_problems(root, endpoints, _DIR_MODE, info, ownership))
    fragments, fragment_problems = _load_fragments(root)
    problems.extend(fragment_problems)
    problems.extend(_managed_file(root, _lock_path(root), _LOCK_MODE, ownership)[1])
    try:
        children = sorted(endpoints.iterdir(), key=lambda child: child.name)
    except OSError as exc:
        return fragments, problems + [
            _io_problem(
                f"cannot read {_fs.display(endpoints, root)}: {exc}",
                path=_fs.display(endpoints, root),
            )
        ]
    for child in children:
        if child.name.endswith(".env") and _owner_problem(child.name[:-4]) is None:
            problems.extend(_managed_file(root, child, _FILE_MODE, ownership)[1])
    return fragments, problems


def _check_environment(
    root: Path,
    fragments: Mapping[str, EndpointFragment],
    aggregate: bytes | None,
    ownership: Ownership | None,
) -> list[Problem]:
    path = _path(root, "/etc/environment")
    shown = _fs.display(path, root)
    _info, problems = _managed_file(root, path, _FILE_MODE, ownership)
    environment = _read_optional(root, path)
    if environment is None:
        return problems
    unmanaged, block_payload, marker_problems = _environment_parts(environment)
    problems.extend(
        _problem("endpoint.environment.block", f"/etc/environment: {message}", path=shown)
        for message in marker_problems
    )
    managed_keys = {key for fragment in fragments.values() for key in fragment.entries}
    for key in sorted(_outside_keys(unmanaged) & managed_keys):
        problems.append(
            _problem(
                "endpoint.environment.duplicate",
                f"{key} is duplicated outside the host-endpoints block",
                path=shown,
                key=key,
            )
        )
    if managed_keys:
        if block_payload is None:
            problems.append(
                _problem(
                    "endpoint.environment.block",
                    "/etc/environment is missing the host-endpoints block",
                    path=shown,
                )
            )
        elif aggregate is not None and block_payload != aggregate:
            problems.append(
                _problem(
                    "endpoint.environment.drift",
                    "/etc/environment host-endpoints block differs from aggregate",
                    path=shown,
                )
            )
    elif block_payload is not None:
        problems.append(
            _problem(
                "endpoint.environment.block",
                "/etc/environment has a host-endpoints block but no fragments remain",
                path=shown,
            )
        )
    return problems


def _check_profile(root: Path, ownership: Ownership | None) -> list[Problem]:
    profile_dir = _path(root, "/etc/profile.d")
    profile_path = profile_dir / "host-endpoints.sh"
    try:
        _fs.safe_components(root, profile_dir)
        profile_dir_info = profile_dir.lstat()
    except FileNotFoundError:
        return [_missing_directory(root, profile_dir)]
    except CliFailure as exc:
        return [_failure_problem(exc)]
    if not stat.S_ISDIR(profile_dir_info.st_mode):
        return [_not_a_directory(root, profile_dir)]
    _info, problems = _managed_file(root, profile_path, _FILE_MODE, ownership)
    content = _read_optional(root, profile_path)
    if content is not None and content != _PROFILE:
        shown = _fs.display(profile_path, root)
        problems.append(
            _problem(
                "endpoint.profile.drift",
                "/etc/profile.d/host-endpoints.sh differs from generated content",
                path=shown,
            )
        )
    return problems


def _stale_problems(root: Path) -> list[Problem]:
    return [
        _problem(
            "endpoint.temp.stale",
            f"stale temporary file {_fs.display(path, root)}; the next publish removes it",
            path=_fs.display(path, root),
        )
        for path in _stale_temporaries(root)
    ]


def _check_unlocked(root: Path, ownership: Ownership | None = None) -> list[Problem]:
    fragments, problems = _check_fragment_directory(root, ownership)
    aggregate_path = _path(root, "/etc/host-endpoints.env")
    _info, aggregate_problems = _managed_file(root, aggregate_path, _FILE_MODE, ownership)
    problems.extend(aggregate_problems)
    aggregate = _read_optional(root, aggregate_path)
    if aggregate is not None and aggregate != _aggregate_bytes(fragments):
        problems.append(
            _problem(
                "endpoint.aggregate.drift",
                "/etc/host-endpoints.env differs from endpoint fragments",
                path="/etc/host-endpoints.env",
            )
        )
    problems.extend(_check_environment(root, fragments, aggregate, ownership))
    problems.extend(_check_profile(root, ownership))
    problems.extend(_stale_problems(root))
    return list(dict.fromkeys(problems))


def _is_pristine(root: Path) -> bool:
    """True when nothing was ever published: no directory, aggregate, block or script."""

    if any(
        _exists(target)
        for target in (
            _path(root, "/etc/host-endpoints.d"),
            _path(root, "/etc/host-endpoints.env"),
            _path(root, "/etc/profile.d/host-endpoints.sh"),
        )
    ):
        return False
    try:
        data = _environment_bytes(root)
    except (CliFailure, OSError):
        return False
    _unmanaged, payload, problems = _environment_parts(data)
    return payload is None and not problems


def _check_body(root: Path, ownership: Ownership | None) -> CheckResult:
    try:
        if _is_pristine(root):
            return CheckResult(_stale_problems(root), message="no endpoints published")
        return CheckResult(_check_unlocked(root, ownership))
    except OSError as exc:
        return CheckResult([_io_problem(f"cannot check host endpoint records: {exc}")])


def _check_once(root: Path, ownership: Ownership | None) -> tuple[CheckResult, bool]:
    with ExitStack() as stack:
        try:
            held = stack.enter_context(_shared_lock(root))
        except (PermissionError, CliFailure):
            held = False
        return _check_body(root, ownership), held


def check(
    *,
    root: str | os.PathLike[str] = "/",
    ownership: Ownership | None = None,
) -> CheckResult:
    """Check all fragments, rendered files, markers, symlinks, modes and owners.

    The check holds the shared side of the writer lock, so it never reports
    false drift while a publish is in flight. A caller that cannot open the
    root-owned lock (non-root) gets an advisory check that re-runs a few times
    before it reports drift. ``ownership`` overrides the root:root policy,
    which only applies to the real ``/`` by default.
    """

    try:
        root_path = _root_path(root)
    except CliFailure as exc:
        return CheckResult([_root_problem(exc)])
    policy = _default_ownership(root_path) if ownership is None else ownership
    for attempt in range(_CHECK_ATTEMPTS):
        try:
            result, held = _check_once(root_path, policy)
        except OSError as exc:
            return CheckResult([_io_problem(f"cannot check host endpoint records: {exc}")])
        if held or not result or attempt == _CHECK_ATTEMPTS - 1:
            return result
        _sleep(_CHECK_RETRY_DELAY)
    raise AssertionError("unreachable")  # pragma: no cover


def require_env(
    name: str,
    *,
    remedy: str,
    environ: Mapping[str, str] = os.environ,
) -> str:
    """Return a non-empty endpoint variable or fail with its named remedy."""

    if not isinstance(name, str) or _KEY_RE.fullmatch(name) is None:
        raise ValueError("name must be a valid uppercase environment variable")
    if not isinstance(remedy, str) or not remedy.strip() or "\n" in remedy or "\r" in remedy:
        raise ValueError("remedy must be a non-empty single line")
    value = environ.get(name)
    if value is None or value == "":
        raise CliFailure(f"{name} is unset: {remedy}")
    return value


def _read_aggregate(root: Path) -> bytes:
    path = _path(root, "/etc/host-endpoints.env")
    try:
        data = _read_file(root, path)
    except (CliFailure, OSError) as exc:
        raise CliFailure(str(exc), exit_code=2) from exc
    if data is None:
        raise CliFailure("/etc/host-endpoints.env is missing", exit_code=2)
    return data


def _cli_publish(args: Any, runtime: CliRuntime) -> None:
    entries: list[tuple[str, str]] = []
    for raw in args.entry:
        key, separator, value = raw.partition("=")
        if not separator:
            raise CliFailure(f"invalid --entry {raw!r}; expected KEY=VALUE", exit_code=2)
        entries.append((key, value))
    publish(args.owner, entries, writer=args.writer)
    runtime.output.primary(f"Published host endpoints for {args.owner}.")


def _cli_withdraw(args: Any, runtime: CliRuntime) -> None:
    if withdraw(args.owner) is False:
        runtime.output.primary(f"No host endpoints published by {args.owner}; nothing to withdraw.")
    else:
        runtime.output.primary(f"Withdrew host endpoints for {args.owner}.")


def _cli_check(_args: Any, runtime: CliRuntime) -> int:
    result = check()
    problems = list(result)
    status = "problems" if problems else "clean"
    message = getattr(result, "message", None) or (
        f"{len(problems)} problem(s) found" if problems else "host endpoint records are consistent"
    )
    if runtime.json_mode:
        runtime.output.primary(
            {
                "status": status,
                "message": message,
                "problems": [str(problem) for problem in problems],
                "records": [problem.as_dict() for problem in problems if isinstance(problem, Problem)],
            }
        )
    elif problems:
        for problem in problems:
            runtime.output.error(str(problem))
    else:
        runtime.output.primary(message)
    return 1 if problems else 0


def _cli_show(_args: Any, runtime: CliRuntime) -> None:
    try:
        rendered = _read_aggregate(_root_path("/")).decode("ascii")
    except UnicodeDecodeError as exc:
        raise CliFailure("/etc/host-endpoints.env is not ASCII", exit_code=2) from exc
    runtime.output.primary(rendered.removesuffix("\n"))


def build_cli(identity: CliIdentity | None = None) -> Any:
    """Build the ``augeaswrap endpoints`` command registry."""

    if identity is None:
        identity = CliIdentity.resolve(
            name="AUGEASWRAP",
            long_name="Generic host configuration utility",
            command="augeaswrap",
            distribution="augeaswrap",
        )
    endpoints_registry = CliRegistry(
        identity,
        prog="augeaswrap endpoints",
        description="Publish and inspect host-owned endpoint environment facts.",
        getting_started=("augeaswrap endpoints check",),
    )
    owner_option = OptionSpec(
        ("--owner",),
        "fragment owner used as the record filename",
        group="RECORD",
        metavar="OWNER",
        parser_kwargs={"required": True},
    )
    endpoints_registry.register(
        VerbSpec(
            "publish",
            description="Publish one owner's endpoint entries and render the shared files.",
            group="MODIFICATION",
            options=(
                owner_option,
                OptionSpec(
                    ("--writer",),
                    "owning install verb and version, for example 'cgpd install 2.3.0'",
                    group="RECORD",
                    metavar="WRITER",
                    parser_kwargs={"required": True},
                ),
                OptionSpec(
                    ("--entry",),
                    "endpoint entry in KEY=VALUE form; repeat for each key",
                    group="RECORD",
                    metavar="KEY=VALUE",
                    parser_kwargs={"action": "append", "required": True},
                ),
            ),
            handler=_cli_publish,
            mutating=True,
            confirmation_required=False,
            include_json=False,
            include_progress=False,
        )
    )
    endpoints_registry.register(
        VerbSpec(
            "withdraw",
            description="Withdraw one owner's fragment and update the shared files.",
            group="MODIFICATION",
            options=(owner_option,),
            handler=_cli_withdraw,
            mutating=True,
            confirmation_required=False,
            include_json=False,
            include_progress=False,
        )
    )
    endpoints_registry.register(
        VerbSpec(
            "check",
            description="Check fragments, rendered files, marker structure, modes and symlinks.",
            group="EXPLORATION",
            handler=_cli_check,
            include_json=True,
            include_progress=False,
        )
    )
    endpoints_registry.register(
        VerbSpec(
            "show",
            description="Print the generated aggregate environment file.",
            group="EXPLORATION",
            handler=_cli_show,
            include_json=False,
            include_progress=False,
        )
    )
    registry = CliRegistry(
        identity,
        prog="augeaswrap",
        description="Generic host configuration utility.",
        getting_started=("augeaswrap endpoints check",),
    )
    registry.register(
        VerbSpec(
            "endpoints",
            description="Publish and inspect host endpoint environment facts.",
            group="MAINTENANCE",
            delegate=endpoints_registry.build(),
            include_progress=False,
        )
    )
    return registry.build()


def build_surface_cli() -> Any:
    """Build the registry for surface review without requiring a built wheel.

    The shared surface schema records the command name and display labels, not
    the package version. Runtime entry points still resolve the real installed
    Augeaswrap version in :func:`build_cli`.
    """

    surface_identity = CliIdentity(
        name="AUGEASWRAP",
        version="surface",
        long_name="Generic host configuration utility",
        command="augeaswrap",
    )
    return build_cli(surface_identity)


def main(argv: Sequence[str] | None = None) -> int:
    """Run the registered Augeaswrap CLI."""

    try:
        app = build_cli()
    except VersionLookupError as exc:
        print(f"[ERROR] augeaswrap: {exc}", file=sys.stderr)
        return 2
    return app.run(argv=argv)
