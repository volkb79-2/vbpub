def test_withdraw_renders_remaining_fragments_and_removes_last_managed_block(tmp_path):
    root = fake_root(tmp_path, b"# administrator line\n")
    publish(root, owner="alpha", entries={"ALPHA_SOCKET": "/run/a.sock"})
    publish(root, owner="beta", entries={"BETA_SOCKET": "/run/b.sock"})

    endpoints.withdraw("alpha", root=root)

    aggregate = (root / "etc" / "host-endpoints.env").read_text()
    environment = (root / "etc" / "environment").read_text()
    assert "ALPHA_SOCKET" not in aggregate
    assert "BETA_SOCKET=/run/b.sock" in aggregate
    assert "# administrator line\n" in environment
    assert "ALPHA_SOCKET" not in environment
    assert endpoints.check(root=root) == []

    endpoints.withdraw("beta", root=root)
    assert (root / "etc" / "host-endpoints.env").read_text() == "# host-endpoints v1\n"
    assert (root / "etc" / "environment").read_text() == "# administrator line\n"
    assert endpoints.check(root=root) == []


