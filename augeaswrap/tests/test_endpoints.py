def fake_root(tmp_path: Path, environment: bytes = b"") -> Path:
    root = tmp_path / "root"
    etc = root / "etc"
    (etc / "profile.d").mkdir(parents=True, exist_ok=True)
    (etc / "environment").write_bytes(environment)
    return root


def publish(root: Path, owner: str = "svc", entries=None, writer: str = "svc install 1.2.3"):
    if entries is None:
        entries = {"SVC_SOCKET": "/run/svc/sock"}
    endpoints.publish(owner, entries, writer=writer, root=root)


