def test_render_is_pure_and_returns_path_content_and_mode_plan(tmp_path):
    root = fake_root(tmp_path, b"KEEP=1")
    before = sorted(str(path.relative_to(root)) for path in root.rglob("*"))
    plan = endpoints.render(
        "svc",
        {"SVC_SOCKET": "/run/svc.sock"},
        writer="svc install 1.0",
        current_environment=b"KEEP=1",
        existing_fragments={},
        root=root,
    )
    after = sorted(str(path.relative_to(root)) for path in root.rglob("*"))
    assert after == before
