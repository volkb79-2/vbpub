"""Guard the package layout and Assay inventory against drift."""

from __future__ import annotations

import tomllib
from pathlib import Path

from cli_extended.review import check_cli_surface

from augeaswrap.cli import build_surface_cli

PROJECT_ROOT = Path(__file__).resolve().parents[1]
PACKAGE_ROOT = PROJECT_ROOT / "src" / "augeaswrap"


def test_assay_targets_cover_every_package_module():
    config = tomllib.loads((PROJECT_ROOT / "assay.toml").read_text(encoding="utf-8"))
    targets = config["lanes"]["augeaswrap"]["judge"]["targets"]
    modules = sorted(
        path.relative_to(PROJECT_ROOT).as_posix()
        for path in PACKAGE_ROOT.rglob("*.py")
    )
    assert targets == modules


def test_cli_surface_files_match_the_registered_command():
    report = check_cli_surface(
        build_surface_cli(),
        review_path=PROJECT_ROOT / "docs" / "cli-review.toml",
        manifest_path=PROJECT_ROOT / "docs" / "cli-surface.json",
        spec_path=PROJECT_ROOT / "docs" / "CLI-SPEC.md",
    )
    assert report.passed, [finding.message for finding in report.findings]


def test_guarded_applier_docs_cover_what_why_and_how():
    readme = (PROJECT_ROOT / "README.md").read_text(encoding="utf-8")
    spec = (PROJECT_ROOT / "SPEC.md").read_text(encoding="utf-8")
    design = (PROJECT_ROOT / "docs" / "DESIGN-GUIDE.md").read_text(encoding="utf-8")
    consumers = (PROJECT_ROOT / "docs" / "CONSUMERS.md").read_text(encoding="utf-8")
    changes = (PROJECT_ROOT / "CHANGES.md").read_text(encoding="utf-8")

    assert "augeaswrap plan" in readme
    assert "docs/CONSUMERS.md" in readme
    assert "docs/DESIGN-GUIDE.md#guarded-applier" in readme
    assert "Guarded applier protocol (HC-1a')" in spec
    assert "txn/<id>/stage" in spec and "txn/<id>/pre" in spec
    assert "## Guarded applier" in design
    assert "## Guarded applier" in consumers
    assert "augeaswrap apply request.toml" in consumers
    assert "explicit revert" in changes
    assert "exactly one JSON document" in spec
    assert "one document" in design
    assert "one document" in consumers
    assert "generated by augeaswrap.endpoints" in spec
    assert "post-image cannot be observed" in spec
    assert "post-image is unknown" in consumers
    assert "reruns recorded post-actions" in spec
    assert "same `--root`" in consumers
    assert "recorded post-actions" in design
