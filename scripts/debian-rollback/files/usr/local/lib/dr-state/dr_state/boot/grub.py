"""GRUB menu and environment publication."""

from __future__ import annotations

import os
import re
import stat
from pathlib import Path
from typing import Sequence

from .. import ids
from ..errors import BootConfigError, BootError, Refused
from ..lock import atomic_write
from ..metadata import write_esp_format
from ..paths import Paths
from ..storage import KernelPair, Storage
from . import BootTarget, Inspection, Selector

_CFG_MARKER = "# generated by dr-state gen-menu; do not edit"
_MENU_ID_RE = re.compile(
    r'\s*menuentry\s+"[^"\n]*"\s+--id\s+([^ \t{]+)\s*\{'
)
_ENV_KEY_RE = re.compile(r"(?P<key>[A-Za-z0-9_.:-]+)=(?P<value>.*)\Z")


class GrubBoot:
    """The ESP marker, GRUB menu, and grubenv selector surface."""

    name = "grub"
    supports_oneshot = True

    def __init__(self, paths: Paths, storage: Storage, runner: object) -> None:
        self.paths = paths
        self.storage = storage
        self.runner = runner

    def _run(self, argv: list[str]) -> str:
        completed = self.runner.run(argv)
        if completed.returncode != 0:
            detail = completed.stderr.strip() or completed.stdout.strip()
            raise BootError(
                f"{' '.join(argv)} failed"
                + (f": {detail}" if detail else "")
            )
        return completed.stdout

    def _marker_value(self) -> str | None:
        marker = self.paths.esp_marker
        try:
            status = os.lstat(marker)
        except FileNotFoundError:
            return None
        except OSError as error:
            raise Refused(f"cannot inspect bootloader marker {marker}: {error}") from error
        if stat.S_ISLNK(status.st_mode):
            raise Refused(f"bootloader marker {marker} is a symlink")
        if not stat.S_ISREG(status.st_mode):
            raise Refused(f"bootloader marker {marker} is not a regular file")
        try:
            value = marker.read_text(encoding="utf-8")
        except (OSError, UnicodeError) as error:
            raise Refused(f"cannot read bootloader marker {marker}: {error}") from error
        return value.replace("\r", "").replace("\n", "")

    def _prepare_publication(self) -> None:
        if not self.paths.esp.is_dir():
            raise Refused(
                f"ESP {self.paths.esp} is missing or not mounted; refusing to publish"
            )
        marker = self._marker_value()
        if marker is None:
            raise Refused(
                f"bootloader marker {self.paths.esp_marker} is missing; "
                "run install-grub first"
            )
        if marker != self.name:
            raise BootConfigError(
                f"bootloader marker {self.paths.esp_marker} names {marker!r}, "
                f"not {self.name!r}"
            )

    def install(self) -> None:
        """Write the GRUB ESP marker and format file."""

        if not self.paths.esp.is_dir():
            raise Refused(f"ESP {self.paths.esp} is missing or not mounted")
        self.paths.esp_dir.mkdir(parents=True, exist_ok=True)
        atomic_write(self.paths.esp_marker, "grub\n", mode=0o644)
        write_esp_format(self.paths)

    def capacity(self, keep: Sequence[BootTarget]) -> None:
        _ = keep
        return None

    def payload(self, target: BootTarget) -> list[tuple[str, int]]:
        _ = target
        return []

    def _target_text(self, target: BootTarget) -> str:
        locator = target.locator
        name = target.state.name
        kernel = target.kernel.version
        return (
            f'menuentry "Debian {name} (kernel {kernel})" --id {name} {{\n'
            f"  search --no-floppy --fs-uuid --set=root {locator}\n"
            f"  linux {target.kernel.fs_vmlinuz} {target.root_args} ro "
            "net.ifnames=0 console=tty0 console=ttyS0,115200\n"
            f"  initrd {target.kernel.fs_initrd}\n"
            "}\n"
        )

    def _menu_text(self, targets: Sequence[BootTarget]) -> str:
        head = (
            f"{_CFG_MARKER}\n"
            "serial --unit=0 --speed=115200\n"
            "terminal_input serial console\n"
            "terminal_output serial console\n"
            "set timeout=5\n"
            "load_env\n"
            'if [ "${next_entry}" ]; then\n'
            '  set default="${next_entry}"\n'
            "  set next_entry=\n"
            "  save_env next_entry\n"
            "else\n"
            '  set default="${saved_entry}"\n'
            "fi\n"
        )
        return head + "".join(self._target_text(target) for target in targets)

    def _cfg_bytes(self) -> bytes | None:
        try:
            status = os.lstat(self.paths.esp_grub_cfg)
        except FileNotFoundError:
            return None
        except OSError as error:
            raise BootError(f"cannot inspect {self.paths.esp_grub_cfg}: {error}") from error
        if stat.S_ISLNK(status.st_mode):
            raise BootError(f"GRUB menu {self.paths.esp_grub_cfg} is a symlink")
        if not stat.S_ISREG(status.st_mode):
            raise BootError(f"GRUB menu {self.paths.esp_grub_cfg} is not a regular file")
        try:
            return self.paths.esp_grub_cfg.read_bytes()
        except OSError as error:
            raise BootError(f"cannot read {self.paths.esp_grub_cfg}: {error}") from error

    def _container_symlink_refusal(self) -> None:
        for directory in (self.paths.esp_dir,):
            try:
                status = os.lstat(directory)
            except FileNotFoundError:
                return
            if stat.S_ISLNK(status.st_mode):
                raise BootError(f"ESP directory {directory} is a symlink")

    def publish(self, targets: Sequence[BootTarget], default: ids.StateId) -> None:
        """Publish exactly the targets, then make ``default`` effective."""

        try:
            self._publish(targets, default)
        except OSError as error:
            raise BootError(f"cannot publish GRUB boot configuration: {error}") from error

    def _publish(
        self,
        targets: Sequence[BootTarget],
        default: ids.StateId,
    ) -> None:
        self._prepare_publication()
        target_names = tuple(target.state.name for target in targets)
        if default.name not in target_names:
            raise Refused(f"default {default.name} is not in the published menu")
        if len(set(target_names)) != len(target_names):
            raise BootError("GRUB target set repeats a state")

        menu = self._menu_text(targets).encode("utf-8")
        old = self._cfg_bytes()
        if old is not None:
            first_line = old.splitlines()[0].rstrip(b"\r") if old.splitlines() else b""
            if first_line.decode("utf-8", "replace") != _CFG_MARKER:
                raise BootError(
                    f"{self.paths.esp_grub_cfg} is not owned by dr-state"
                )

        current = self.default(strict=False)
        menu_changed = old != menu
        selector_changed = current is None or current.state != default.name
        if not menu_changed and not selector_changed:
            return
        write_esp_format(self.paths)
        if menu_changed:
            self.paths.esp_dir.mkdir(parents=True, exist_ok=True)
            atomic_write(self.paths.esp_grub_cfg, menu, mode=0o644)
        if selector_changed:
            if not self.paths.esp_grubenv.exists():
                try:
                    self._run(
                        ["grub-editenv", str(self.paths.esp_grubenv), "create"]
                    )
                except BootError as error:
                    raise BootError(
                        f"cannot create {self.paths.esp_grubenv}: {error}"
                    ) from error
            try:
                self._run(
                    [
                        "grub-editenv",
                        str(self.paths.esp_grubenv),
                        "set",
                        f"saved_entry={default.name}",
                    ]
                )
            except BootError as error:
                raise BootError(
                    f"GRUB menu was published but saved_entry could not be set: {error}"
                ) from error

    def _environment(self, *, strict: bool) -> dict[str, str] | None:
        path = self.paths.esp_grubenv
        try:
            status = os.lstat(path)
        except FileNotFoundError:
            return {}
        except OSError as error:
            if strict:
                raise BootConfigError(f"cannot inspect {path}: {error}") from error
            return None
        if stat.S_ISLNK(status.st_mode):
            if strict:
                raise BootConfigError(f"GRUB environment {path} is a symlink")
            return None
        if not stat.S_ISREG(status.st_mode):
            if strict:
                raise BootConfigError(f"GRUB environment {path} is not a regular file")
            return None
        try:
            output = self._run(["grub-editenv", str(path), "list"])
        except BootError as error:
            if strict:
                raise BootConfigError(str(error)) from error
            return None
        result: dict[str, str] = {}
        for raw_line in output.splitlines():
            line = raw_line.rstrip("\r")
            match = _ENV_KEY_RE.fullmatch(line)
            if match is None:
                if strict:
                    raise BootConfigError(
                        f"GRUB environment contains a malformed line {line!r}"
                    )
                return None
            key = match.group("key")
            if key in result:
                if strict:
                    raise BootConfigError(
                        f"GRUB environment repeats {key}"
                    )
                return None
            result[key] = match.group("value")
        return result

    def _menu_ids(self) -> frozenset[str]:
        contents = self._cfg_bytes()
        if contents is None:
            return frozenset()
        result: set[str] = set()
        for raw_line in contents.decode("utf-8", "replace").splitlines():
            match = _MENU_ID_RE.fullmatch(raw_line.rstrip("\r"))
            if match is not None:
                result.add(match.group(1))
        return frozenset(result)

    def _map_selector(
        self,
        raw: str,
        *,
        strict: bool,
        default: bool,
    ) -> Selector | None:
        parsed = ids.parse(raw)
        if parsed is not None:
            names = {item.name for item in self.storage.list()}
            if parsed.name in names:
                return Selector(raw=raw, state=parsed.name, entry=raw, known=True)
            if strict:
                raise BootConfigError(
                    f"selector {raw!r} names no existing managed state"
                )
            if not default:
                return Selector(raw=raw, state=parsed.name, entry=raw, known=True)
            return None
        if raw in self._menu_ids():
            return Selector(raw=raw, state=None, entry=raw, known=True)
        if strict:
            raise BootConfigError(
                f"selector {raw!r} matches no managed state or existing GRUB entry"
            )
        return None

    def _selector(self, key: str, *, strict: bool, default: bool) -> Selector | None:
        environment = self._environment(strict=strict)
        if environment is None:
            if default:
                return None
            return Selector(raw="", state=None, entry=None, known=False)
        raw = environment.get(key)
        if raw is None or not raw:
            return None
        try:
            mapped = self._map_selector(raw, strict=strict, default=default)
        except BootConfigError:
            raise
        if mapped is None and not default:
            return Selector(raw=raw, state=None, entry=None, known=False)
        return mapped

    def default(self, *, strict: bool) -> Selector | None:
        return self._selector("saved_entry", strict=strict, default=True)

    def oneshot(self, *, strict: bool) -> Selector | None:
        return self._selector("next_entry", strict=strict, default=False)

    def set_oneshot(self, state: ids.StateId) -> None:
        try:
            self._set_oneshot(state)
        except OSError as error:
            raise BootError(
                f"cannot publish the GRUB one-shot boot: {error}"
            ) from error

    def _set_oneshot(self, state: ids.StateId) -> None:
        self._prepare_publication()
        current = self.oneshot(strict=False)
        if current is not None and current.raw == state.name:
            return
        write_esp_format(self.paths)
        if not self.paths.esp_grubenv.exists():
            self._run(["grub-editenv", str(self.paths.esp_grubenv), "create"])
        self._run(
            [
                "grub-editenv",
                str(self.paths.esp_grubenv),
                "set",
                f"next_entry={state.name}",
            ]
        )

    def protected(self) -> frozenset[str]:
        selected: set[str] = set()
        for selector in (
            self.default(strict=True),
            self.oneshot(strict=True),
        ):
            if selector is not None and selector.state is not None:
                selected.add(selector.state)
        return frozenset(selected)

    def inspect(self) -> Inspection:
        return Inspection(
            published=self._menu_ids(),
            stale_owned=(),
            violations=(),
        )

    def kernel_available(self, state: ids.StateId, kernel: KernelPair) -> bool:
        """Whether a target's files exist away from the ESP."""

        return kernel.vmlinuz.is_file() and kernel.initrd.is_file()

    def menu_path(self) -> Path:
        """The menu path, exposed for focused boundary tests."""

        return self.paths.esp_grub_cfg
