ENTRY_MARKER = "# generated by dr-state sdboot; do not edit"
ONESHOT_EFIVAR = "LoaderEntryOneShot-4a67b082-0a4c-41cf-b6c7-440b29bb8c4f"
DEFAULT_EFIVAR = "LoaderEntryDefault-4a67b082-0a4c-41cf-b6c7-440b29bb8c4f"
CAPACITY_MARGIN = 8 * 1024 * 1024
ENTRY_BYTES = 4096

_PAIR_ID_RE = re.compile(
    r"^(?P<version>[A-Za-z0-9][A-Za-z0-9._+-]*)-"
    r"(?P<digest>[0-9a-f]{64})$",
    re.IGNORECASE,
)
_SELECTOR_RE = re.compile(
    r"^os-[A-Za-z0-9][A-Za-z0-9._-]*(?:\+[0-9]+(?:-[0-9]+)?)?\.conf$",
    re.IGNORECASE,
)
_UUID_RE = re.compile(
    r"^[0-9A-Fa-f]{8}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-"
    r"[0-9A-Fa-f]{4}-[0-9A-Fa-f]{12}$"
)
_KERNEL_VERSION_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._+-]*$")


class Filesystem:
    """The filesystem and space observations sdboot consumes."""

    def is_directory(self, path: Path) -> bool:
        """Follow a symlink to decide whether the ESP directory exists."""

        return path.is_dir()

    def lstat(self, path: Path) -> os.stat_result:
        return os.lstat(path)

    def listdir(self, path: Path) -> tuple[str, ...]:
        try:
            return tuple(item.name for item in path.iterdir())
        except FileNotFoundError:
            return ()

    def read_bytes(self, path: Path) -> bytes:
        return path.read_bytes()

    def statvfs(self, path: Path) -> os.statvfs_result:
        return os.statvfs(path)

    def lookup(self, path: Path) -> Path | None:
        """Return the actual entry name, preferring an exact match over a VFAT alias."""

        try:
            candidates = tuple(path.parent.iterdir())
        except FileNotFoundError:
            return None
        for candidate in candidates:
            if candidate.name == path.name:
                return candidate
        for candidate in candidates:
            if candidate.name.casefold() == path.name.casefold():
                return candidate
        return None

    def mkdir(self, path: Path) -> None:
        path.mkdir(parents=True, exist_ok=True)

    def unlink(self, path: Path) -> None:
        path.unlink()

    def rmtree(self, path: Path) -> None:
        shutil.rmtree(path)

    def replace(self, source: Path, destination: Path) -> None:
        os.replace(source, destination)

    def write_atomic(self, path: Path, data: bytes) -> None:
        atomic_write(path, data, mode=0o644)

    def copy_file(self, source: Path, destination: Path) -> tuple[str, int]:
        shutil.copyfile(source, destination)
        destination.chmod(0o644)
        digest = hashlib.sha256()
        size = 0
        with destination.open("rb") as stream:
            while chunk := stream.read(1024 * 1024):
                digest.update(chunk)
                size += len(chunk)
            os.fsync(stream.fileno())
        return digest.hexdigest(), size


@dataclass(frozen=True, slots=True)
class _Loader:
    lines: tuple[str, ...]
    defaults: tuple[str, ...]
    valid: bool


@dataclass(frozen=True, slots=True)
class _EFIVar:
    present: bool
    raw: str | None
    readable: bool


@dataclass(frozen=True, slots=True)
class _Entry:
    path: Path
    name: str
    data: bytes
    owned: bool
    state: str | None
    refs: frozenset[str]


@dataclass(frozen=True, slots=True)
class _Pair:
    path: Path
    name: str
    version: str


@dataclass(frozen=True, slots=True)
class _Inventory:
    entries: tuple[_Entry, ...]
    pairs: tuple[_Pair, ...]

    @property
    def owned_entries(self) -> tuple[_Entry, ...]:
        return tuple(entry for entry in self.entries if entry.owned)

    def pairs_by_fold(self) -> dict[str, _Pair]:
        return {pair.name.casefold(): pair for pair in self.pairs}


@dataclass(frozen=True, slots=True)
class _PairPlan:
    id: str
    path: Path
    kernel: Path
    initrd: Path
    kernel_hash: str | None
    initrd_hash: str | None
    sizes: tuple[int, int]

    @property
    def needs_copy(self) -> bool:
        return self.kernel_hash is not None


@dataclass(frozen=True, slots=True)
class _EntryPlan:
    target: BootTarget
    path: Path
    old: bytes | None
    new: bytes


def _first_line(data: bytes) -> bytes:
    return data.splitlines()[0].rstrip(b"\r") if data.splitlines() else b""


def _entry_refs(data: bytes) -> frozenset[str]:
    refs: set[str] = set()
    for raw_line in data.decode("utf-8", "replace").splitlines():
        fields = raw_line.rstrip("\r").split()
        if not fields or fields[0].casefold() not in ("linux", "initrd"):
            continue
        for raw_path in fields[1:]:
            parts = PurePosixPath(raw_path).parts
            if len(parts) != 6 or parts[0] != "/":
                continue
            if tuple(part.casefold() for part in parts[1:4]) != (
                "efi",
                "dr",
                "kernels",
            ):
                continue
            if parts[5].casefold() not in ("vmlinuz", "initrd.img"):
                continue
            pair_id = parts[4].casefold()
            if _PAIR_ID_RE.fullmatch(pair_id) is not None:
                refs.add(pair_id)
    return frozenset(refs)


def _pair_id(
    version: str,
    kernel_hash: str | None = None,
    initrd_hash: str | None = None,
) -> str:
    if (
        _KERNEL_VERSION_RE.fullmatch(version) is None
        or ".." in version
        or len(version) + 65 > 255
    ):
        raise BootError(f"unsafe kernel version {version!r}")
    if (
        not isinstance(kernel_hash, str)
        or not isinstance(initrd_hash, str)
        or len(kernel_hash) != 64
        or len(initrd_hash) != 64
        or any(char not in "0123456789abcdef" for char in kernel_hash + initrd_hash)
    ):
        raise BootError("kernel and initrd hashes must be lowercase SHA-256")
    pair_hash = hashlib.sha256((kernel_hash + initrd_hash).encode("ascii")).hexdigest()
    return f"{version}-{pair_hash}"


class SdbootBoot:
    """The ESP marker, BLS entries, selectors, and bootctl boundary."""

    name = "systemd-boot"
    supports_oneshot = True

    def __init__(
        self,
        paths: Paths,
        storage: Storage,
        runner: object,
        *,
        filesystem: Filesystem | None = None,
        warn: Callable[[str], None] | None = None,
    ) -> None:
        self.paths = paths
        self.storage = storage
        self.runner = runner
        self.files = filesystem or Filesystem()
        self.warn = warn or (lambda text: None)
        self._managed: frozenset[str] | None = None
        self._inventory_cache: _Inventory | None = None
        self._pair_cache: dict[tuple[str, str], _PairPlan] = {}
        self._entry_cache: dict[str, _EntryPlan] = {}

    def _run(self, argv: list[str]) -> str:
        completed = self.runner.run(argv)
        if completed.returncode != 0:
            detail = completed.stderr.strip() or completed.stdout.strip()
            raise BootError(f"{' '.join(argv)} failed" + (f": {detail}" if detail else ""))
        return completed.stdout

    def _warning(self, message: str) -> None:
        self.warn(message)

    def _managed_names(self) -> frozenset[str]:
        if self._managed is None:
            self._managed = frozenset(
                parsed.name
                for item in self.storage.list()
                if (parsed := ids.parse(item.name)) is not None
            )
        return self._managed

    def _marker(self) -> str | None:
        marker = self.paths.esp_marker
        try:
            status = self.files.lstat(marker)
        except FileNotFoundError:
            return None
        except OSError as error:
            raise Refused(f"cannot inspect bootloader marker {marker}: {error}") from error
        if stat.S_ISLNK(status.st_mode) or not stat.S_ISREG(status.st_mode):
            raise Refused(f"bootloader marker {marker} is not a regular file")
        try:
            value = self.files.read_bytes(marker).decode("utf-8")
        except (OSError, UnicodeError) as error:
            raise Refused(f"cannot read bootloader marker {marker}: {error}") from error
        return value.replace("\r", "").replace("\n", "")

    def _prepare_publication(self) -> None:
        if not self.files.is_directory(self.paths.esp):
            raise Refused(
                f"ESP {self.paths.esp} is missing or not mounted; refusing to publish"
            )
        marker = self._marker()
        if marker is None:
            raise Refused(
                f"bootloader marker {self.paths.esp_marker} is missing; "
                "run install-systemd-boot first"
            )
        if marker != self.name:
            raise BootConfigError(
                f"bootloader marker {self.paths.esp_marker} names {marker!r}, "
                f"not {self.name!r}"
            )

    def install(self) -> None:
        """Install systemd-boot, then write the shared marker and format."""

        if not self.files.is_directory(self.paths.esp):
            raise Refused(f"ESP {self.paths.esp} is missing or not mounted")
        self._run(
            ["bootctl", "install", f"--esp-path={self.paths.esp}", "--no-variables"]
        )
        self.files.mkdir(self.paths.esp_dir)
        self.files.mkdir(self.paths.esp_kernel_dir)
        self.files.mkdir(self.paths.entry_dir)
        self.files.write_atomic(self.paths.esp_marker, b"systemd-boot\n")
        write_esp_format(self.paths)

    def _loader(self, *, strict: bool) -> _Loader | None:
        path = self.paths.loader_conf
        try:
            status = self.files.lstat(path)
        except FileNotFoundError:
            return _Loader((), (), True)
        except OSError as error:
            if strict:
                raise BootConfigError(f"cannot inspect {path}: {error}") from error
            return None
        if not stat.S_ISREG(status.st_mode):
            if strict:
                raise BootConfigError(f"{path} is not a regular file")
            return None
        try:
            raw = self.files.read_bytes(path).decode("utf-8")
        except (OSError, UnicodeError) as error:
            if strict:
                raise BootConfigError(f"cannot read {path}: {error}") from error
            return None
        lines = tuple(line.rstrip("\r") for line in raw.splitlines())
        defaults: list[str] = []
        valid = True
        for line in lines:
            fields = line.split()
            if not fields or fields[0] not in ("default", "timeout"):
                continue
            if fields[0] == "default":
                if len(fields) != 2 or _SELECTOR_RE.fullmatch(fields[1]) is None:
                    valid = False
                else:
                    defaults.append(fields[1])
            elif len(fields) != 2 or not fields[1].isdecimal():
                valid = False
        if strict and not valid:
            raise BootConfigError(f"{path} contains a malformed default or timeout")
        if not valid:
            return _Loader(lines, (), False)
        return _Loader(lines, tuple(defaults), True)

    def _rewrite_loader(self, default_entry: str, current: _Loader | None) -> bytes:
        if _SELECTOR_RE.fullmatch(default_entry) is None:
            raise BootError(f"cannot publish unsafe default entry {default_entry!r}")
        kept = (
            [
                line
                for line in current.lines
                if not line.split() or line.split()[0] not in ("default", "timeout")
            ]
            if current is not None
            else []
        )
        kept.extend((f"default {default_entry}", "timeout 5"))
        return ("\n".join(kept) + "\n").encode("utf-8")

    def _read_efivar(self, name: str, *, strict: bool) -> _EFIVar:
        directory = self.paths.efivars_dir
        try:
            directory_status = self.files.lstat(directory)
        except FileNotFoundError:
            if strict:
                raise BootConfigError("efivarfs is unavailable; the pending selector is unknown")
            return _EFIVar(False, None, False)
        except OSError as error:
            if strict:
                raise BootConfigError(f"cannot inspect {directory}: {error}") from error
            return _EFIVar(True, None, False)
        if not stat.S_ISDIR(directory_status.st_mode):
            if strict:
                raise BootConfigError(f"{directory} is not a directory")
            return _EFIVar(True, None, False)
        path = directory / name
        try:
            status = self.files.lstat(path)
        except FileNotFoundError:
            return _EFIVar(False, None, True)
        except OSError as error:
            if strict:
                raise BootConfigError(f"cannot inspect {path}: {error}") from error
            return _EFIVar(True, None, False)
        if not stat.S_ISREG(status.st_mode):
            if strict:
                raise BootConfigError(f"{path} is not a regular file")
            return _EFIVar(True, None, False)
        try:
            data = self.files.read_bytes(path)
            if len(data) < 4:
                raise UnicodeError("efivar data is shorter than its attributes")
            encoded = data[4:]
            if encoded.startswith(b"\xff\xfe"):
                encoded = encoded[2:]
            value = encoded.decode("utf-16-le").split("\x00", 1)[0]
            value = value.replace("\r", "").replace("\n", "").strip()
        except (OSError, UnicodeError) as error:
            if strict:
                raise BootConfigError(f"cannot decode {name}: {error}") from error
            return _EFIVar(True, None, False)
        return _EFIVar(True, value or None, True)

    def _map_selector(
        self,
        raw: str,
        *,
        strict: bool,
        default: bool,
        label: str,
    ) -> Selector | None:
        if _SELECTOR_RE.fullmatch(raw) is None:
            if strict:
                raise BootConfigError(
                    f"selector {raw!r} is not a canonical systemd-boot entry file"
                )
            if not default:
                self._warning(
                    f"{label} {raw!r} is not a dr-state entry id; "
                    "the pending one-shot is unknown"
                )
                return Selector(raw, None, None, False)
            self._warning(
                f"{label} {raw!r} does not name an existing OS state; "
                "inventory continues without a default label"
            )
            return None
        parsed = ids.parse_entry_id(raw)
        if parsed is not None and parsed.name in self._managed_names():
            return Selector(raw, parsed.name, raw, True)
        lookup = self.files.lookup(self.paths.entry_dir / raw)
        if lookup is not None and stat.S_ISREG(self.files.lstat(lookup).st_mode):
            if strict or not default:
                return Selector(raw, None, raw, True)
        if strict:
            raise BootConfigError(
                f"selector {raw!r} names no existing managed state or entry"
            )
        if default:
            self._warning(
                f"{label} {raw!r} does not name an existing OS state; "
                "inventory continues without a default label"
            )
            return None
        if parsed is None:
            self._warning(
                f"{label} {raw!r} cannot be mapped safely; "
                "the pending one-shot is unknown"
            )
            return Selector(raw, None, None, False)
        return Selector(raw, parsed.name if parsed is not None else None, raw, True)

    def _loader_defaults(self, *, strict: bool) -> tuple[str, ...]:
        loader = self._loader(strict=strict)
        return () if loader is None or not loader.valid else loader.defaults

    def default(self, *, strict: bool) -> Selector | None:
        override = self._read_efivar(DEFAULT_EFIVAR, strict=strict)
        if override.present:
            if override.raw is not None:
                return self._map_selector(
                    override.raw,
                    strict=strict,
                    default=True,
                    label="LoaderEntryDefault",
                )
            if not override.readable:
                # Publication mode treats an unreadable configured default as
                # absent; loader.conf is not a fallback for a value that exists
                # but cannot be read.
                return None
        defaults = self._loader_defaults(strict=strict)
        if not defaults:
            return None
        return self._map_selector(
            defaults[0],
            strict=strict,
            default=True,
            label=f"{self.paths.loader_conf} default",
        )

    def oneshot(self, *, strict: bool) -> Selector | None:
        value = self._read_efivar(ONESHOT_EFIVAR, strict=strict)
        if value.present and value.raw is not None:
            return self._map_selector(
                value.raw,
                strict=strict,
                default=False,
                label="LoaderEntryOneShot",
            )
        if value.readable:
            return None
        if strict:
            raise BootConfigError(
                "cannot read LoaderEntryOneShot; the pending one-shot is unknown"
            )
        self._warning(
            "efivarfs or LoaderEntryOneShot is unreadable; "
            "the pending one-shot is unknown"
        )
        return Selector("", None, None, False)

    def _scan(self) -> _Inventory:
        if self._inventory_cache is not None:
            return self._inventory_cache
        entries: list[_Entry] = []
        for name in self.files.listdir(self.paths.entry_dir):
            if not name.casefold().endswith(".conf"):
                continue
            path = self.paths.entry_dir / name
            try:
                status = self.files.lstat(path)
                if not stat.S_ISREG(status.st_mode):
                    continue
                data = self.files.read_bytes(path)
            except FileNotFoundError:
                continue
            except OSError as error:
                raise BootError(f"cannot read systemd-boot entry {path}: {error}") from error
            parsed = ids.parse_entry_id(name)
            entries.append(
                _Entry(
                    path,
                    name,
                    data,
                    _first_line(data) == ENTRY_MARKER.encode("ascii"),
                    parsed.name if parsed is not None else None,
                    _entry_refs(data),
                )
            )
        pairs: list[_Pair] = []
        for name in self.files.listdir(self.paths.esp_kernel_dir):
            path = self.paths.esp_kernel_dir / name
            try:
                status = self.files.lstat(path)
            except FileNotFoundError:
                continue
            if stat.S_ISDIR(status.st_mode):
                match = _PAIR_ID_RE.fullmatch(name)
                if match is not None and ".." not in name:
                    pairs.append(_Pair(path, name, match.group("version")))
        inventory = _Inventory(tuple(entries), tuple(pairs))
        self._inventory_cache = inventory
        return inventory

    def _fresh_scan(self) -> _Inventory:
        self._inventory_cache = None
        return self._scan()

    def _owned_entries(self, state: str) -> tuple[_Entry, ...]:
        return tuple(
            sorted(
                (
                    entry
                    for entry in self._scan().entries
                    if entry.owned and entry.state == state
                ),
                key=lambda entry: entry.name.encode("ascii", "surrogateescape"),
            )
        )

    def _entry_for_state(self, state: str) -> _Entry | None:
        entries = self._owned_entries(state)
        return entries[0] if entries else None

    def _hash_source(self, path: Path) -> tuple[str, int]:
        digest = hashlib.sha256()
        size = 0
        try:
            with path.open("rb") as stream:
                while chunk := stream.read(1024 * 1024):
                    digest.update(chunk)
                    size += len(chunk)
        except OSError as error:
            raise BootError(f"cannot read kernel payload {path}: {error}") from error
        if size <= 0:
            raise BootError(f"kernel payload {path} is empty")
        return digest.hexdigest(), size

    def _pair_plan(self, target: BootTarget) -> _PairPlan:
        cache_key = (target.state.name, target.kernel.version)
        if cache_key in self._pair_cache:
            return self._pair_cache[cache_key]
        pairs = self._scan().pairs_by_fold()
        kernel_hash, kernel_size = self._hash_source(target.kernel.vmlinuz)
        initrd_hash, initrd_size = self._hash_source(target.kernel.initrd)
        pair_id = _pair_id(target.kernel.version, kernel_hash, initrd_hash)
        existing = pairs.get(pair_id.casefold())
        existing_sizes: tuple[int, int] | None = None
        if existing is not None:
            try:
                copied_kernel_hash, copied_kernel_size = self._hash_source(
                    existing.path / "vmlinuz"
                )
                copied_initrd_hash, copied_initrd_size = self._hash_source(
                    existing.path / "initrd.img"
                )
                if (
                    copied_kernel_hash == kernel_hash
                    and copied_initrd_hash == initrd_hash
                ):
                    existing_sizes = (copied_kernel_size, copied_initrd_size)
            except BootError:
                existing_sizes = None
        if existing_sizes is not None:
            plan = _PairPlan(
                existing.name,
                existing.path,
                target.kernel.vmlinuz,
                target.kernel.initrd,
                None,
                None,
                existing_sizes,
            )
            self._pair_cache[cache_key] = plan
            return plan
        plan = _PairPlan(
            pair_id,
            existing.path if existing is not None else self.paths.esp_kernel_dir / pair_id,
            target.kernel.vmlinuz,
            target.kernel.initrd,
            kernel_hash,
            initrd_hash,
            (kernel_size, initrd_size),
        )
        self._pair_cache[cache_key] = plan
        return plan

    def _entry_text(self, target: BootTarget, pair_id: str) -> bytes:
        if _UUID_RE.fullmatch(target.locator) is None:
            raise BootError(f"unsafe root locator {target.locator!r}")
        pair = _PAIR_ID_RE.fullmatch(pair_id)
        if pair is None or pair.group("version") != target.kernel.version:
            raise BootError(
                f"kernel id {pair_id!r} does not name version {target.kernel.version!r}"
            )
        return (
            f"{ENTRY_MARKER}\n"
            f"title {target.title}\n"
            f"linux /EFI/dr/kernels/{pair_id}/vmlinuz\n"
            f"initrd /EFI/dr/kernels/{pair_id}/initrd.img\n"
            f"options {target.root_args} ro net.ifnames=0 "
            "console=tty0 console=ttyS0,115200\n"
            f"sort-key {target.state.bare}\n"
        ).encode("utf-8")

    def _entry_plan(self, target: BootTarget) -> _EntryPlan:
        if target.state.name in self._entry_cache:
            return self._entry_cache[target.state.name]
        canonical_name = ids.entry_id(target.state)
        if len(canonical_name.encode("ascii")) > 255:
            raise BootError(
                f"state entry id {canonical_name!r} exceeds the ESP filename limit"
            )
        canonical = self.paths.entry_dir / canonical_name
        actual = self.files.lookup(canonical)
        if actual is not None:
            try:
                status = self.files.lstat(actual)
            except OSError as error:
                raise BootError(f"cannot inspect desired entry {actual}: {error}") from error
            if actual.name != canonical_name:
                raise BootError(
                    f"existing ESP name {actual} case-insensitively collides with "
                    f"desired entry {canonical_name}; refusing to overwrite it"
                )
            if not stat.S_ISREG(status.st_mode):
                raise BootError(
                    f"desired BLS entry path {actual} exists but is not a regular file"
                )
            try:
                canonical_data = self.files.read_bytes(actual)
            except OSError as error:
                raise BootError(f"cannot read desired entry {actual}: {error}") from error
            if _first_line(canonical_data) != ENTRY_MARKER.encode("ascii"):
                raise BootError(
                    f"existing BLS entry {actual} is not owned by dr-state; "
                    "refusing to overwrite it"
                )
        pair = self._pair_plan(target)
        chosen = self._entry_for_state(target.state.name)
        path = chosen.path if chosen is not None else canonical
        old = chosen.data if chosen is not None else None
        plan = _EntryPlan(target, path, old, self._entry_text(target, pair.id))
        self._entry_cache[target.state.name] = plan
        return plan

    def payload(self, target: BootTarget) -> list[tuple[str, int]]:
        pair = self._pair_plan(target)
        entry = self._entry_plan(target)
        return [
            (pair.id.casefold(), sum(pair.sizes)),
            (entry.path.name.casefold(), ENTRY_BYTES),
        ]

    def _selector_entry_names(
        self, raw: str, inventory: _Inventory
    ) -> frozenset[str]:
        parsed = ids.parse_entry_id(raw)
        if parsed is None:
            return frozenset()
        return frozenset(
            entry.name
            for entry in inventory.owned_entries
            if entry.state == parsed.name
        )

    def _protected(
        self, inventory: _Inventory
    ) -> tuple[bool, frozenset[str], frozenset[str]]:
        """Return (known one-shot, protected entry names, protected states)."""

        names: set[str] = set()
        states: set[str] = set()
        selectors: list[Selector] = []
        override = self._read_efivar(DEFAULT_EFIVAR, strict=False)
        if override.present and override.raw is not None:
            names.update(self._selector_entry_names(override.raw, inventory))
            mapped = self._map_selector(
                override.raw,
                strict=False,
                default=True,
                label="LoaderEntryDefault",
            )
            if mapped is not None:
                selectors.append(mapped)
        for raw in self._loader_defaults(strict=False):
            names.update(self._selector_entry_names(raw, inventory))
            mapped = self._map_selector(
                raw,
                strict=False,
                default=True,
                label=f"{self.paths.loader_conf} default",
            )
            if mapped is not None:
                selectors.append(mapped)
        pending = self.oneshot(strict=False)
        if pending is not None and pending.known:
            selectors.append(pending)
            names.update(self._selector_entry_names(pending.raw, inventory))
        for selector in selectors:
            parsed = ids.parse_entry_id(selector.entry or selector.raw)
            if parsed is not None and parsed.name in self._managed_names():
                states.add(parsed.name)
        known = pending is None or pending.known
        return known, frozenset(names), frozenset(states)

    def _free_bytes(self) -> int:
        try:
            space = self.files.statvfs(self.paths.esp)
        except OSError as error:
            raise BootError(f"cannot read free space on {self.paths.esp}: {error}") from error
        return int(space.f_bavail * space.f_frsize)

    def capacity(self, keep: Sequence[BootTarget]) -> int:
        """Return the post-shrink allowance for the D19 selection fit."""

        inventory = self._scan()
        keep_states = frozenset(target.state.name for target in keep)
        target_pairs = frozenset(
            self._pair_plan(target).id.casefold() for target in keep
        )
        known, protected_names, protected_states = self._protected(inventory)
        foreign_refs = frozenset().union(
            *(entry.refs for entry in inventory.entries if not entry.owned)
        )
        credit = 0
        for entry in inventory.owned_entries:
            if not known:
                if entry.state in keep_states:
                    credit += ENTRY_BYTES
                continue
            if (
                entry.name in protected_names
                and entry.state is not None
                and entry.state not in keep_states
            ):
                continue
            credit += ENTRY_BYTES
        refs_by_state: dict[str | None, set[str]] = {}
        for entry in inventory.owned_entries:
            refs_by_state.setdefault(entry.state, set()).update(entry.refs)
        protected_refs = frozenset().union(
            *(
                entry.refs
                for entry in inventory.owned_entries
                if entry.name in protected_names
            )
        )
        keep_refs = frozenset().union(
            *(
                entry.refs
                for entry in inventory.owned_entries
                if entry.state in keep_states
            )
        )
        for pair in inventory.pairs:
            folded = pair.name.casefold()
            if folded in foreign_refs:
                continue
            owners = {
                state
                for state, refs in refs_by_state.items()
                if folded in refs
            }
            if not known and any(
                owner is not None and owner not in keep_states for owner in owners
            ):
                continue
            if (
                known
                and folded in protected_refs
                and folded not in keep_refs
                and folded not in target_pairs
            ):
                continue
            try:
                credit += (
                    self.files.lstat(pair.path / "vmlinuz").st_size
                    + self.files.lstat(pair.path / "initrd.img").st_size
                )
            except FileNotFoundError:
                continue
            except OSError as error:
                raise BootError(f"cannot inspect kernel pair {pair.path}: {error}") from error
        return self._free_bytes() + credit - CAPACITY_MARGIN

    def _remove_scratch(self) -> None:
        for directory in (
            self.paths.esp_kernel_dir,
            self.paths.entry_dir,
            self.paths.loader_dir,
            self.paths.esp_dir,
            self.paths.control_dir,
        ):
            for name in self.files.listdir(directory):
                if not name.startswith(SCRATCH_PREFIX):
                    continue
                path = directory / name
                try:
                    status = self.files.lstat(path)
                except FileNotFoundError:
                    continue
                except OSError as error:
                    raise BootError(f"cannot inspect scratch {path}: {error}") from error
                try:
                    if stat.S_ISDIR(status.st_mode) and not stat.S_ISLNK(status.st_mode):
                        self.files.rmtree(path)
                    else:
                        self.files.unlink(path)
                except OSError as error:
                    raise BootError(f"cannot remove scratch {path}: {error}") from error

    def _shrink(
        self,
        inventory: _Inventory,
        *,
        target_entries: frozenset[Path],
        target_pairs: frozenset[str],
    ) -> bool:
        changed = False
        known, protected_entries, _ = self._protected(inventory)
        remaining = list(inventory.entries)
        if known:
            kept_entries: list[_Entry] = []
            for entry in remaining:
                if (
                    entry.owned
                    and entry.path not in target_entries
                    and entry.name not in protected_entries
                ):
                    try:
                        self.files.unlink(entry.path)
                    except FileNotFoundError:
                        pass
                    except OSError as error:
                        raise BootError(
                            f"cannot remove stale entry {entry.path}: {error}"
                        ) from error
                    changed = True
                else:
                    kept_entries.append(entry)
            remaining = kept_entries
        # A target pair survives even when no current entry references it yet.
        referenced = target_pairs | frozenset().union(
            *(entry.refs for entry in remaining)
        )
        for pair in inventory.pairs:
            if pair.name.casefold() in referenced:
                continue
            try:
                self.files.rmtree(pair.path)
            except OSError as error:
                raise BootError(
                    f"cannot remove stale kernel pair {pair.path}: {error}"
                ) from error
            changed = True
        return changed

    def _copy_pair(self, plan: _PairPlan) -> None:
        if plan.kernel_hash is None or plan.initrd_hash is None:
            return
        parent = plan.path.parent
        self.files.mkdir(parent)
        scratch = parent / f"{SCRATCH_PREFIX}{plan.id}"
        if self.files.lookup(scratch) is not None:
            self.files.rmtree(scratch)
        self.files.mkdir(scratch)
        try:
            kernel_hash, kernel_size = self.files.copy_file(
                plan.kernel, scratch / "vmlinuz"
            )
            initrd_hash, initrd_size = self.files.copy_file(
                plan.initrd, scratch / "initrd.img"
            )
            if (
                kernel_hash != plan.kernel_hash
                or initrd_hash != plan.initrd_hash
                or kernel_size != plan.sizes[0]
                or initrd_size != plan.sizes[1]
            ):
                raise BootError(
                    f"kernel payload changed while publishing {plan.kernel} "
                    f"or {plan.initrd}; retry"
                )
            if self.files.lookup(plan.path) is None:
                self.files.replace(scratch, plan.path)
                fsync_directory(parent)
                return
            for name in ("vmlinuz", "initrd.img"):
                self.files.replace(scratch / name, plan.path / name)
            fsync_directory(plan.path)
        except OSError as error:
            raise BootError(f"cannot publish kernel pair {plan.path}: {error}") from error
        finally:
            if self.files.lookup(scratch) is not None:
                try:
                    self.files.rmtree(scratch)
                except OSError:
                    pass

    def _copy_check(
        self,
        pair_plans: Sequence[_PairPlan],
        entry_plans: Sequence[_EntryPlan],
        loader_old: bytes | None,
        loader_new: bytes,
    ) -> None:
        pairs: dict[str, _PairPlan] = {}
        for plan in pair_plans:
            if plan.needs_copy:
                pairs.setdefault(plan.id.casefold(), plan)
        needed = sum(sum(plan.sizes) for plan in pairs.values())
        needed += sum(ENTRY_BYTES for plan in entry_plans if plan.old != plan.new)
        if loader_old != loader_new:
            needed += len(loader_new)
        free = self._free_bytes()
        if needed + CAPACITY_MARGIN > free:
            raise CapacityError(
                f"ESP has too little space after shrink: need {needed} bytes "
                f"plus {CAPACITY_MARGIN} bytes margin, only {free} bytes free; "
                "keeping the shrunken menu"
            )

    def _loader_bytes(self) -> bytes | None:
        try:
            status = self.files.lstat(self.paths.loader_conf)
        except FileNotFoundError:
            return None
        except OSError as error:
            raise BootError(f"cannot inspect {self.paths.loader_conf}: {error}") from error
        if not stat.S_ISREG(status.st_mode):
            raise BootError(f"{self.paths.loader_conf} is not a regular file")
        try:
            return self.files.read_bytes(self.paths.loader_conf)
        except OSError as error:
            raise BootError(f"cannot read {self.paths.loader_conf}: {error}") from error

    def publish(
        self,
        targets: Sequence[BootTarget],
        default: ids.StateId,
        *,
        clear_default_variable: bool = False,
    ) -> None:
        """Publish the targets through shrink, copy-check, and write phases."""

        try:
            self._publish(
                targets,
                default,
                clear_default_variable=clear_default_variable,
            )
        except OSError as error:
            raise BootError(f"cannot publish systemd-boot configuration: {error}") from error
        finally:
            self._managed = None
            self._inventory_cache = None
            self._pair_cache.clear()
            self._entry_cache.clear()

    def _publish(
        self,
        targets: Sequence[BootTarget],
        default: ids.StateId,
        *,
        clear_default_variable: bool,
    ) -> None:
        self._prepare_publication()
        names = tuple(target.state.name for target in targets)
        if default.name not in names:
            raise Refused(f"default {default.name} is not in the published menu")
        if len(set(names)) != len(names):
            raise BootError("systemd-boot target set repeats a state")
        self._managed = None
        self._inventory_cache = None
        self._remove_scratch()
        inventory = self._fresh_scan()
        pair_plans = tuple(self._pair_plan(target) for target in targets)
        entry_plans = tuple(self._entry_plan(target) for target in targets)
        target_entries = frozenset(plan.path for plan in entry_plans)
        target_pairs = frozenset(plan.id.casefold() for plan in pair_plans)
        loader_current = self._loader(strict=False)
        loader_old = self._loader_bytes()
        loader_new = self._rewrite_loader(ids.entry_id(default), loader_current)
        override = self._read_efivar(DEFAULT_EFIVAR, strict=False)
        clear_default = (
            clear_default_variable and override.present and override.readable
        )

        self._shrink(
            inventory,
            target_entries=target_entries,
            target_pairs=target_pairs,
        )
        entry_changes = any(plan.old != plan.new for plan in entry_plans)
        pair_changes = any(plan.needs_copy for plan in pair_plans)
        loader_changes = loader_old != loader_new
        if (
            not entry_changes
            and not pair_changes
            and not loader_changes
            and not clear_default
        ):
            return
        if entry_changes or pair_changes or loader_changes:
            self._copy_check(pair_plans, entry_plans, loader_old, loader_new)
            write_esp_format(self.paths)
            for pair in {
                plan.id.casefold(): plan for plan in pair_plans if plan.needs_copy
            }.values():
                self._copy_pair(pair)
            for plan in entry_plans:
                if plan.old == plan.new:
                    continue
                self.files.mkdir(plan.path.parent)
                self.files.write_atomic(plan.path, plan.new)

            # B-1: loader.conf names the old default until every new entry and pair exists.
            self.files.mkdir(self.paths.loader_conf.parent)
            self.files.write_atomic(self.paths.loader_conf, loader_new)
        if clear_default:
            self._run(["bootctl", "set-default", ""])

        # Only after the new default is effective may D17a remove old-default leftovers.
        self._shrink(
            self._fresh_scan(),
            target_entries=target_entries,
            target_pairs=target_pairs,
        )

    def set_oneshot(self, state: ids.StateId) -> None:
        try:
            self._set_oneshot(state)
        except OSError as error:
            raise BootError(
                f"cannot publish the systemd-boot one-shot: {error}"
            ) from error

    def _set_oneshot(self, state: ids.StateId) -> None:
        self._prepare_publication()
        entry = self._entry_for_state(state.name)
        if entry is None:
            raise BootError(f"state {state.name} has no bootable systemd-boot entry")
        current = self.oneshot(strict=False)
        parsed = (
            ids.parse_entry_id(current.entry or current.raw)
            if current is not None and current.known
            else None
        )
        if parsed is not None and parsed.name == state.name:
            return
        write_esp_format(self.paths)
        self._run(["bootctl", "set-oneshot", ids.entry_id(state)])

    def protected(self) -> frozenset[str]:
        self._loader(strict=True)
        values: set[str] = set()
        override = self._read_efivar(DEFAULT_EFIVAR, strict=True)
        if override.present and override.raw is not None:
            mapped = self._map_selector(
                override.raw,
                strict=True,
                default=True,
                label="LoaderEntryDefault",
            )
            if mapped is not None and mapped.state is not None:
                values.add(mapped.state)
        for raw in self._loader_defaults(strict=True):
            mapped = self._map_selector(
                raw,
                strict=True,
                default=True,
                label=f"{self.paths.loader_conf} default",
            )
            if mapped is not None and mapped.state is not None:
                values.add(mapped.state)
        pending = self.oneshot(strict=True)
        if pending is not None and pending.state is not None:
            values.add(pending.state)
        return frozenset(values)

    def inspect(self) -> Inspection:
        inventory = self._fresh_scan()
        managed = self._managed_names()
        published = frozenset(
            entry.state
            for entry in inventory.owned_entries
            if entry.state is not None
        )
        stale = tuple(
            entry.name
            for entry in inventory.owned_entries
            if entry.state is None or entry.state not in managed
        )
        return Inspection(published, stale, ())
