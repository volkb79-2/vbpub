def test_real_dstdns_fixture_finds_exactly_the_two_real_restrict_foreign_keys():
    """The carve's own central measurement (§9 M3/M4), reproduced against
    the adapter's real output: the pinned dstdns file's only two
    ``ON DELETE RESTRICT`` foreign keys live INSIDE a ``DO $$ ... $$``
    idempotency guard, at source lines 327 and 332. A bare-regex scanner
    over the raw bytes reports 3 (the ``-- ON DELETE RESTRICT`` comment on
    line 99 is a phantom match); a single-level lexer that treats the
    dollar-quoted body as an opaque string literal reports 0 (both real
    sites are invisible without phase-2 recursion)."""
    source = FIXTURE_PATH.read_text(encoding="utf-8")
    sites = ADAPTER.generate_mutation_sites(
        source, _all_lines(source), operators=("sql:weaken-delete-action",), limit=1000
    )
    assert len(sites) == 2
    linenos = sorted(site.lineno for site in sites)
    assert linenos == [327, 332]
    for site in sites:
        assert site.replacement == b"CASCADE"
        assert _span_text(source, site) in (b"RESTRICT",)


def test_real_dstdns_fixture_produces_no_site_for_the_commented_out_occurrence():
    """Source line 99 is ``-- ... ON DELETE RESTRICT, which is the
    invariant that protects history.`` -- a comment, not code. No site of
    ANY operator may be attributed to it."""
    source = FIXTURE_PATH.read_text(encoding="utf-8")
    all_operator_sites = ADAPTER.generate_mutation_sites(
        source,
        _all_lines(source),
        operators=(
            "sql:drop-check",
            "sql:drop-unique",
            "sql:drop-not-null",
            "sql:drop-foreign-key",
            "sql:weaken-delete-action",
            "sql:drop-trigger",
            "sql:widen-check-in",
        ),
        limit=1000,
    )
    assert all(site.lineno != 99 for site in all_operator_sites)


def test_real_dstdns_fixture_produces_a_fully_valid_batch_end_to_end():
    """Every returned site survives :mod:`assay.mutation`'s own real
    validation gate (:func:`assay.mutation.collect_mutation_sites`) -- byte
    bounds, UTF-8 boundaries, no-op detection, identity ordering, and
    duplicate-freedom -- proven by driving the REAL function, not by
    inspecting this adapter's own output in isolation."""
    from assay.mutation import MutationTarget, collect_mutation_sites
    from assay.vocabulary import MUTATION_OPERATORS_BY_LANGUAGE

    source = FIXTURE_PATH.read_text(encoding="utf-8")
