def test_drop_check_replaces_the_whole_check_clause_with_check_true():
    source = "CREATE TABLE t (a INT, CONSTRAINT ck CHECK (a > 0));\n"
    site = _one_site(source, "sql:drop-check")
    assert _span_text(source, site) == b"CHECK (a > 0)"
    assert site.replacement == b"CHECK (true)"
    assert site.lineno == 1


def test_drop_unique_column_form_replaces_bare_unique_with_check_true():
    source = "CREATE TABLE t (email TEXT UNIQUE);\n"
    site = _one_site(source, "sql:drop-unique")
    assert _span_text(source, site) == b"UNIQUE"
    assert site.replacement == b"CHECK (true)"


def test_drop_unique_table_form_replaces_unique_and_its_column_list():
    source = "CREATE TABLE t (a INT, b INT, UNIQUE (a, b));\n"
    site = _one_site(source, "sql:drop-unique")
    assert _span_text(source, site) == b"UNIQUE (a, b)"
    assert site.replacement == b"CHECK (true)"


def test_drop_unique_index_form_replaces_create_unique_index_with_create_index():
    source = "CREATE UNIQUE INDEX idx ON t (a);\n"
    site = _one_site(source, "sql:drop-unique")
    assert _span_text(source, site) == b"CREATE UNIQUE INDEX"
    assert site.replacement == b"CREATE INDEX"


def test_drop_not_null_bare_form_replaces_not_null_with_null():
    source = "CREATE TABLE t (a INT NOT NULL);\n"
    site = _one_site(source, "sql:drop-not-null")
    assert _span_text(source, site) == b"NOT NULL"
    assert site.replacement == b"NULL"


def test_drop_not_null_alter_form_replaces_set_not_null_with_drop_not_null():
    """The mirror of rule 2: this is BOTH the operator's own alter-form span
    AND the paired must-succeed control for rule 4's ``DROP``-preceded
    exclusion below (the near-identical, ``SET``-preceded form is accepted)."""
    source = "ALTER TABLE t ALTER COLUMN a SET NOT NULL;\n"
    site = _one_site(source, "sql:drop-not-null")
    assert _span_text(source, site) == b"SET NOT NULL"
    assert site.replacement == b"DROP NOT NULL"


