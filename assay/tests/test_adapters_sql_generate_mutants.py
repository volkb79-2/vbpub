"""O2/O3 -- ``SqlAdapter.generate_mutation_sites`` (carve
``W3-CARVE-P34-sql-adapter.md`` §3.2, A-281/A-283): the seven operators'
spans and replacements, the five binding lexical context rules (each with
its own paired must-succeed control -- a test proving something is refused
proves nothing unless a sibling proves the near-identical valid form is
accepted), A-281's bounded worst-eviction retention, and the real,
producer-emitted dstdns oracle.

Every fixture below is a small, independently-reasoned, hand-constructed
SQL snippet (never generated by calling :meth:`SqlAdapter.generate_mutation_sites`
first and trusting its own output -- A-041/A-080's own "independent oracle"
discipline): the expected span text, replacement bytes, and line number are
all derived by READING the fixture, not by running the adapter and copying
what it printed.
"""

from __future__ import annotations

from conftest import PROJECT_ROOT

from assay.adapters.sql import SqlAdapter

ADAPTER = SqlAdapter()

FIXTURE_PATH = (
    PROJECT_ROOT
    / "tests"
    / "fixtures"
    / "mutation"
    / "sql"
    / "dstdns-21-create-workflow-corpus.sql"
)


def _all_lines(source: str) -> set[int]:
    return set(range(1, len(source.splitlines()) + 1))


def _one_site(source: str, operator: str):
    sites = ADAPTER.generate_mutation_sites(
        source, _all_lines(source), operators=(operator,), limit=1000
    )
    assert len(sites) == 1, sites
    return sites[0]


def _span_text(source: str, site) -> bytes:
    return source.encode("utf-8")[site.start_byte : site.end_byte]


