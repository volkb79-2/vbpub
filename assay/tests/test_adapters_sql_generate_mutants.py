def test_retention_returns_an_identity_ordered_batch_regardless_of_scan_order():
    """This adapter's own internal scan order is fixed (drop-check first,
    ... widen-check-in last, the operator table's own order) and
    deliberately does NOT match this fixture's byte order: the
    ``widen-check-in`` site sits EARLIER in the file than the
    ``drop-unique`` site, but is scanned LAST internally. The returned
    batch must still be sorted by identity (byte position first)."""
    source = "CREATE TABLE t (\n    k INT CHECK (k IN (1, 2)),\n    email TEXT UNIQUE\n);\n"
    sites = ADAPTER.generate_mutation_sites(
        source,
        _all_lines(source),
        operators=("sql:drop-unique", "sql:widen-check-in"),
        limit=1000,
    )
    assert [site.operator for site in sites] == ["sql:widen-check-in", "sql:drop-unique"]
    assert sites[0].start_byte < sites[1].start_byte
    identities = [site.identity for site in sites]
    assert identities == sorted(identities)


def test_retention_at_limit_one_keeps_the_identity_smallest_site_not_the_scan_first_one():
    """A-281's own strengthened test: the carve's original "limit=1 ->
    exactly one descriptor" wording cannot distinguish a correct bounded
    heap from a per-operator walk that merely stops early (which would
    retain whichever operator's own scan happens to run first --
    ``sql:drop-unique``, scanned before ``sql:widen-check-in`` internally
    -- rather than the identity-smallest candidate)."""
    source = "CREATE TABLE t (\n    k INT CHECK (k IN (1, 2)),\n    email TEXT UNIQUE\n);\n"
    all_lines = _all_lines(source)
    unbounded = ADAPTER.generate_mutation_sites(
        source, all_lines, operators=("sql:drop-unique", "sql:widen-check-in"), limit=1000
    )
    bounded = ADAPTER.generate_mutation_sites(
        source, all_lines, operators=("sql:drop-unique", "sql:widen-check-in"), limit=1
    )
    assert len(bounded) == 1
    assert bounded[0].operator == "sql:widen-check-in"
    assert bounded[0].identity == unbounded[0].identity
    assert bounded[0].start_byte < unbounded[1].start_byte  # the evicted site was the LATER one


