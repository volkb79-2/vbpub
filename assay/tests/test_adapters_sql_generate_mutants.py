def test_rule1_is_not_null_predicate_produces_no_site():
    """Probe: ``IS NOT NULL`` is a predicate inside a CHECK expression, not
    a column constraint -- 35 of 267 code-context occurrences in the real
    corpus (13.1%, carve §9 M12)."""
    source = "CREATE TABLE t (a INT, CHECK (a IS NOT NULL));\n"
    sites = ADAPTER.generate_mutation_sites(
        source, _all_lines(source), operators=("sql:drop-not-null",), limit=1000
    )
    assert sites == ()


def test_rule1_control_bare_not_null_is_still_accepted():
    """Paired must-succeed control for rule 1: the near-identical form
    WITHOUT the ``IS`` predicate is a real column constraint and IS a site
    (same fixture/assertion as the bare-form span test above, restated
    explicitly as this rule's own control)."""
    source = "CREATE TABLE t (a INT NOT NULL);\n"
    site = _one_site(source, "sql:drop-not-null")
    assert site.replacement == b"NULL"


def test_rule2_and_4_set_prefixed_is_rewritten_drop_prefixed_is_refused():
    """Rule 2's probe (accepted, rewritten) and rule 4's probe (A-283,
    refused) side by side, over the SAME two-statement fixture, so the
    contrast is direct: ``SET NOT NULL`` -> ``DROP NOT NULL`` is a real
    site; ``DROP NOT NULL`` (the very text rule 2's own replacement
    emits) produces none, because ``DROP NULL`` is a syntax error."""
    source = (
        "ALTER TABLE t ALTER COLUMN a SET NOT NULL;\n"
        "ALTER TABLE t ALTER COLUMN b DROP NOT NULL;\n"
    )
    sites = ADAPTER.generate_mutation_sites(
        source, _all_lines(source), operators=("sql:drop-not-null",), limit=1000
    )
    assert len(sites) == 1
    assert sites[0].lineno == 1
    assert _span_text(source, sites[0]) == b"SET NOT NULL"
    assert sites[0].replacement == b"DROP NOT NULL"


