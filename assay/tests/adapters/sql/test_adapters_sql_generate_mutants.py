def test_replacement_invariant_is_actually_wired_into_generate_mutation_sites(monkeypatch):
    """None of the seven real scanners can ever construct an unsafe
    replacement (every one is fixed, controlled text), so the filter inside
    :meth:`SqlAdapter.generate_mutation_sites` is unreachable through any
    real SQL input -- proven honestly, by fault injection, rather than left
    untested: a scanner is monkeypatched to emit one deliberately unsafe
    site alongside a real one, and the unsafe one must be dropped while the
    real one survives."""
    import assay.adapters.sql as sql_module

    real_candidates = sql_module._all_candidate_sites

    def _poisoned_candidates(
        source,
        masked,
        dollar_bodies,
        declare_spans,
        *,
        context=None,
        source_identity=None,
        check_deadline=None,
    ):
        sites = list(
            real_candidates(
                source,
                masked,
                dollar_bodies,
                declare_spans,
                context=context,
                source_identity=source_identity,
                check_deadline=check_deadline,
            )
        )
        sites.append(
            sql_module._Site(
                lineno=1,
                operator="sql:drop-check",
                description="poisoned",
                start=0,
                end=1,
                replacement=b"CHECK ($injected)",
            )
        )
        return sites

    monkeypatch.setattr(sql_module, "_all_candidate_sites", _poisoned_candidates)
    source = "CREATE TABLE t (a INT, CONSTRAINT ck CHECK (a > 0));\n"
    sites = ADAPTER.generate_mutation_sites(
        source, _all_lines(source), operators=("sql:drop-check",), limit=1000
    )
    assert all(b"$" not in site.replacement for site in sites)
    assert any(site.replacement == b"CHECK (true)" for site in sites)


def test_bounded_retention_rejects_a_worse_candidate_without_evicting_the_retained_one():
    """The heap-eviction ``elif`` branch's own FALSE arc: a third candidate
    scanned after the heap is already full, whose identity is WORSE than
    the current worst retained entry, must be discarded without touching
    the heap -- distinct from the eviction case above, where the new
    candidate WAS better."""
    source = (
        "CREATE TABLE t (\n"
        "    email TEXT UNIQUE,\n"
        "    a INT NOT NULL,\n"
        "    CONSTRAINT ck CHECK (a > 0)\n"
        ");\n"
    )
    all_lines = _all_lines(source)
    unbounded = ADAPTER.generate_mutation_sites(
        source,
        all_lines,
        operators=("sql:drop-check", "sql:drop-unique", "sql:drop-not-null"),
        limit=1000,
    )
    # scanned in THIS order internally: drop-check (latest byte position),
    # drop-unique (earliest), drop-not-null (middle) -- so the heap fills
    # with drop-check first, drop-unique evicts it (better), and
    # drop-not-null must then be REJECTED (worse than drop-unique) without
    # disturbing the heap.
    assert [site.operator for site in unbounded] == [
        "sql:drop-unique",
        "sql:drop-not-null",
        "sql:drop-check",
    ]
    bounded = ADAPTER.generate_mutation_sites(
        source,
        all_lines,
        operators=("sql:drop-check", "sql:drop-unique", "sql:drop-not-null"),
        limit=1,
    )
    assert len(bounded) == 1
    assert bounded[0].operator == "sql:drop-unique"
    assert bounded[0].identity == unbounded[0].identity


