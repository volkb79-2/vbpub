def test_qualification_schema_finds_exactly_the_three_weaken_delete_sites():
    """The schema's only three delete-action sites: line 19's explicit
    ``NO ACTION``, line 25's ``ON DELETE RESTRICT`` and line 38's
    ``ON DELETE RESTRICT`` INSIDE a ``DO $$ ... $$`` idempotency guard. A
    bare-regex scanner over the raw bytes would also report the ``ON DELETE
    RESTRICT`` in line 2's comment (a phantom match); a single-level lexer
    that treats the dollar-quoted body as an opaque string literal would miss
    line 38 (invisible without phase-2 recursion)."""
    source = FIXTURE_PATH.read_text(encoding="utf-8")
    sites = ADAPTER.generate_mutation_sites(
        source, _all_lines(source), operators=("sql:weaken-delete-action",), limit=1000
    )
    assert sorted(site.lineno for site in sites) == [19, 25, 38]
    for site in sites:
        assert site.replacement == b"CASCADE"
        assert _span_text(source, site) in {b"RESTRICT", b"NO ACTION"}


def test_qualification_schema_produces_no_site_on_a_trap_line():
    """Lines 2 and 3 (a ``--`` and a block comment), 15 (a string literal),
    29 (``DROP NOT NULL``), 32 (an ``IS NOT NULL`` predicate), 50 (a plpgsql
    ``DECLARE`` variable), 52 (``IS NOT NULL`` in a function body), 74
    (``GRANT REFERENCES``), 75 (a ``COMMENT`` string) and 76 (quoted
    identifiers) spell constructs that are not mutation sites: none of the
    seven operators may be attributed to them."""
    source = FIXTURE_PATH.read_text(encoding="utf-8")
    all_operator_sites = ADAPTER.generate_mutation_sites(
        source, _all_lines(source), operators=_ALL_SQL_OPERATORS, limit=1000
    )
    assert len(all_operator_sites) == 24
    assert not {site.lineno for site in all_operator_sites} & {2, 3, 15, 29, 32, 50, 52, 74, 75, 76}


