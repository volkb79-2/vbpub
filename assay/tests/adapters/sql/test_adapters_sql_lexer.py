# --- construct 5: $tag$...$tag$ dollar quote ---------------------------------


def test_bare_dollar_quote_delimiters_are_masked_but_plain_body_is_recovered_as_code():
    """The delimiters (``$$``) are never code and stay masked; the BODY, once
    phase 2 recurses into it, is a plain word sequence with no comment or
    string of its own, so it is recovered as real code, unchanged."""
    source = b"A $$ body text $$ B"
    result = lex_sql(source)
    assert result.dollar_bodies == ((4, 15),)
    assert source[4:15] == b" body text "
    expected = bytearray(source)
    expected[2:4] = b"  "  # opening "$$"
    expected[15:17] = b"  "  # closing "$$"
    assert result.mask == bytes(expected)


def test_named_tag_dollar_quote_delimiters_are_masked_body_recovered_as_code():
    source = b"A $tag$ body text $tag$ B"
    result = lex_sql(source)
    assert result.dollar_bodies == ((7, 18),)
    assert source[7:18] == b" body text "
    expected = bytearray(source)
    expected[2:7] = b"     "  # opening "$tag$"
    expected[18:23] = b"     "  # closing "$tag$"
    assert result.mask == bytes(expected)


def test_dollar_quote_body_containing_the_other_tag_is_not_mistaken_closed():
    """The real hazard this construct exists to defend against: the OUTER
    tag's own closing scan must not stop early at an unrelated dollar-quote
    delimiter appearing inside the body. The body here contains a complete,
    SELF-CLOSING ``$other$ ... $other$`` construct -- phase 1's outer scan
    must skip straight past both occurrences of ``$other$`` and land on the
    real trailing ``$$``, and phase 2's one-level recursion then masks the
    nested construct (its own interior, ``" nested "``, is a body-inside-a-
    body and stays invisible -- the same one-level limit proven directly by
    ``test_a_body_inside_a_body_is_not_recursed_into`` below)."""
    source = b"$$ has $other$ nested $other$ text $$"
    result = lex_sql(source)
    assert result.dollar_bodies == ((2, 35),)
    assert source[2:35] == b" has $other$ nested $other$ text "
    # the outer delimiters are masked
    assert result.mask[0:2] == b"  "
    assert result.mask[35:37] == b"  "
    # code either side of the nested construct is recovered
    assert result.mask[2:7] == source[2:7] == b" has "
    assert result.mask[29:35] == source[29:35] == b" text "
    # the nested "$other$ ... $other$" construct, INCLUDING its own body, is
    # entirely blanked -- a body inside a body is never recursed into
    assert result.mask[7:29] == b" " * 22
    assert b"nested" not in result.mask


def test_positional_parameter_is_not_mistaken_for_a_dollar_quote_opener():
    """``$1`` (a positional parameter) must not open a dollar quote: a
    digit is never a valid dollar-quote tag START byte."""
    source = b"SELECT $1, $2"
    result = lex_sql(source)
    assert result.mask == source
    assert result.dollar_bodies == ()


def test_trailing_bare_dollar_at_eof_is_ordinary_code():
    source = b"SELECT $"
    result = lex_sql(source)
    assert result.mask == source
    assert result.dollar_bodies == ()


def test_tag_broken_by_whitespace_before_its_closing_dollar_is_not_an_opener():
    """``$foo bar$`` -- the identifier scan consumes ``foo``, then hits a
    space (not a valid tag byte) before ever seeing a closing ``$``, so this
    is not a dollar-quote opener at all, and no exception is raised."""
    source = b"A $foo bar$ B"
    result = lex_sql(source)
    assert result.mask == source
    assert result.dollar_bodies == ()


def test_tag_with_no_closing_dollar_anywhere_is_not_an_opener_and_does_not_raise():
    """``$foo`` with no second ``$`` anywhere in the file never even opens a
    tag (the tag-recognition scan itself fails), which is a DIFFERENT case
    from a recognised tag whose BODY never closes (that one raises, tested
    below)."""
    source = b"A $foo"
    result = lex_sql(source)
    assert result.mask == source
    assert result.dollar_bodies == ()


def test_unterminated_dollar_quote_raises_mutation_discovery_error():
    """Unlike the case above, ``$foo$`` IS a recognised, validly-formed
    opening tag; when the identical closing tag never appears anywhere
    later in the file, the construct is genuinely unterminated."""
    with pytest.raises(MutationDiscoveryError):
        lex_sql(b"A $foo$ never closed")


def test_control_a_terminated_named_tag_dollar_quote_does_not_raise():
    lex_sql(b"A $foo$ closed $foo$ B")


