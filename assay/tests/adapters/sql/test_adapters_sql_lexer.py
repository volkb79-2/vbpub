def _line_span(source: bytes, lineno: int) -> tuple[int, int]:
    """The ``(start, end)`` byte offsets of 1-based physical line *lineno*
    in *source* (excluding its own trailing ``\\n``) -- an independent,
    from-scratch line locator built only from ``bytes.split``, never from
    anything :mod:`assay.mutation`/:mod:`assay.adapters.sql_lex` computes,
    so it cannot share a bug with the code under test."""
    lines = source.split(b"\n")
    offset = 0
    for line in lines[: lineno - 1]:
        offset += len(line) + 1
    return offset, offset + len(lines[lineno - 1])


# --- construct 1: -- line comment -------------------------------------------


def test_line_comment_is_masked_to_next_newline():
    source = b"SELECT 1; -- drop everything\nSELECT 2;"
    result = lex_sql(source)
    assert result.mask == b"SELECT 1; " + b" " * len(b"-- drop everything") + b"\nSELECT 2;"


def test_line_comment_at_eof_with_no_trailing_newline_is_masked_to_end():
    source = b"SELECT 1; -- trailing, no newline"
    result = lex_sql(source)
    assert result.mask == b"SELECT 1; " + b" " * len(b"-- trailing, no newline")


# --- construct 2: /* block comment */ (nests) -------------------------------


def test_block_comment_is_masked():
    source = b"A /* comment */ B"
    result = lex_sql(source)
    assert result.mask == b"A " + b" " * len(b"/* comment */") + b" B"


def test_nested_block_comment_is_masked_as_one_construct():
    """PostgreSQL nests ``/* */``, unlike SQL-92: the FIRST ``*/`` does not
    close the comment, only the one matching the outermost ``/*`` does."""
    source = b"A /* outer /* inner */ still-comment */ B"
    result = lex_sql(source)
    assert result.mask == b"A " + b" " * len(b"/* outer /* inner */ still-comment */") + b" B"


def test_unterminated_block_comment_raises_mutation_discovery_error():
    with pytest.raises(MutationDiscoveryError):
        lex_sql(b"A /* never closed")


def test_control_a_terminated_block_comment_does_not_raise():
    """Paired must-succeed control for the unterminated-block-comment probe
    above: the identical construct, properly closed, lexes cleanly."""
    lex_sql(b"A /* closed */ B")


