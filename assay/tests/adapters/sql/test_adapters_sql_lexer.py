def test_backslash_is_not_an_escape_in_a_plain_string():
    """standard_conforming_strings = on (measured, carve §9 M22): a bare
    backslash inside a plain ``'...'`` string is an ordinary character, so
    the string terminates at the very next quote regardless of what
    precedes it."""
    source = b"A 'ends\\' B"
    result = lex_sql(source)
    # The string is `'ends\'` (terminates at the quote right after the
    # backslash); ` B` is real code, unmasked.
    assert result.mask == b"A " + b" " * len(b"'ends\\'") + b" B"


